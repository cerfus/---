-- 0012 · Идентичность вывода включает прогон.
--
-- ДЕФЕКТ. Уникальность по (account_id, content_hash) дедуплицировала выводы
-- ПО СОДЕРЖАНИЮ между прогонами. Вывод, сохранившийся с прошлого раза,
-- оставался за старым run_id, и «текущий прогон» получался неполным:
-- представление insights_current возвращало прежний набор целиком.
--
-- ИСПРАВЛЕНИЕ. Журнал выводов отвечает на вопрос «что система заключила
-- в прогоне X», поэтому прогон входит в идентичность. Повторяющиеся
-- формулировки между прогонами — не дубликаты, а свидетельство того, что
-- вывод сохранился. Идемпотентность не теряется: run_id детерминирован от
-- содержания, поэтому повтор на тех же данных даёт тот же run_id и
-- конфликт по ключу.

ALTER TABLE insights DROP CONSTRAINT uq_insight_content;
ALTER TABLE insights ADD CONSTRAINT uq_insight_run_content
  UNIQUE (account_id, run_id, content_hash);

CREATE INDEX ix_insights_run ON insights(run_id);
