# -*- coding: utf-8 -*-
"""Проверка распознавания номера квартиры. Запуск: python test_ru_numbers.py"""

from ru_numbers import find_apartment

CASES = [
    ("Квартира 200, подтверждение дефектов", 200),
    ("кв.15 стеклопакет", 15),
    ("кв_305_дефект.mp4", 305),
    ("305_кв_дефект", 305),
    ("квартира_412.MOV", 412),
    ("VID-20260314_кв88.mp4", 88),
    ("кв-12-дефект окна", 12),
    ("квартира №101", 101),
    ("видео 2026-03-14 кв 7", 7),
    ("200 квартира", 200),
    ("подтверждение в квартире двести", 200),
    ("квартира двести пятьдесят три", 253),
    ("квартира сто пять, окно на кухне", 105),
    ("Смотрим квартиру номер сорок семь", 47),
    ("квартира пятнадцать", 15),
    ("квартира девяносто девять", 99),
    ("квартира четыреста двадцать один", 421),
    ("двухсотая квартира", 200),
    ("сто двадцать пятая квартира", 125),
    ("пятнадцатая кв", 15),
    ("Итак, квартира двести пятьдесят, смотрим стеклопакет", 250),
    ("подтверждение дефектов квартира сто восемьдесят", 180),
    ("№312", 312),
    # Не должно срабатывать
    ("просто видео без номера", None),
    ("IMG_1234.mp4", None),
    ("кв 30512 мусор", None),
    ("площадь кв м 45", None),
    ("смотрим окно на кухне", None),
]


def main():
    failed = 0
    for text, expected in CASES:
        got = find_apartment(text)[0]
        if got != expected:
            failed += 1
            print("ПЛОХО %-52s ждём=%s получили=%s" % (text, expected, got))
    print("Проверок: %d, провалов: %d" % (len(CASES), failed))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
