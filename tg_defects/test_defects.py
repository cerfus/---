# -*- coding: utf-8 -*-
"""Проверка подсчёта дефектов в подписи. Запуск: python test_defects.py"""

from common import count_defects

CASES = [
    ("66кв  1об- стп1,2", 2),
    ("Кв 60  Об1-стп1,2 Об2-стп 1", 3),
    ("КВ 63  Об1 стп 1 Об2 стп 1,2", 3),
    ("КВ 142  Об1 стп 1,2 Об2 стп 1,2", 4),
    ("квартира 65 об1 стп1 - 1,5 об1 стп2 - 1 общий:2,5", 2),
    ("Квартира 67 Об1 стп 1 -1.5 Об1 стп 2 -1 Об2 стп 1 -1.5 Об2 стп 2 -1 Общ 5", 4),
    ("Квартира 68 Об1 стп 1 -0.3 Об1 стп 2 -1 Об2 стп 1 -1.5 Общ 2.8", 3),
    ("5 этаж квартира 75 об1 стп2-1 общий:1", 1),
    ("178кв об2сп1", 1),
    ("Кв 102 об1 сп2", 1),
    # Без перечня дефектов считаем, что видео одно
    ("кв 134 2/1", 1),
    ("", 1),
]


def main():
    failed = 0
    for text, expected in CASES:
        got = count_defects(text)
        if got != expected:
            failed += 1
            print("ПЛОХО %-58s ждём=%s получили=%s" % (text[:58], expected, got))
    print("Проверок: %d, провалов: %d" % (len(CASES), failed))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
