# -*- coding: utf-8 -*-
"""Проверка достройки видео по подписям. Запуск: python test_spread.py"""

from sort_export import fill_backwards, spread_by_caption


def видео(подпись="", квартира=None, как="подпись", текст=None):
    """текст — то, откуда взялся номер: подпись видео или соседнее сообщение."""
    return {"подпись": подпись, "квартира": квартира, "путь": "x.mp4",
            "как": как if квартира else "не определено",
            "текст": подпись if текст is None else текст}


def прогнать(items):
    items = spread_by_caption(items)
    items, _ = fill_backwards(items)
    return [i["квартира"] for i in items]


CASES = [
    # Подпись первым сообщением: "Об1 стп1,2" — два дефекта, значит два видео
    ("подпись впереди, 2 дефекта",
     [видео("кв 65 об1 стп1,2", 65), видео()],
     [65, 65]),
    # Четыре дефекта — четыре видео
    ("подпись впереди, 4 дефекта",
     [видео("кв 67 об1 стп1,2 об2 стп1,2", 67), видео(), видео(), видео()],
     [67, 67, 67, 67]),
    # Достройка не должна залезать на следующую квартиру
    ("счётчик не пускает на соседа",
     [видео("кв 65 об1 стп1,2", 65), видео(), видео(),
      видео("кв 70 об1 стп1", 70)],
     [65, 65, None, 70]),
    # Подпись последним сообщением: добираем назад ровно недобор
    ("подпись позади",
     [видео(), видео(), видео("кв 45 об1 стп1,2 об2 стп1", 45)],
     [45, 45, 45]),
    # Назад берём ровно недостающее: 2 дефекта = 2 видео, лишнее не трогаем
    ("назад — только сколько обещано",
     [видео(), видео(), видео(), видео("кв 76 об1 стп1,2", 76)],
     [None, None, 76, 76]),
    # Две подписи одной квартиры складываются
    ("две подписи одной квартиры",
     [видео("кв 69 об1 стп1,2", 69), видео("кв 69 об2 стп2", 69), видео()],
     [69, 69, 69]),
    # Без подписей ничего не выдумываем
    ("нет подписей — нет догадок",
     [видео(), видео()],
     [None, None]),
    # Номер из соседнего сообщения — такое же обещание, как подпись
    ("номер из соседнего сообщения",
     [видео(квартира=65, как="соседнее сообщение (цифры)",
            текст="квартира 65 об1 стп1 - 1,5 об1 стп2 - 1"),
      видео()],
     [65, 65]),
]


def проверить_обещания():
    """Обещания считаются и по подписи, и по соседнему сообщению."""
    from sort_export import promised_counts
    items = [
        видео(квартира=65, как="соседнее сообщение (цифры)",
              текст="квартира 65 об1 стп1 - 1,5 об1 стп2 - 1"),   # 2 дефекта
        видео("Квартира 65 Об2 стп 1 -1.5 Об2 стп 2 -1", 65),      # ещё 2
        видео(квартира=65, как="достроено по подписи кв 65"),      # не обещает
    ]
    got = promised_counts(items)
    if got != {65: 4}:
        print("ПЛОХО обещания: ждём {65: 4}, получили %s" % got)
        return 1
    return 0


def main():
    failed = 0
    for name, items, expected in CASES:
        got = прогнать(items)
        if got != expected:
            failed += 1
            print("ПЛОХО %-34s ждём=%s получили=%s" % (name, expected, got))
    failed += проверить_обещания()
    print("Проверок: %d, провалов: %d" % (len(CASES) + 1, failed))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
