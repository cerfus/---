# -*- coding: utf-8 -*-
"""Проверка чтения .env. Запуск: python test_settings.py

Главное здесь — что заданное окружение сильнее файла. Иначе однажды
.env с чьего-то ноутбука перебьёт настройки на сервере, и никто не
поймёт, почему бот ходит не в ту базу.

Все случаи работают с временным файлом и выдуманными именами переменных,
так что настоящий .env рядом с тестом ничему не мешает.
"""

import os
import shutil
import tempfile

import console          # noqa: F401
import settings

# Имена нарочно такие, каких не бывает ни в окружении, ни в .env.
ИМЯ = "CHAT_COACH_ПРОВЕРКА_1"
ВТОРОЕ = "CHAT_COACH_ПРОВЕРКА_2"


def _файл(текст, кодировка="utf-8"):
    """Пишет .env во временную папку. Возвращает путь и саму папку."""
    папка = tempfile.mkdtemp()
    путь = os.path.join(папка, ".env")
    with open(путь, "wb") as fh:
        fh.write(текст.encode(кодировка))
    return путь, папка


def _чисто():
    for имя in (ИМЯ, ВТОРОЕ):
        os.environ.pop(имя, None)


def случай_окружение_главнее():
    """Заданное снаружи не перетирается файлом.

    Ради этого правила всё и написано так: «set» в консоли и env_file
    в докере должны оставаться главнее, а .env работать только там, где
    переменной ещё нет.
    """
    путь, папка = _файл("%s=из_файла\n%s=тоже_из_файла\n" % (ИМЯ, ВТОРОЕ))
    try:
        _чисто()
        os.environ[ИМЯ] = "из_окружения"
        подхваченные = settings.подхватить(путь)
        ок = (os.environ[ИМЯ] == "из_окружения"
              and os.environ[ВТОРОЕ] == "тоже_из_файла"
              and подхваченные == [ВТОРОЕ])
        return ок, ("окружение главнее: %s=%s, подхвачено %s"
                    % (ИМЯ, os.environ[ИМЯ], подхваченные))
    finally:
        _чисто()
        shutil.rmtree(папка, ignore_errors=True)


def случай_подхватывает():
    """Чего в окружении нет — то берётся из файла."""
    путь, папка = _файл("%s=sk-ant-выдуманный\n" % ИМЯ)
    try:
        _чисто()
        подхваченные = settings.подхватить(путь)
        ок = (os.environ.get(ИМЯ) == "sk-ant-выдуманный"
              and подхваченные == [ИМЯ] and ВТОРОЕ not in os.environ)
        return ок, "подхват: %s=%s" % (ИМЯ, os.environ.get(ИМЯ))
    finally:
        _чисто()
        shutil.rmtree(папка, ignore_errors=True)


def случай_значений_не_возвращает():
    """Возвращаются имена, и только имена.

    Это не придирка: возвращённое печатает бот при запуске, и ключ,
    попавший в журнал, — тот же ключ, что утёк.
    """
    секрет = "sk-ant-ОЧЕНЬ-СЕКРЕТНО"
    путь, папка = _файл("%s=%s\n" % (ИМЯ, секрет))
    try:
        _чисто()
        подхваченные = settings.подхватить(путь)
        ок = (подхваченные == [ИМЯ]
              and all(секрет not in кусок for кусок in подхваченные))
        return ок, "вернулось: %s" % подхваченные
    finally:
        _чисто()
        shutil.rmtree(папка, ignore_errors=True)


def случай_нет_файла():
    """Нет .env — пустой список, а не исключение на импорте."""
    папка = tempfile.mkdtemp()
    try:
        подхваченные = settings.подхватить(os.path.join(папка, ".env"))
        return подхваченные == [], "нет файла: %s" % подхваченные
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_мусорные_строки():
    """Комментарии, пустые строки и строка без «=» пропускаются."""
    путь, папка = _файл("# комментарий\n\n   \nпросто слово\n"
                        "%s=значение\n" % ИМЯ)
    try:
        _чисто()
        подхваченные = settings.подхватить(путь)
        ок = подхваченные == [ИМЯ] and os.environ.get(ИМЯ) == "значение"
        return ок, "мусор: подхвачено %s" % подхваченные
    finally:
        _чисто()
        shutil.rmtree(папка, ignore_errors=True)


def случай_export():
    """«export KEY=...» — привычка из шелла, префикс снимаем."""
    разбор = settings.разобрать_строку("export %s=значение" % ИМЯ)
    return разбор == (ИМЯ, "значение"), "export: %s" % (разбор,)


def случай_кавычки():
    """Кавычки вокруг значения снимаются, одинокая остаётся частью ключа."""
    двойные = settings.разобрать_строку('%s="значение"' % ИМЯ)
    одинарные = settings.разобрать_строку("%s='значение'" % ИМЯ)
    одна = settings.разобрать_строку('%s="значение' % ИМЯ)
    ок = (двойные == (ИМЯ, "значение") and одинарные == (ИМЯ, "значение")
          and одна == (ИМЯ, '"значение'))
    return ок, "кавычки: %s / %s / %s" % (двойные, одинарные, одна)


def случай_равно_внутри_значения():
    """Режем по первому «=»: в ключах base64 равно встречается запросто."""
    разбор = settings.разобрать_строку("%s=sk-ant-a=b==" % ИМЯ)
    return разбор == (ИМЯ, "sk-ant-a=b=="), "равно внутри: %s" % (разбор,)


def случай_решётка_и_пробелы():
    """Решётка внутри значения — не комментарий, а пробелы по краям срезаны.

    Пробел, случайно прилипший к концу токена при копировании, — это
    отказ авторизации без единого объяснения, искать такое можно долго.
    """
    решётка = settings.разобрать_строку("%s=abc#def" % ИМЯ)
    пробелы = settings.разобрать_строку("  %s =  значение  " % ИМЯ)
    ок = решётка == (ИМЯ, "abc#def") and пробелы == (ИМЯ, "значение")
    return ок, "решётка и пробелы: %s / %s" % (решётка, пробелы)


def случай_блокнот():
    """Файл, сохранённый блокнотом обоими способами, читается.

    По умолчанию блокнот пишет UTF-8 с меткой в начале — без utf-8-sig
    к имени первой переменной прилипал бы невидимый символ, и бот говорил
    бы «не задан BOT_TOKEN» человеку, который смотрит прямо на эту строку.
    А «ANSI» — это cp1251, и на русском комментарии чтение в UTF-8 падало
    вовсе.
    """
    с_меткой, папка1 = _файл("%s=значение\n" % ИМЯ, кодировка="utf-8-sig")
    ansi, папка2 = _файл("# русский комментарий\n%s=значение\n" % ИМЯ,
                         кодировка="cp1251")
    try:
        _чисто()
        первое = settings.подхватить(с_меткой)
        _чисто()
        второе = settings.подхватить(ansi)
        ок = (первое == [ИМЯ] and второе == [ИМЯ]
              and os.environ.get(ИМЯ) == "значение")
        return ок, "блокнот: с меткой %s, ansi %s" % (первое, второе)
    finally:
        _чисто()
        shutil.rmtree(папка1, ignore_errors=True)
        shutil.rmtree(папка2, ignore_errors=True)


def main():
    случаи = (случай_окружение_главнее, случай_подхватывает,
              случай_значений_не_возвращает, случай_нет_файла,
              случай_мусорные_строки, случай_export, случай_кавычки,
              случай_равно_внутри_значения, случай_решётка_и_пробелы,
              случай_блокнот)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
