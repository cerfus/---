def _выгрузка(куда):
    """Кладёт настоящий по форме result.json и возвращает путь."""
    чат, курсор = образцы.тёплый(образцы.СТАРТ, 5)
    хвост, _ = образцы.холодный(курсор + timedelta(hours=10), 5)
    данные = {"name": "Аня", "type": "personal_chat", "messages": [
        {"id": номер, "type": "message",
         "date": с["дата"].strftime("%Y-%m-%dT%H:%M:%S"),
         "from": с["автор"], "text": с["текст"]}
        for номер, с in enumerate(чат + хвост, 1)]}
    путь = os.path.join(куда, "result.json")
    with open(путь, "w", encoding="utf-8") as fh:
        json.dump(данные, fh, ensure_ascii=False)
    return путь


def случай_весь_путь():
    """От файла до готовых текстов — без единого падения."""
    папка = tempfile.mkdtemp()
    try:
        сообщения = parser.read_export(_выгрузка(папка))
        двое, групповой = parser.two_sides(сообщения)
        я, она = "Иван", "Аня"
        итог = metrics.analyse(сообщения, я, она)
        отчёт = report.текст_отчёта(итог)

        отобранное = analysis.выборка(сообщения, я, она)
        ответ = analysis.Разбор(
            коротко="Общение держится на тебе.",
            что_работает=["не навязываешься с вопросами"],
            что_мешает=[analysis.Совет(что_не_так="пишешь дважды подряд",
                                       цитата="может увидимся",
                                       как_лучше="Свободна в субботу?")],
            следующий_шаг="Напиши одно сообщение и дождись ответа.",
            стоп_сигнал=False, стоп_причина="")
        клиент = заглушки.ЗаглушкаКлиента(
            заглушки.ЗаглушкаОтвета(parsed_output=ответ))
        разбор = analysis.разобрать(None, итог, "позвать на свидание",
                                    клиент=клиент, отобранное=отобранное)
        текст = analysis.текст_разбора(разбор)

        ок = (not групповой
              and "ИНДЕКС" in отчёт
              and "Общение держится на тебе." in текст
              and "Свободна в субботу?" in текст
              and итог["индекс"] is not None)
        return ок, "путь: индекс=%s, отчёт %d симв., разбор %d симв." % (
            итог["индекс"], len(отчёт), len(текст))
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_нарезка():
    """Длинный отчёт режется на куски, влезающие в сообщение Телеграма."""
    длинный = "\n".join("строка %d %s" % (номер, "я" * 60) for номер in range(400))
    куски = bot._нарезать(длинный)
    ок = (len(куски) > 1
          and all(len(кусок) <= bot.ПРЕДЕЛ_СООБЩЕНИЯ for кусок in куски)
          and "".join(куски).count("строка") == 400)
    return ок, "нарезка: кусков=%d, самый длинный=%d" % (
        len(куски), max(len(к) for к in куски))


def случай_нарезка_края():
    """Пустой текст не шлём вовсе, одну строку не режем, длинную — рубим."""
    пусто = bot._нарезать("   \n\n  ")
    одна = bot._нарезать("коротко")
    сплошная = bot._нарезать("ю" * (bot.ПРЕДЕЛ_СООБЩЕНИЯ * 2 + 5))
    ок = (пусто == [] and одна == ["коротко\n"]
          and len(сплошная) == 3
          and all(len(кусок) <= bot.ПРЕДЕЛ_СООБЩЕНИЯ for кусок in сплошная))
    return ок, "края: пусто=%s одна=%s сплошная=%d кусков" % (
        пусто, одна, len(сплошная))


def случай_имя_файла():
    """Имя файла от пользователя не должно уводить запись из временной папки.

    Папку берём настоящую, а склеиваем и сравниваем через os.sep: с жёстко
    прописанным «/tmp/выгрузки» и «/» проверка падала на Windows даже для
    безобидного result.json — abspath дописывает букву диска и меняет
    разделитель, так что совпасть не могло ничего.
    """
    проверки = [
        ("result.json", "result.json"),
        ("../../etc/passwd.json", "passwd.json"),
        (r"..\..\windows\система.json", "система.json"),
        (".скрытый.json", "скрытый.json"),
        ("", "выгрузка"),
        (None, "выгрузка"),
    ]
    плохие = [(было, bot._безопасное_имя(было))
              for было, ждём in проверки if bot._безопасное_имя(было) != ждём]

    корень = os.path.abspath(tempfile.mkdtemp())
    try:
        ушёл = [имя for имя, _ in проверки
                if not os.path.abspath(
                    os.path.join(корень, bot._безопасное_имя(имя))
                ).startswith(корень + os.sep)]
    finally:
        shutil.rmtree(корень, ignore_errors=True)

    ок = not плохие and not ушёл
    return ок, "имя файла: сломалось %s, ушло из папки %s" % (плохие, ушёл)


