def случай_имена_команд():
    """Имена команд должны проходить правило Телеграма.

    Оно жёсткое: строчная латиница, цифры и подчёркивание, 1-32 символа.
    Кириллическое имя BotFather не примет вовсе — а значит, у команды
    не будет ни меню, ни автодополнения, и для всех, кроме автора, её
    просто нет. Ровно на этом и споткнулись: /удалить обещана в первом
    же приветствии, а увидеть её было негде.
    """
    правило = re.compile(r"^[a-z0-9_]{1,32}$")
    имена = [имя for имя, _синоним, _описание in texts.КОМАНДЫ]
    имена.append(texts.КОМАНДА_ВОЗВРАТА[0])
    кривые = [имя for имя in имена if not правило.match(имя)]
    описания = [о for _и, _с, о in texts.КОМАНДЫ]
    ок = (not кривые and len(имена) == len(set(имена))
          and all(3 <= len(о) <= 256 for о in описания)
          # Возврат — админская, в общем меню ей делать нечего.
          and texts.КОМАНДА_ВОЗВРАТА[0] not in
          [и for и, _с, _о in texts.КОМАНДЫ])
    return ок, "имена команд: кривые=%s" % (кривые or "нет")


def случай_синонимы_команд():
    """Латинское имя и русский синоним ведут в один обработчик."""
    async def проверить():
        плохие = []
        for латиница, кириллица, _описание in texts.КОМАНДЫ:
            фильтр = bot._команда(латиница)
            for текст in ("/" + латиница, "/" + кириллица):
                if not await фильтр(_письмо(текст), bot=None):
                    плохие.append(текст)
            # Обрубок командой быть не должен.
            if await фильтр(_письмо("/" + латиница[:2]), bot=None):
                плохие.append("обрубок /" + латиница[:2])
        return плохие
    плохие = asyncio.run(проверить())
    return not плохие, "синонимы: не сработало %s" % (плохие or "ничего")


def случай_меню_собирается():
    """Меню строится из того же списка и принимается типом BotCommand."""
    from aiogram.types import BotCommand
    меню = [BotCommand(command=имя, description=описание)
            for имя, _синоним, описание in texts.КОМАНДЫ]
    ок = (len(меню) == len(texts.КОМАНДЫ)
          and [к.command for к in меню]
          == [и for и, _с, _о in texts.КОМАНДЫ])
    return ок, "меню: %s" % [к.command for к in меню]


class Ловушка:
    """Ловит то, что бот отправил бы в Телеграм."""

    def __init__(self):
        self.отправленные = []

    async def answer(self, текст, reply_markup=None):
        self.отправленные.append(текст)


def случай_нарезка_разметки():
    """Готовый HTML режется по границам блоков, а не по символам.

    Разорванный между сообщениями тег Телеграм не примет — откажется
    от обоих кусков, и человек не увидит отчёта вовсе. Дёргаем
    настоящую функцию бота, а не её пересказ: пересказ разойдётся
    с оригиналом при первой же правке.
    """
    блоки = ["<b>шапка</b>", "<i>середина</i>", "<b>ещё</b>", "<i>хвост</i>"]
    блоки = блоки * 120                      # заведомо больше одного сообщения
    ловушка = Ловушка()
    asyncio.run(bot._послать_разметкой(ловушка, блоки))

    влезли = all(len(с) <= bot.ПРЕДЕЛ_СООБЩЕНИЯ
                 for с in ловушка.отправленные)
    целы = all(с.count("<b>") == с.count("</b>")
               and с.count("<i>") == с.count("</i>")
               for с in ловушка.отправленные)
    всё = "".join(ловушка.отправленные)
    ок = (len(ловушка.отправленные) > 1 and влезли and целы
          and всё.count("<b>шапка</b>") == 120)
    return ок, "нарезка: сообщений %d, влезли=%s теги целы=%s" % (
        len(ловушка.отправленные), влезли, целы)


def случай_громоздкий_блок():
    """Блок длиннее предела уходит без разметки, а не пропадает.

    Резать его по границам блоков нечем, а по символам нельзя: тег
    разорвётся. Потерять оформление лучше, чем потерять текст —
    сообщение сверх предела Телеграм просто отвергнет.
    """
    громадный = "<pre>" + "строка\n" * 900 + "</pre>"
    ловушка = Ловушка()
    asyncio.run(bot._послать_разметкой(ловушка, ["<b>шапка</b>", громадный]))
    влезли = all(len(с) <= bot.ПРЕДЕЛ_СООБЩЕНИЯ
                 for с in ловушка.отправленные)
    всё = "".join(ловушка.отправленные)
    ок = (влезли and "<pre>" not in всё
          and всё.count("строка") == 900 and "<b>шапка</b>" in всё)
    return ок, "громоздкий: сообщений %d, влезли=%s, строк %d" % (
        len(ловушка.отправленные), влезли, всё.count("строка"))


