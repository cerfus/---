# База должна лечь во временную папку: bot.py создаёт её при импорте.
_ВРЕМЕННАЯ = tempfile.mkdtemp(prefix="chat_coach_тест_")
os.environ.setdefault("CHAT_COACH_DB", os.path.join(_ВРЕМЕННАЯ, "бот.sqlite3"))

import console          # noqa: F401
