def случай_накопитель():
    """Вставку шлют несколькими сообщениями — они должны склеиться в одну."""
    по_одному = [len(bot._собрать_куски(КУСКИ[:сколько])[0])
                 for сколько in (1, 2, 3)]
    всё, явная = bot._собрать_куски(КУСКИ)
    авторы = {с["автор"] for с in всё}
    # Каждый новый кусок добавляет сообщений, а не начинает счёт заново.
    растёт = по_одному == sorted(по_одному) and по_одному[0] < по_одному[-1]
    ок = (растёт and len(всё) == 11 and авторы == {"Аня", "Иван"}
          and явная is False)
    return ок, "накопитель: по кускам %s, итого %d" % (по_одному, len(всё))


def случай_вставка_в_отчёт():
    """Вставленный кусок доходит до отчёта и честно говорит о пробелах."""
    сообщения, _ = bot._собрать_куски(КУСКИ)
    итог = metrics.analyse(сообщения, "Иван", "Аня")
    текст = report.текст_отчёта(итог)
    пропущено = {имя for имя, _ in metrics.не_посчитано(итог)}
    ок = ("ИНДЕКС" in текст
          and ("Не посчитано" in текст) == bool(пропущено)
          and итог["индекс"] is not None)
    return ок, "вставка в отчёт: индекс=%s, не посчитано %s" % (
        итог["индекс"], sorted(пропущено) or "ничего")


def случай_вставка_не_съедает_вопрос():
    """Короткий вопрос остаётся вопросом, а не уходит в разбор."""
    вопросы = ["что ей написать?", "а если она не ответит",
               "сколько ждать перед следующим сообщением"]
    спутано = [в for в in вопросы
               if parser.похоже_на_переписку(в, bot.МИНИМУМ_ВСТАВКИ)[0]]
    переписка, _ = parser.похоже_на_переписку("\n".join(КУСКИ),
                                              bot.МИНИМУМ_ВСТАВКИ)
    ок = not спутано and переписка is not None
    return ок, "разделение: спутано %s" % (спутано or "ничего")


def случай_предел_накопителя():
    """Потолок накопителя реальный, а не на словах."""
    ок = (bot.ПРЕДЕЛ_КУСКОВ > 0 and bot.ПРЕДЕЛ_ВСТАВКИ >= 10 * 1024
          and bot.МИНИМУМ_ВСТАВКИ < bot.МИНИМУМ_СООБЩЕНИЙ)
    return ок, "пределы: кусков %d, байт %d, минимум вставки %d" % (
        bot.ПРЕДЕЛ_КУСКОВ, bot.ПРЕДЕЛ_ВСТАВКИ, bot.МИНИМУМ_ВСТАВКИ)


def main():
    случаи = (случай_весь_путь, случай_нарезка, случай_нарезка_края,
              случай_имя_файла, случай_обработчики, случай_накопитель,
              случай_вставка_в_отчёт, случай_вставка_не_съедает_вопрос,
              случай_предел_накопителя)
    провалов = 0
    try:
        for случай in случаи:
            ок, описание = случай()
            if not ок:
                провалов += 1
                print("ПЛОХО  %s" % описание)
        print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
        return 1 if провалов else 0
    finally:
        shutil.rmtree(_ВРЕМЕННАЯ, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
