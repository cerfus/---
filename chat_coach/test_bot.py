"""Сквозная проверка: файл -> цифры -> разбор -> текст для Телеграма.

Запуск: python test_bot.py

Ни Телеграма, ни сети: модель подменяется заглушкой, токен не нужен.
Смысл проверки — что модули стыкуются друг с другом, а не каждый сам
по себе, и что длинный отчёт корректно режется на сообщения.
"""

import json
