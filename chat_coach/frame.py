# -*- coding: utf-8 -*-
"""
Рамка разговора: что это вообще за переписка.

Индекс вовлечённости меряет ровно одно — ухаживание. Он спрашивает, идёт
ли она навстречу, и по-другому спрашивать не умеет. Пока переписка и
правда про это, всё честно. А стоит принести дружескую — и тот же индекс
выдаёт «18 из 100, встречного интереса почти не видно» про подругу,
которая просто подруга. Арифметика верна, вывод мимо, и человек уходит
с неправдой.

Поэтому прежде, чем показывать цифры, отвечаем на вопрос попроще: что
здесь происходит. Считается на голом питоне — без ключа, без сети и без
денег, то есть работает и на бесплатном тарифе, где сейчас никакой
защиты нет вовсе.

Отдельная забота — отказ. Сейчас поймать его может только модель
(`стоп_сигнал` в analysis.py), а значит, без ключа человек получает
падающий тренд и ни слова о том, что вопрос уже закрыт. Слова «нет,
спасибо» и «давай останемся друзьями» в питоне видны не хуже.

Главное правило этого модуля: показывать улику, а не выносить приговор.
На каждый отказ сохраняется цитата и дата — человек сам увидит, о чём
речь, и ложное срабатывание останется проверяемым, а не превратится
в обвинение.
"""

import re
from datetime import datetime, timedelta

import metrics

# Типы переписки. Порядок здесь же и есть порядок разбора: первый
# сработавший выигрывает.
ОТКАЗ = "отказ"
СОВЕТЧИЦА = "советчица"
ЗАГЛОХЛО = "заглохло"
ДРУЖБА = "дружба"
ОБЩАЕТЕСЬ = "общаетесь"
УХАЖИВАНИЕ = "ухаживание"

# Без двоеточий внутри: строка в отчёте уже начинается с «Что это за
# переписка:», и второе подряд читается спотыкаясь.
НАЗВАНИЯ = {
    ОТКАЗ: "здесь уже прозвучал отказ",
    СОВЕТЧИЦА: "дружеское общение — она обсуждает с тобой третьего человека",
    ЗАГЛОХЛО: "переписка заглохла",
    ДРУЖБА: "вы много общаетесь, и это похоже на дружбу",
    ОБЩАЕТЕСЬ: "вы общаетесь примерно на равных",
    УХАЖИВАНИЕ: "ухаживание, навстречу идёшь ты",
}

# Сколько молчания считать концом переписки.
ТИШИНА = timedelta(days=14)
# Насколько должен просесть тренд, чтобы это была не рябь, а затухание.
ПАДЕНИЕ = 15
# Быстрее часа отвечают друг другу те, кто общается, а не терпит.
БЫСТРО = 3600

# Дружба. Прочитанная живая переписка: 4994 сообщения за 93 дня — это
# 54 в день, медианы ответа пять и шесть секунд, три месяца подряд.
# И при этом про чувства и встречи — 40 реплик из 4576, меньше процента,
# и почти все про третьих лиц. Бот называл это «интерес прохладный:
# отвечает, но навстречу не идёт» — про человека, который отвечает
# за пять секунд полсотни раз в день.
#
# Условий четыре, и нужны все. Темп и скорость без последнего условия
# съели бы настоящее ухаживание: оно тоже бывает быстрым и частым.
# Отличает дружбу именно отсутствие романтической линии на дистанции.
ТЕМП_ДРУЖБЫ = 30        # сообщений в день
ДНЕЙ_ДРУЖБЫ = 14        # на такой дистанции темп уже не случайность
БЫСТРО_ОБА = 300        # обе медианы быстрее пяти минут
ДОЛЯ_РОМАНТИКИ = 0.02   # выше — это уже не «просто общаемся»


# --------------------------------------------------------------------------
# Отказ
# --------------------------------------------------------------------------

# Список нарочно узкий — той же дисциплины, что _ВОПРОС_СЛОВОМ в metrics.py.
# Приписать человеку отказ, которого не было, хуже, чем не заметить отказ:
# в первом случае мы врём, во втором просто молчим. Поэтому каждый оборот
# требует, чтобы он был обращён к собеседнику, а не сказан о ком-то третьем:
# «не пиши ей пока» — это совет, а не «не пиши мне».
_ОТКАЗЫ = (
    ("не пиши мне",
     r"не\s+пиши\s+(?:мне|сюда|больше)\b|не\s+надо\s+(?:мне\s+)?писать"),
    ("нет, спасибо",
     r"^\s*нет[,\s!.]*спасибо[.!)\s]*$"),
    ("останемся друзьями",
     r"останемся\s+(?:просто\s+|только\s+)?друзьями"),
    ("ты мне как друг",
     r"ты\s+мне\s+как\s+(?:друг|брат)\b"),
    ("у меня есть парень",
     r"у\s+меня\s+есть\s+(?:парень|молодой\s+человек|муж|девушка)\b"),
    ("не хочу общаться",
     r"не\s+хочу\s+(?:с\s+тобой\s+)?(?:общаться|переписываться|разговаривать|"
     r"тебя\s+видеть)"),
    ("оставь меня",
     r"оставь\s+меня(?:\s+в\s+покое)?"),
    ("ты мне не нравишься",
     r"ты\s+мне\s+не\s+нравишься"),
    ("я люблю другого",
     r"(?:я\s+)?люблю\s+друг(?:ого|ую)\b"),
    ("ты любишь другую",
     r"(?:ты\s+)?любишь\s+друг(?:ую|ого)\b"),
)

_ОТКАЗЫ = tuple((имя, re.compile(образец, re.IGNORECASE))
                for имя, образец in _ОТКАЗЫ)


def _найти_отказ(её_сообщения):
    """Последний отказ в её словах: (правило, цитата, дата) или None.

    Именно последний, а не первый: «останемся друзьями» полгода назад и
    вчерашнее — разные новости, и показывать надо свежее.
    """
    найдено = None
    for сообщение in её_сообщения:
        текст = (сообщение["текст"] or "").strip()
        if not текст:
            continue
        for имя, образец in _ОТКАЗЫ:
            if образец.search(текст):
                найдено = (имя, текст, сообщение["дата"])
                break
    return найдено


# --------------------------------------------------------------------------
# Советчица
# --------------------------------------------------------------------------

# В переписке двоих «она» — это всегда кто-то третий: сама собеседница
# сказала бы «я». А «она» вместе с «ты» в одной реплике — разговор про
# твои отношения с кем-то ещё. Так выглядит совет со стороны, а не
# ухаживание, и меряться индексом такая переписка не должна.
_ТРЕТЬЯ = re.compile(r"\b(?:она|её|ее|ей|неё|нее|ней|ею)\b", re.IGNORECASE)
_ТЕБЕ = re.compile(
    r"\b(?:ты|тебе|тебя|тобой|тобою|твой|твоя|твою|твои|твоего|твоей|"
    r"тво[её]м|тво[её]|тебе)\b", re.IGNORECASE)

# Одного счёта реплик мало. На переписке в двенадцать сообщений три
# реплики — четверть и настоящий сигнал; на двух с лишним тысячах её
# сообщений шестнадцать штук — шум: за полгода любые двое случайно
# помянут «ей» рядом с «ты» шестнадцать раз. Живой отчёт на 5956
# сообщениях так и переключился на «дружеское общение» — с уликой
# «это 1% её сообщений», напечатанной прямо под выводом.
#
# Поэтому условий два, и нужны оба: и реплик не меньше МИНИМУМ_НАБЛЮДЕНИЙ,
# и доля не ниже этой. На коротком куске они сходятся сами.
ДОЛЯ_СОВЕТОВ = 0.10


def _советы(её_сообщения):
    """Её реплики, где речь про тебя и про третьего человека разом."""
    return [с for с in её_сообщения
            if с["текст"] and _ТРЕТЬЯ.search(с["текст"])
            and _ТЕБЕ.search(с["текст"])]


# --------------------------------------------------------------------------
# Дружба
# --------------------------------------------------------------------------

# Романтическая реплика считается тем же приёмом, что и совет про третью,
# только наоборот: слово про чувства или встречу плюс обращение на «ты»
# и без третьего лица. «У неё парень есть» так не засчитается — и верно,
# это разговор про чужую жизнь, а не про вас двоих.
_РОМАНТИКА = re.compile(
    r"\bнравишь|\bскучаю|\bлюблю\b|\bсвидан|\bобним|\bцелу|"
    r"\bвстрет(?:им|иш)|\bпогуля(?:ем|ешь)|\bувидим|\bвместе\b",
    re.IGNORECASE)


def _романтика(сообщения):
    """Реплики про вас двоих, а не про чужую жизнь."""
    return [с for с in сообщения
            if с["текст"] and _РОМАНТИКА.search(с["текст"])
            and _ТЕБЕ.search(с["текст"])
            and not _ТРЕТЬЯ.search(с["текст"])]


def _дружба(сообщения, итог):
    """(да/нет, почему) — общаются много и давно, а романтики нет.

    Четыре условия, и нужны все. Темп и скорость поодиночке не
    показательны: ухаживание тоже бывает быстрым и частым. Отличает
    дружбу именно отсутствие романтической линии на дистанции.
    """
    дней = итог.get("дней") or 0
    if дней < ДНЕЙ_ДРУЖБЫ:
        return False, ""
    темп = итог["всего"] / дней
    if темп < ТЕМП_ДРУЖБЫ:
        return False, ""

    м = итог["метрики"]
    оба_быстро = (м["мой_ответ_сек"] is not None
                  and м["её_ответ_сек"] is not None
                  and м["мой_ответ_сек"] < БЫСТРО_ОБА
                  and м["её_ответ_сек"] < БЫСТРО_ОБА)
    if not оба_быстро:
        return False, ""

    с_текстом = [с for с in сообщения if с["текст"]]
    доля = (len(_романтика(с_текстом)) / len(с_текстом)) if с_текстом else 0
    if доля >= ДОЛЯ_РОМАНТИКИ:
        return False, ""

    return True, ("%d %s в день, и так %d %s подряд, отвечаете друг другу "
                  "за %s — и при этом про чувства и встречи меньше %d%% "
                  "переписки"
                  % (round(темп),
                     metrics.склонение(round(темп), "сообщение", "сообщения",
                                       "сообщений"),
                     дней, metrics.склонение(дней, "день", "дня", "дней"),
                     metrics.по_русски_время(max(м["мой_ответ_сек"],
                                                 м["её_ответ_сек"])),
                     round(ДОЛЯ_РОМАНТИКИ * 100)))


# --------------------------------------------------------------------------
# Сборка
# --------------------------------------------------------------------------

def _значение(итог, фактор):
    """Сырое значение фактора из разбивки или None, если он не посчитан."""
    for пункт in итог.get("разбивка", ()):
        if пункт["фактор"] == фактор:
            return пункт["значение"]
    return None


def _заглохло(сообщения, итог, я, сейчас):
    """(да/нет, почему) — переписка кончилась, а не идёт."""
    последнее = итог.get("последнее")
    if последнее and сейчас - последнее > ТИШИНА:
        дней = (сейчас - последнее).days
        # «Если выгрузка свежая» — не вежливость, а честность: отличить
        # мёртвую переписку от выгрузки месячной давности мы не можем,
        # и делать вид, что можем, не должны.
        return True, ("последнее сообщение было %d %s назад — если выгрузка "
                      "свежая" % (дней, metrics.склонение(дней, "день",
                                                          "дня", "дней")))
    тренд = итог.get("тренд")
    if (тренд and тренд["разница"] <= -ПАДЕНИЕ
            and сообщения[-1]["автор"] == я):
        return True, ("общение остыло (было %d, стало %d), и последнее слово "
                      "осталось за тобой" % (тренд["начало"], тренд["конец"]))
    return False, ""


def _на_равных(итог):
    """(да/нет, почему) — похоже, что общаются двое, а не один старается."""
    инициатива = _значение(итог, "инициатива")
    объём = _значение(итог, "объём")
    м = итог["метрики"]
    если_быстро = (м["мой_ответ_сек"] is not None
                   and м["её_ответ_сек"] is not None
                   and м["мой_ответ_сек"] < БЫСТРО
                   and м["её_ответ_сек"] < БЫСТРО)
    if (инициатива is not None and 0.4 <= инициатива <= 0.6
            and объём is not None and объём >= 0.67 and если_быстро):
        return True, ("разговор начинают поровну, пишете одинаково подробно "
                      "и оба отвечаете быстро")
    return False, ""


def определить(сообщения, я, она, итог, сейчас=None):
    """Что это за переписка. Возвращает словарь-рамку.

    Ключи: «тип», «уверенность», «почему» (строки для человека) и «отказ»
    с цитатой и датой, если он нашёлся.
    """
    сейчас = сейчас or datetime.now()
    её = [с for с in сообщения if с["автор"] == она]

    отказ = _найти_отказ(её)
    if отказ:
        правило, цитата, когда = отказ
        подпись = ("Её слова: «%s»" % цитата) + (
            " — %s" % когда.strftime("%d.%m.%Y") if когда else "")
        return {"тип": ОТКАЗ, "уверенность": "высокая", "почему": [подпись],
                "отказ": {"правило": правило, "цитата": цитата, "когда": когда}}

    советы = _советы(её)
    доля = len(советы) / len(её) if её else 0
    # Порог по счёту защищает от одной случайной реплики, порог по доле —
    # от длинной переписки, где случайных наберётся сколько угодно.
    if (len(советы) >= metrics.МИНИМУМ_НАБЛЮДЕНИЙ
            and доля >= ДОЛЯ_СОВЕТОВ):
        return {"тип": СОВЕТЧИЦА,
                "уверенность": "высокая" if len(советы) >= 5 else "средняя",
                "почему": ["в %d %s она говорит про тебя и кого-то третьего "
                           "(это %d%% её сообщений)"
                           % (len(советы),
                              metrics.склонение(len(советы), "реплике",
                                                "репликах", "репликах"),
                              round(доля * 100))],
                "отказ": None}

    да, почему = _заглохло(сообщения, итог, я, сейчас)
    if да:
        return {"тип": ЗАГЛОХЛО, "уверенность": "средняя", "почему": [почему],
                "отказ": None}

    да, почему = _дружба(сообщения, итог)
    if да:
        return {"тип": ДРУЖБА, "уверенность": "средняя", "почему": [почему],
                "отказ": None}

    да, почему = _на_равных(итог)
    if да:
        return {"тип": ОБЩАЕТЕСЬ, "уверенность": "средняя", "почему": [почему],
                "отказ": None}

    return {"тип": УХАЖИВАНИЕ, "уверенность": "низкая", "почему": [],
            "отказ": None}


# --------------------------------------------------------------------------
# Показ
# --------------------------------------------------------------------------

def стоп(рамка):
    """Тот случай, когда советов не будет вовсе."""
    return bool(рамка) and рамка["тип"] == ОТКАЗ


def поправить_ступень(рамка, ступень):
    """Прижимает размер следующего шага к тому, что это за переписка.

    Индекс может быть каким угодно высоким, но если она обсуждает с тобой
    третьего человека или переписка месяц как стоит — звать на свидание
    всё равно не время. Отказ сюда не доходит: его ловит стоп() раньше.
    """
    if рамка and рамка["тип"] in (СОВЕТЧИЦА, ЗАГЛОХЛО):
        return metrics.СТУПЕНЬ_МАЛАЯ
    return ступень


def коротко(рамка):
    """Одна строка под шапкой отчёта."""
    if not рамка:
        return ""
    строка = "Что это за переписка: %s" % НАЗВАНИЯ[рамка["тип"]]
    if рамка["почему"]:
        строка += ". " + рамка["почему"][0][0].upper() + рамка["почему"][0][1:]
    return строка + "."


def заголовок(итог, рамка):
    """Первая фраза про индекс — с поправкой на то, что это за переписка.

    Для дружеской переписки metrics.словами сказала бы «встречного интереса
    почти не видно», и формально не соврала бы: индекс и правда низкий.
    Только человек прочитает это как приговор подруге, а не как «линейка
    не та». Поэтому здесь она не дополняется оговоркой, а заменяется:
    два текста, которые могут разойтись, — это тот же баг, только в словах.
    """
    if стоп(рамка):
        # Всё, что нужно было сказать, уже сказано стоп-блоком. Добавлять
        # к отказу «встречного интереса почти не видно» — топтаться.
        return ""
    if рамка and рамка["тип"] == СОВЕТЧИЦА:
        return ("Индекс ниже меряет ухаживание, а здесь его нет: она "
                "обсуждает с тобой другого человека. Читай цифры как справку "
                "об общении, а не как ответ про интерес к тебе.")
    if рамка and рамка["тип"] == ДРУЖБА:
        return ("Индекс ниже меряет ухаживание, а похоже это на дружбу. "
                "Низкая оценка тут не про холод: по стольку в день и с такой "
                "скоростью ответов холодно не общаются. Читай цифры как "
                "справку об общении.")
    return metrics.словами(итог)


def стоп_абзацы(рамка):
    """Стоп-блок отдельными абзацами и без заголовка — для окна."""
    абзацы = []
    отказ = (рамка or {}).get("отказ") or {}
    if отказ.get("цитата"):
        когда = отказ["когда"].strftime("%d.%m.%Y") if отказ.get("когда") else ""
        абзацы.append("В переписке есть её ответ: «%s»%s"
                      % (отказ["цитата"], " — %s" % когда if когда else ""))
    абзацы += [
        "Здесь нет смысла искать подход: человек уже ответил. Советов по "
        "этой переписке не будет — не потому, что их жалко, а потому что "
        "любой из них был бы про то, как обойти чужое «нет».",
        "Если считаешь, что я ошибся и это не отказ, — пришли переписку без "
        "этого куска, разберу как обычно.",
    ]
    return абзацы


def стоп_текст(рамка):
    """Что сказать вместо советов, когда отказ уже прозвучал."""
    абзацы = стоп_абзацы(рамка)
    return "СТОП.\n" + "\n\n".join(абзацы)
