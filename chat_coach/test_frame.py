def случай_отказ():
    """Отказ в её словах виден, и к нему прилагается улика."""
    чат, _ = ровный(СТАРТ, 4)
    чат.append(_сообщение(чат[-1]["дата"] + timedelta(minutes=5), "Иван",
                          "слушай, может сходим куда-нибудь вдвоём?"))
    чат.append(_сообщение(чат[-1]["дата"] + timedelta(minutes=9), "Аня",
                          "нет спасибо"))
    рамка = _рамка(чат)
    ок = (рамка["тип"] == frame.ОТКАЗ
          and рамка["отказ"]["цитата"] == "нет спасибо"
          and рамка["отказ"]["когда"] is not None
          and frame.стоп(рамка)
          and "нет спасибо" in frame.стоп_текст(рамка))
    return ок, "отказ: %s, улика=%s" % (рамка["тип"], рамка["отказ"])


def случай_отказ_только_её():
    """Те же слова, но сказанные им, отказом не считаются.

    Иначе достаточно было бы самому написать «давай останемся друзьями»,
    чтобы бот объявил отказ собеседницы.
    """
    чат = _с_репликами([
        ("Иван", "нет спасибо"),
        ("Аня", "ты чего"),
        ("Иван", "давай останемся друзьями"),
        ("Аня", "ну ладно"),
        ("Иван", "не пиши мне больше"),
        ("Аня", "хорошо"),
    ])
    рамка = _рамка(чат)
    ок = рамка["тип"] != frame.ОТКАЗ and рамка["отказ"] is None
    return ок, "его слова: тип=%s" % рамка["тип"]


def случай_отказ_узко():
    """Похожие обороты не про него отказом не становятся."""
    чат = _с_репликами([
        ("Иван", "чё делать с ней"),
        ("Аня", "не пиши ей пока, пусть сама напишет"),
        ("Иван", "а если не напишет"),
        ("Аня", "нет спасибо я уже поела, позже расскажу"),
        ("Иван", "ну ок"),
        ("Аня", "ага"),
    ])
    рамка = _рамка(чат)
    ок = рамка["тип"] != frame.ОТКАЗ
    return ок, "узость: тип=%s, улика=%s" % (рамка["тип"], рамка["отказ"])


def случай_советчица():
    """Она обсуждает с ним третьего человека — это не ухаживание."""
    чат = _с_репликами([
        ("Иван", "не знаю что ей написать"),
        ("Аня", "напиши ей просто привет, ты же не на экзамене"),
        ("Иван", "а вдруг не ответит"),
        ("Аня", "если ей не всё равно на тебя, то ответит"),
        ("Иван", "ну хз"),
        ("Аня", "сначала позови её погулять, а ты сразу с признаниями лезешь"),
        ("Иван", "ладно попробую"),
        ("Аня", "и не пиши по десять раз, она тебе ответит когда сможет"),
    ])
    рамка = _рамка(чат)
    ок = (рамка["тип"] == frame.СОВЕТЧИЦА
          and frame.заголовок(metrics.analyse(чат, "Иван", "Аня"), рамка)
          != metrics.словами(metrics.analyse(чат, "Иван", "Аня")))
    return ок, "советчица: тип=%s почему=%s" % (рамка["тип"], рамка["почему"])


def случай_один_совет_не_рамка():
    """Одна реплика про третьего человека рамку не переворачивает.

    Тот же порог, которым защищён индекс: МИНИМУМ_НАБЛЮДЕНИЙ.
    """
    чат, _ = ровный(СТАРТ, 4)
    чат.append(_сообщение(чат[-1]["дата"] + timedelta(minutes=5), "Аня",
                          "кстати она про тебя спрашивала вчера"))
    рамка = _рамка(чат)
    ок = рамка["тип"] != frame.СОВЕТЧИЦА
    return ок, "один совет: тип=%s" % рамка["тип"]


def случай_на_равных():
    """Симметричная переписка — «общаетесь», а не «ухаживание»."""
    чат, конец = ровный(СТАРТ, 6)
    рамка = _рамка(чат, сейчас=конец)
    ок = рамка["тип"] == frame.ОБЩАЕТЕСЬ
    return ок, "на равных: тип=%s почему=%s" % (рамка["тип"], рамка["почему"])


def случай_заглохло():
    """Месяц тишины — переписка кончилась, и это стоит сказать."""
    чат, конец = ровный(СТАРТ, 6)
    рамка = _рамка(чат, сейчас=конец + timedelta(days=30))
    ок = рамка["тип"] == frame.ЗАГЛОХЛО and "назад" in рамка["почему"][0]
    return ок, "заглохло: тип=%s почему=%s" % (рамка["тип"], рамка["почему"])


def случай_ухаживание():
    """Обычная холодная переписка остаётся тем, чем была."""
    чат, конец = холодный(СТАРТ, 8)
    рамка = _рамка(чат, сейчас=конец)
    ок = рамка["тип"] == frame.УХАЖИВАНИЕ and not frame.стоп(рамка)
    return ок, "ухаживание: тип=%s" % рамка["тип"]


def случай_без_дат():
    """Вставка с телефона без дат не роняет определение."""
    чат = [{"автор": "Иван" if н % 2 else "Аня", "дата": None,
            "текст": "ну как-то так получилось", "вложение": False}
           for н in range(12)]
    чат[4]["текст"] = "нет спасибо"          # чётный номер — это её реплика
    итог = metrics.analyse(чат, "Иван", "Аня")
    рамка = frame.определить(чат, "Иван", "Аня", итог)
    ок = (рамка["тип"] == frame.ОТКАЗ
          and рамка["отказ"]["когда"] is None
          and "нет спасибо" in frame.стоп_текст(рамка))
    return ок, "без дат: тип=%s улика=%s" % (рамка["тип"], рамка["отказ"])


def случай_коротко():
    """Строка для отчёта собирается и не разваливается без причины."""
    чат, конец = холодный(СТАРТ, 8)
    пустая = frame.коротко(None)
    обычная = frame.коротко(_рамка(чат, сейчас=конец))
    ок = (пустая == "" and обычная.startswith("Что это за переписка:")
          and обычная.endswith("."))
    return ок, "коротко: пустая=%r обычная=%r" % (пустая, обычная)


def случай_советчица_по_доле():
    """Шестнадцать реплик про третьего — сигнал или шум, смотря от чего.

    Пришло с живой переписки: 5956 сообщений за полгода, 16 её реплик
    про «ей» рядом с «ты» — это 1%, чистый шум. Абсолютный порог в три
    реплики переключал рамку на «дружеское общение», и весь вердикт
    подменялся справкой. Улика «это 1% её сообщений» при этом печаталась
    прямо под выводом.
    """
    def чат(её_всего, советов):
        реплики = []
        for н in range(её_всего):
            текст = ("если ей не всё равно на тебя, она ответит"
                     if н < советов else "ну да, бывает")
            реплики += [("Иван", "ага"), ("Аня", текст)]
        return _с_репликами(реплики)

    длинная = _рамка(чат(300, 16))          # 16 из 300 — 5%
    короткая = _рамка(чат(80, 16))          # 16 из 80 — 20%
    ок = (длинная["тип"] != frame.СОВЕТЧИЦА
          and короткая["тип"] == frame.СОВЕТЧИЦА)
    return ок, "доля советов: длинная=%s короткая=%s" % (
        длинная["тип"], короткая["тип"])


def _густо(дней, в_день, текст_её, текст_его="ну че там"):
    """Плотная переписка: много сообщений в день, ответы за секунды."""
    чат, курсор = [], СТАРТ
    for _день in range(дней):
        for н in range(в_день // 2):
            чат.append(_сообщение(курсор, "Иван", текст_его))
            курсор += timedelta(seconds=5)
            чат.append(_сообщение(курсор, "Аня", текст_её))
            курсор += timedelta(seconds=6)
        курсор += timedelta(hours=20)
    return чат, курсор


def случай_дружба():
    """Полсотни сообщений в день месяцами и ноль романтики — это дружба.

    Пришло с живой переписки: 4994 сообщения за 93 дня, медианы ответа
    пять и шесть секунд, про чувства и встречи меньше процента. Бот
    называл это «интерес прохладный: отвечает, но навстречу не идёт» —
    про человека, который отвечает за пять секунд полсотни раз в день.
    """
    чат, конец = _густо(30, 40, "да ты пипидастр")
    рамка = _рамка(чат, сейчас=конец)
    итог = metrics.analyse(чат, "Иван", "Аня")
    ок = (рамка["тип"] == frame.ДРУЖБА
          # Вердикт про ухаживание на дружбе молчит — как и у советчицы.
          and frame.заголовок(итог, рамка) != metrics.словами(итог)
          and "в день" in рамка["почему"][0])
    return ок, "дружба: тип=%s почему=%s" % (рамка["тип"],
                                             рамка["почему"][0][:60])


def случай_дружба_не_съедает_ухаживание():
    """Тот же темп, но с признаниями — не дружба.

    Без этого условия новый тип проглотил бы ровно тот сценарий, ради
    которого весь продукт и написан: ухаживание тоже бывает быстрым
    и частым.
    """
    чат, конец = _густо(30, 40, "скучаю по тебе, когда увидимся")
    рамка = _рамка(чат, сейчас=конец)
    ок = рамка["тип"] != frame.ДРУЖБА
    return ок, "с романтикой: тип=%s" % рамка["тип"]


def случай_романтика_не_про_третью():
    """«У неё парень есть» романтической репликой не считается."""
    про_третью = [{"автор": "Аня", "текст": "у неё есть парень, ты же знаешь",
                   "дата": None, "вложение": False},
                  {"автор": "Аня", "текст": "встретимся с ней потом",
                   "дата": None, "вложение": False}]
    про_вас = [{"автор": "Аня", "текст": "скучаю по тебе",
                "дата": None, "вложение": False}]
    ок = (frame._романтика(про_третью) == []
          and len(frame._романтика(про_вас)) == 1)
    return ок, "романтика: про третью=%d, про вас=%d" % (
        len(frame._романтика(про_третью)), len(frame._романтика(про_вас)))


def случай_оговорка_про_выгрузку():
    """Тишина в выгрузке — не обязательно мёртвая переписка.

    Отличить мёртвый чат от выгрузки месячной давности мы не можем,
    и утверждать, что можем, не должны.
    """
    чат, конец = ровный(СТАРТ, 6)
    рамка = _рамка(чат, сейчас=конец + timedelta(days=40))
    ок = (рамка["тип"] == frame.ЗАГЛОХЛО
          and "если выгрузка свежая" in рамка["почему"][0])
    return ок, "оговорка: %s" % рамка["почему"][0]


def main():
    случаи = (случай_отказ, случай_отказ_только_её, случай_отказ_узко,
              случай_советчица, случай_один_совет_не_рамка, случай_на_равных,
              случай_заглохло, случай_ухаживание, случай_без_дат,
              случай_коротко, случай_советчица_по_доле,
              случай_дружба, случай_дружба_не_съедает_ухаживание,
              случай_романтика_не_про_третью,
              случай_оговорка_про_выгрузку)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
