# -*- coding: utf-8 -*-
"""Проверка рамки разговора. Запуск: python test_frame.py

Главное, что проверяется, — узость правил. Рамка нужна, чтобы бот не
называл дружбу остывшим ухаживанием и не молчал про отказ; но ошибиться
в другую сторону — приписать отказ, которого не было, — хуже вдвое.
Поэтому почти на каждый положительный случай здесь стоит отрицательный.
"""

from datetime import datetime, timedelta

import console          # noqa: F401
import frame
import metrics
from test_metrics import СТАРТ, _сообщение, холодный


def ровный(курсор, сколько):
    """Оба начинают по очереди, отвечают за минуты, пишут одинаково длинно.

    Пауза между заходами — трое суток: иначе открытие разговора считается
    запоздалым ответом и в инициативу не идёт (см. _инициативы в metrics).
    """
    чат = []
    for н in range(сколько):
        первый, второй = ("Аня", "Иван") if н % 2 else ("Иван", "Аня")
        чат.append(_сообщение(курсор, первый,
                              "привет, как ты там? чем занят сегодня?"))
        курсор += timedelta(minutes=3)
        чат.append(_сообщение(курсор, второй,
                              "да нормально всё, работаю потихоньку"))
        курсор += timedelta(minutes=4)
        чат.append(_сообщение(курсор, первый,
                              "ясно) вечером свободен, может погуляем"))
        курсор += timedelta(minutes=2)
        чат.append(_сообщение(курсор, второй,
                              "давай, часов в восемь у метро тогда"))
        курсор += timedelta(days=3)
    return чат, курсор


def _рамка(чат, сейчас=None):
    итог = metrics.analyse(чат, "Иван", "Аня")
    return frame.определить(чат, "Иван", "Аня", итог,
                            сейчас=сейчас or чат[-1]["дата"])


def _с_репликами(реплики, курсор=None):
    """Из [(автор, текст), ...] делает переписку с шагом в пару минут."""
    курсор = курсор or СТАРТ
    чат = []
    for автор, текст in реплики:
        чат.append(_сообщение(курсор, автор, текст))
        курсор += timedelta(minutes=2)
    return чат


# --------------------------------------------------------------------------

def случай_отказ():
    """Отказ в её словах виден, и к нему прилагается улика."""
    чат, _ = ровный(СТАРТ, 4)
    чат.append(_сообщение(чат[-1]["дата"] + timedelta(minutes=5), "Иван",
                          "слушай, может сходим куда-нибудь вдвоём?"))
    чат.append(_сообщение(чат[-1]["дата"] + timedelta(minutes=9), "Аня",
                          "нет спасибо"))
    рамка = _рамка(чат)
    ок = (рамка["тип"] == frame.ОТКАЗ
          and рамка["отказ"]["цитата"] == "нет спасибо"
          and рамка["отказ"]["когда"] is not None
          and frame.стоп(рамка)
          and "нет спасибо" in frame.стоп_текст(рамка))
    return ок, "отказ: %s, улика=%s" % (рамка["тип"], рамка["отказ"])


def случай_отказ_только_её():
    """Те же слова, но сказанные им, отказом не считаются.

    Иначе достаточно было бы самому написать «давай останемся друзьями»,
    чтобы бот объявил отказ собеседницы.
    """
    чат = _с_репликами([
        ("Иван", "нет спасибо"),
        ("Аня", "ты чего"),
        ("Иван", "давай останемся друзьями"),
        ("Аня", "ну ладно"),
        ("Иван", "не пиши мне больше"),
        ("Аня", "хорошо"),
    ])
    рамка = _рамка(чат)
    ок = рамка["тип"] != frame.ОТКАЗ and рамка["отказ"] is None
    return ок, "его слова: тип=%s" % рамка["тип"]


def случай_отказ_узко():
    """Похожие обороты не про него отказом не становятся."""
    чат = _с_репликами([
        ("Иван", "чё делать с ней"),
        ("Аня", "не пиши ей пока, пусть сама напишет"),
        ("Иван", "а если не напишет"),
        ("Аня", "нет спасибо я уже поела, позже расскажу"),
        ("Иван", "ну ок"),
        ("Аня", "ага"),
    ])
    рамка = _рамка(чат)
    ок = рамка["тип"] != frame.ОТКАЗ
    return ок, "узость: тип=%s, улика=%s" % (рамка["тип"], рамка["отказ"])


def случай_советчица():
    """Она обсуждает с ним третьего человека — это не ухаживание."""
    чат = _с_репликами([
        ("Иван", "не знаю что ей написать"),
        ("Аня", "напиши ей просто привет, ты же не на экзамене"),
        ("Иван", "а вдруг не ответит"),
        ("Аня", "если ей не всё равно на тебя, то ответит"),
        ("Иван", "ну хз"),
        ("Аня", "сначала позови её погулять, а ты сразу с признаниями лезешь"),
        ("Иван", "ладно попробую"),
        ("Аня", "и не пиши по десять раз, она тебе ответит когда сможет"),
    ])
    рамка = _рамка(чат)
    ок = (рамка["тип"] == frame.СОВЕТЧИЦА
          and frame.заголовок(metrics.analyse(чат, "Иван", "Аня"), рамка)
          != metrics.словами(metrics.analyse(чат, "Иван", "Аня")))
    return ок, "советчица: тип=%s почему=%s" % (рамка["тип"], рамка["почему"])


def случай_один_совет_не_рамка():
    """Одна реплика про третьего человека рамку не переворачивает.

    Тот же порог, которым защищён индекс: МИНИМУМ_НАБЛЮДЕНИЙ.
    """
    чат, _ = ровный(СТАРТ, 4)
    чат.append(_сообщение(чат[-1]["дата"] + timedelta(minutes=5), "Аня",
                          "кстати она про тебя спрашивала вчера"))
    рамка = _рамка(чат)
    ок = рамка["тип"] != frame.СОВЕТЧИЦА
    return ок, "один совет: тип=%s" % рамка["тип"]


def случай_на_равных():
    """Симметричная переписка — «общаетесь», а не «ухаживание»."""
    чат, конец = ровный(СТАРТ, 6)
    рамка = _рамка(чат, сейчас=конец)
    ок = рамка["тип"] == frame.ОБЩАЕТЕСЬ
    return ок, "на равных: тип=%s почему=%s" % (рамка["тип"], рамка["почему"])


def случай_заглохло():
    """Месяц тишины — переписка кончилась, и это стоит сказать."""
    чат, конец = ровный(СТАРТ, 6)
    рамка = _рамка(чат, сейчас=конец + timedelta(days=30))
    ок = рамка["тип"] == frame.ЗАГЛОХЛО and "назад" in рамка["почему"][0]
    return ок, "заглохло: тип=%s почему=%s" % (рамка["тип"], рамка["почему"])


def случай_ухаживание():
    """Обычная холодная переписка остаётся тем, чем была."""
    чат, конец = холодный(СТАРТ, 8)
    рамка = _рамка(чат, сейчас=конец)
    ок = рамка["тип"] == frame.УХАЖИВАНИЕ and not frame.стоп(рамка)
    return ок, "ухаживание: тип=%s" % рамка["тип"]


def случай_без_дат():
    """Вставка с телефона без дат не роняет определение."""
    чат = [{"автор": "Иван" if н % 2 else "Аня", "дата": None,
            "текст": "ну как-то так получилось", "вложение": False}
           for н in range(12)]
    чат[4]["текст"] = "нет спасибо"          # чётный номер — это её реплика
    итог = metrics.analyse(чат, "Иван", "Аня")
    рамка = frame.определить(чат, "Иван", "Аня", итог)
    ок = (рамка["тип"] == frame.ОТКАЗ
          and рамка["отказ"]["когда"] is None
          and "нет спасибо" in frame.стоп_текст(рамка))
    return ок, "без дат: тип=%s улика=%s" % (рамка["тип"], рамка["отказ"])


def случай_коротко():
    """Строка для отчёта собирается и не разваливается без причины."""
    чат, конец = холодный(СТАРТ, 8)
    пустая = frame.коротко(None)
    обычная = frame.коротко(_рамка(чат, сейчас=конец))
    ок = (пустая == "" and обычная.startswith("Что это за переписка:")
          and обычная.endswith("."))
    return ок, "коротко: пустая=%r обычная=%r" % (пустая, обычная)


def main():
    случаи = (случай_отказ, случай_отказ_только_её, случай_отказ_узко,
              случай_советчица, случай_один_совет_не_рамка, случай_на_равных,
              случай_заглохло, случай_ухаживание, случай_без_дат,
              случай_коротко)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
