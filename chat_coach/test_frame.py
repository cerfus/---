# -*- coding: utf-8 -*-
"""Проверка рамки разговора. Запуск: python test_frame.py

Главное, что проверяется, — узость правил. Рамка нужна, чтобы бот не
называл дружбу остывшим ухаживанием и не молчал про отказ; но ошибиться
в другую сторону — приписать отказ, которого не было, — хуже вдвое.
Поэтому почти на каждый положительный случай здесь стоит отрицательный.
"""

from datetime import datetime, timedelta

import console          # noqa: F401
import frame
import metrics
from test_metrics import СТАРТ, _сообщение, холодный


def ровный(курсор, сколько):
    """Оба начинают по очереди, отвечают за минуты, пишут одинаково длинно.

    Пауза между заходами — трое суток: иначе открытие разговора считается
    запоздалым ответом и в инициативу не идёт (см. _инициативы в metrics).
    """
    чат = []
    for н in range(сколько):
        первый, второй = ("Аня", "Иван") if н % 2 else ("Иван", "Аня")
        чат.append(_сообщение(курсор, первый,
                              "привет, как ты там? чем занят сегодня?"))
        курсор += timedelta(minutes=3)
        чат.append(_сообщение(курсор, второй,
                              "да нормально всё, работаю потихоньку"))
        курсор += timedelta(minutes=4)
        чат.append(_сообщение(курсор, первый,
                              "ясно) вечером свободен, может погуляем"))
        курсор += timedelta(minutes=2)
        чат.append(_сообщение(курсор, второй,
                              "давай, часов в восемь у метро тогда"))
        курсор += timedelta(days=3)
    return чат, курсор


def _рамка(чат, сейчас=None):
    итог = metrics.analyse(чат, "Иван", "Аня")
    return frame.определить(чат, "Иван", "Аня", итог,
                            сейчас=сейчас or чат[-1]["дата"])


def _с_репликами(реплики, курсор=None):
    """Из [(автор, текст), ...] делает переписку с шагом в пару минут."""
    курсор = курсор or СТАРТ
    чат = []
    for автор, текст in реплики:
        чат.append(_сообщение(курсор, автор, текст))
        курсор += timedelta(minutes=2)
    return чат


