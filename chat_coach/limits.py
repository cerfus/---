# -*- coding: utf-8 -*-
"""
Тарифы и квоты.

Бесплатный тариф с лимитами включён с первого дня — не из жадности, а из
арифметики: один полный разбор стоит около девяти центов, и сотня человек
по разбору в день — это уже триста долларов в месяц. Лимит здесь и есть
единственное, что стоит между работающим ботом и закончившимися деньгами.

Сверх бесплатного есть купленное — пакеты разборов (payments.py). Порядок
трат всегда один: сначала бесплатное, потом купленное. Наоборот было бы
воровством в мелочах — человек платил бы за то, что и так сегодня даром.

Отсюда же и главная тонкость этого файла: потратить() возвращает не «да
или нет», а откуда именно взяли. Вернуть бесплатную попытку вместо
купленной — значит молча подарить разбор, и заметить это по логам почти
невозможно.
"""

from datetime import datetime

import metrics          # нужен только ради склонения числительных

РАЗБОР = "разбор"          # полный разбор переписки с участием ИИ
ВОПРОС = "вопрос"          # короткий вопрос по уже разобранной переписке
ЧЕРНОВИК = "черновик"      # проверка одного сообщения перед отправкой
ПОДСКАЗКА = "подсказка"    # готовое следующее сообщение под выбранную цель

# Откуда списали попытку. None — не списали вовсе, и он ложен, поэтому
# «if not откуда:» у вызывающих читается как раньше.
БЕСПЛАТНО = "бесплатно"
ИЗ_ПАКЕТА = "из пакета"

# тариф -> вид -> (сколько можно, за какой срок)
#
# Черновик считается отдельно от вопросов, а не из общего котла. Причин
# две. Разбор целой переписки делают раз в неделю, а черновик — каждый
# день: это и есть то, за чем возвращаются, и душить его чужим лимитом
# глупо. И спрос на него надо мерить отдельно: в какой лимит упираются
# люди, в тот и имеет смысл продавать.
ТАРИФЫ = {
    "free": {
        РАЗБОР: (1, "неделя"),
        ВОПРОС: (3, "день"),
        ЧЕРНОВИК: (3, "день"),
        ПОДСКАЗКА: (3, "день"),
    },
    "premium": {
        РАЗБОР: (30, "неделя"),
        ВОПРОС: (100, "день"),
        ЧЕРНОВИК: (100, "день"),
        ПОДСКАЗКА: (100, "день"),
    },
}

# По три формы на вид: без них выходило «3 вопрос в неделя» — строка,
# которую человек видит ровно в тот момент, когда уже расстроен лимитом.
НАЗВАНИЯ = {
    РАЗБОР: ("разбор переписки", "разбора переписки", "разборов переписки"),
    ВОПРОС: ("вопрос", "вопроса", "вопросов"),
    ЧЕРНОВИК: ("проверка черновика", "проверки черновика",
               "проверок черновика"),
    ПОДСКАЗКА: ("подсказка", "подсказки", "подсказок"),
}

СРОКИ = {"день": "в день", "неделя": "в неделю"}


def период(срок, сейчас=None):
    """Ключ текущего окна: сутки или календарная неделя."""
    сейчас = сейчас or datetime.now()
    if срок == "день":
        return сейчас.strftime("%Y-%m-%d")
    if срок == "неделя":
        год, неделя, _день = сейчас.isocalendar()
        return "%04d-W%02d" % (год, неделя)
    raise ValueError("Неизвестный срок: %s" % срок)


def правило(тариф, вид):
    """(лимит, срок) для тарифа. Незнакомый тариф считаем бесплатным."""
    return ТАРИФЫ.get(тариф, ТАРИФЫ["free"])[вид]


def осталось(база, user_id, вид, тариф=None, сейчас=None):
    """Сколько бесплатных попыток осталось в текущем окне."""
    тариф = тариф or база.тариф(user_id)
    лимит, срок = правило(тариф, вид)
    потрачено = база.потрачено(user_id, вид, период(срок, сейчас))
    return max(лимит - потрачено, 0)


def остаток(база, user_id, вид, тариф=None, сейчас=None):
    """Оба числа разом: {«бесплатно»: n, «куплено»: m}."""
    return {"бесплатно": осталось(база, user_id, вид, тариф, сейчас),
            "куплено": база.остаток_купленного(user_id, вид)}


def потратить(база, user_id, вид, тариф=None, сейчас=None):
    """Списывает попытку и говорит откуда: БЕСПЛАТНО, ИЗ_ПАКЕТА или None.

    Сначала бесплатное, потом купленное — иначе человек платил бы за то,
    что и так сегодня даром.
    """
    тариф = тариф or база.тариф(user_id)
    лимит, срок = правило(тариф, вид)
    if база.потратить(user_id, вид, период(срок, сейчас), лимит):
        return БЕСПЛАТНО
    if база.потратить_купленное(user_id, вид):
        return ИЗ_ПАКЕТА
    return None


def вернуть(база, user_id, вид, откуда, тариф=None, сейчас=None):
    """Возврат попытки туда же, откуда её взяли.

    Упавший запрос к ИИ или битый файл не должны съедать ни недельную
    квоту, ни купленный разбор. «Откуда» обязателен: вернуть бесплатную
    попытку вместо купленной значит подарить разбор, и по логам это
    не увидеть.
    """
    if откуда == ИЗ_ПАКЕТА:
        база.вернуть_купленное(user_id, вид)
        return
    if откуда == БЕСПЛАТНО:
        тариф = тариф or база.тариф(user_id)
        _лимит, срок = правило(тариф, вид)
        база.вернуть(user_id, вид, период(срок, сейчас))


def когда_обновится(срок, сейчас=None):
    """Человеческое «приходи тогда-то»."""
    сейчас = сейчас or datetime.now()
    if срок == "день":
        return "завтра"
    дней_до_понедельника = 7 - сейчас.isoweekday() + 1
    if дней_до_понедельника == 1:
        return "завтра"
    return "через %d %s" % (дней_до_понедельника,
                            metrics.склонение(дней_до_понедельника,
                                              "день", "дня", "дней"))


def текст_лимита(вид, тариф="free", сейчас=None):
    """Что сказать человеку, упёршемуся в потолок."""
    лимит, срок = правило(тариф, вид)
    return ("Бесплатно доступно: %d %s %s. Следующий — %s."
            % (лимит, metrics.склонение(лимит, *НАЗВАНИЯ[вид]), СРОКИ[срок],
               когда_обновится(срок, сейчас)))
