# -*- coding: utf-8 -*-
"""
Ключи из файла .env — чтобы не вбивать их руками при каждом запуске.

Импортируется ради побочного действия, как console.py: подхватывает .env
сразу при импорте. Поэтому в bot.py стоит первым — analysis.py читает
переменные окружения уже на своём импорте, и опоздать нельзя. Окно
(app.py) и консольный отчёт (report.py) импортируют его по той же
причине: ключ Claude нужен всем троим, а лежать он должен в одном месте.

Зачем вообще. Докер читает .env сам (env_file в compose), а «python
bot.py» — нет, и человеку приходилось каждый раз набирать «set
BOT_TOKEN=...» в консоли. Набирать ключи руками — это не только скучно,
это ещё и способ однажды отправить их не туда.

Библиотеки для этого не нужны: формат простой, а лишняя зависимость
в проекте, который считает цифры на голой стандартной поставке, ни к чему.

Главное правило: **уже заданное окружение всегда сильнее файла.** Так
«set» в консоли и env_file в докере остаются главнее, а .env работает
только там, где переменной ещё нет.
"""

import os

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ФАЙЛ = os.path.join(ЗДЕСЬ, ".env")


def разобрать_строку(строка):
    """(имя, значение) или None, если строка ничего не задаёт."""
    строка = строка.strip()
    if not строка or строка.startswith("#"):
        return None
    if строка.lower().startswith("export "):
        строка = строка[len("export "):].strip()
    if "=" not in строка:
        return None
    имя, значение = строка.split("=", 1)
    имя, значение = имя.strip(), значение.strip()
    if not имя:
        return None
    # Кавычки вокруг значения снимаем: их ставят по привычке из шелла,
    # а в питон они приехали бы частью ключа.
    кавычка = значение[:1]
    if len(значение) >= 2 and кавычка in "\"'" and значение[-1] == кавычка:
        значение = значение[1:-1]
    return имя, значение


def прочитать(путь):
    """Текст файла. Блокнот сохраняет .env двумя способами, и оба ломали.

    По умолчанию он пишет UTF-8 **с меткой** в начале файла: первым именем
    тогда становится не BOT_TOKEN, а BOT_TOKEN с невидимым символом
    впереди. Бот говорит «не задан BOT_TOKEN» человеку, который смотрит
    прямо на эту строку. Лечится словом `utf-8-sig`.

    А если сохранить «в ANSI» (на русской Windows это cp1251), файл
    вообще перестаёт читаться в UTF-8, и UnicodeDecodeError вылетает
    голым трейсбеком на импорте — раньше любых наших понятных слов.
    Ключи всё равно ASCII, так что испорченный русский комментарий не
    стоит ничего, а падение на ровном месте стоит вечера.
    """
    with open(путь, "rb") as файл:
        сырое = файл.read()
    try:
        return сырое.decode("utf-8-sig")
    except UnicodeDecodeError:
        return сырое.decode("cp1251", errors="replace")


def подхватить(путь=None):
    """Кладёт в окружение то, чего в нём ещё нет. Возвращает имена.

    Значения не логируются и не возвращаются: это ключи, и им нечего
    делать ни в выводе, ни в отчёте об ошибке.
    """
    путь = путь or ФАЙЛ
    if not os.path.exists(путь):
        return []
    подхваченные = []
    for строка in прочитать(путь).splitlines():
        пара = разобрать_строку(строка)
        if пара is None:
            continue
        имя, значение = пара
        if имя in os.environ:
            continue              # заданное снаружи всегда главнее
        os.environ[имя] = значение
        подхваченные.append(имя)
    return подхваченные


# Имена, а не значения: их печатает бот при запуске, чтобы было видно,
# что файл прочитан.
ПОДХВАЧЕНО = подхватить()
