# -*- coding: utf-8 -*-
"""Проверка отчёта: наблюдения, линии, пороги, вёрстка.

Запуск: python test_report.py

Смысл в том, чтобы отчёт не начал врать по мелочи. Три места, где это
особенно легко: сравнение половин переписки (их баллы нормированы
по-разному), выдуманная точка на месте недели без данных и чужое имя,
попавшее в разметку.
"""

import re
from datetime import timedelta

import console          # noqa: F401
import frame
import metrics
import report
import test_metrics as образцы


def _остывшая():
    """Была тёплой, стала холодной — на такой видно всё сразу."""
    чат, курсор = образцы.тёплый(образцы.СТАРТ, 5)
    хвост, конец = образцы.холодный(курсор + timedelta(hours=10), 6)
    чат += хвост
    итог = metrics.analyse(чат, "Иван", "Аня")
    рамка = frame.определить(чат, "Иван", "Аня", итог, сейчас=конец)
    return чат, итог, рамка


# --------------------------------------------------------------------------

def случай_тренд_по_факторам():
    """Сравниваются баллы, а не вклады, и только общие факторы.

    Вклад пересчитывается под набор факторов своей половины: если
    в начале переписки их посчиталось меньше, вклад каждого раздут,
    и выходит «скорость 21 → 15» при потолке 15.
    """
    _чат, итог, _рамка = _остывшая()
    сдвиги = итог["тренд"]["по_факторам"]
    все_доли = all(0.0 <= было <= 1.0 and 0.0 <= стало <= 1.0
                   for было, стало in сдвиги.values())
    ок = (сдвиги and все_доли
          and сдвиги["инициатива"][0] > сдвиги["инициатива"][1])
    return ок, "тренд по факторам: инициатива %s" % (сдвиги.get("инициатива"),)


def случай_наблюдения():
    """Наблюдений не больше пяти, и в каждом есть число."""
    _чат, итог, рамка = _остывшая()
    строки = report.наблюдения(итог, рамка)
    без_чисел = [с for с in строки if not re.search(r"\d", с)]
    ок = 0 < len(строки) <= 5 and not без_чисел
    return ок, "наблюдения: %d штук, без чисел %s" % (
        len(строки), без_чисел or "нет")


def случай_наблюдения_без_советов():
    """Только факты: ни оценок, ни рекомендаций.

    Правило проверяется, а не держится на честном слове: иначе оно
    размоется при первой же правке формулировок.
    """
    запрещённое = re.compile(
        r"стоит|советую|попробуй|надо бы|лучше бы|рекоменд|шанс|вероятн",
        re.IGNORECASE)
    наборы = []
    for чат, курсор in (образцы.тёплый(образцы.СТАРТ, 6),
                        образцы.холодный(образцы.СТАРТ, 6)):
        итог = metrics.analyse(чат, "Иван", "Аня")
        наборы += report.наблюдения(итог)
    плохие = [с for с in наборы if запрещённое.search(с)]
    return not плохие, "советы в наблюдениях: %s" % (плохие or "нет")


def случай_линия():
    """Дыра остаётся дырой, а не превращается в ноль."""
    обычная = report.линия([0, 50, 100], потолок=100)
    с_дырой = report.линия([10, None, 90], потолок=100)
    пустая = report.линия([None, None])
    ок = (len(обычная) == 3 and обычная[0] == "▁" and обычная[-1] == "█"
          and с_дырой[1] == "·" and len(с_дырой) == 3
          and пустая == "")
    return ок, "линия: %r, с дырой %r, пустая %r" % (обычная, с_дырой, пустая)


def случай_недели():
    """Неделя без данных даёт None, а не выдуманный уровень."""
    чат, _итог, _рамка = _остывшая()
    недели = metrics.по_неделям(чат, "Иван", "Аня")
    куцая = метрики_куцей_недели()
    ок = (len(недели) >= 2
          and all(сколько > 0 for _н, _и, сколько in недели)
          and куцая is None)
    return ок, "недели: %d, куцая=%s" % (len(недели), куцая)


def метрики_куцей_недели():
    """Индекс недели, где сообщений меньше порога."""
    мало = [образцы._сообщение(образцы.СТАРТ + timedelta(minutes=н),
                               "Иван" if н % 2 else "Аня", "ок")
            for н in range(4)]
    недели = metrics.по_неделям(мало, "Иван", "Аня")
    return недели[0][1] if недели else "нет недель"


def случай_пороги():
    """Порог не предлагают тому, у кого и так неплохо."""
    _чат, итог, _рамка = _остывшая()
    строки = report.пороги(итог)
    тёплая, _ = образцы.тёплый(образцы.СТАРТ, 8)
    у_тёплой = report.пороги(metrics.analyse(тёплая, "Иван", "Аня"))
    ок = (строки and len(строки) <= 3
          and all("Половина баллов" in с for с in строки)
          # У тёплой переписки почти всё на максимуме — предлагать нечего.
          and len(у_тёплой) < len(строки))
    return ок, "пороги: остывшая %d, тёплая %d" % (len(строки), len(у_тёплой))


def случай_имя_не_ломает_разметку():
    """Имя приходит из чужого файла и попадает в разметку."""
    _чат, итог, рамка = _остывшая()
    итог = dict(итог, я="<b>Иван", она="Аня & <script>")
    блоки = report.телеграмом(итог, рамка, [])
    всё = "\n".join(блоки)
    ок = ("&lt;b&gt;Иван" in всё and "&amp;" in всё
          and "<script>" not in всё)
    return ок, "экранирование: скрипт внутри=%s" % ("<script>" in всё)


def случай_стоп_выше_индекса():
    """При отказе стоп-блок стоит выше всего остального."""
    чат, курсор = образцы.тёплый(образцы.СТАРТ, 5)
    чат.append(образцы._сообщение(курсор, "Аня", "нет спасибо"))
    итог = metrics.analyse(чат, "Иван", "Аня")
    рамка = frame.определить(чат, "Иван", "Аня", итог, сейчас=курсор)
    всё = "\n".join(report.телеграмом(итог, рамка, []))
    ок = (frame.стоп(рамка)
          and всё.index("СТОП") < всё.index("вовлечённость"))
    return ок, "стоп выше индекса: %s" % frame.стоп(рамка)


def случай_блоки_влезают():
    """Каждый блок короче предела сообщения — значит, резать можно."""
    чат, итог, рамка = _остывшая()
    недели = metrics.по_неделям(чат, "Иван", "Аня")
    блоки = report.телеграмом(итог, рамка, недели)
    длинные = [len(б) for б in блоки if len(б) > 3500]
    # И теги закрыты: открытых ровно столько же, сколько закрытых.
    всё = "\n".join(блоки)
    открытые = re.findall(r"<(\w+)>", всё)
    закрытые = re.findall(r"</(\w+)>", всё)
    ок = not длинные and sorted(открытые) == sorted(закрытые)
    return ок, "блоки: длинных %s, теги %d/%d" % (
        длинные or "нет", len(открытые), len(закрытые))


def случай_узкие_полоски():
    """В моноширинных блоках строки влезают в ширину телефона."""
    чат, итог, рамка = _остывшая()
    блоки = report.телеграмом(итог, рамка,
                              metrics.по_неделям(чат, "Иван", "Аня"))
    широкие = []
    for блок in блоки:
        for кусок in re.findall(r"<pre>(.*?)</pre>", блок, re.S):
            широкие += [с for с in кусок.split("\n") if len(с) > 44]
    return not широкие, "широкие строки: %s" % (широкие or "нет")


def main():
    случаи = (случай_тренд_по_факторам, случай_наблюдения,
              случай_наблюдения_без_советов, случай_линия, случай_недели,
              случай_пороги, случай_имя_не_ломает_разметку,
              случай_стоп_выше_индекса, случай_блоки_влезают,
              случай_узкие_полоски)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
