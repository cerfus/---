#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Окно программы: разбор переписки без командной строки.

Запуск — двойным кликом по «Разобрать переписку.bat». Программа поднимает
маленький сервер на своём же компьютере и открывает браузер: получается
обычное окно, только сверстанное как страница.

Почему браузер, а не tkinter: страницу можно проверить запросами, а окно
tkinter — только глазами. Плюс ни одной новой зависимости, всё из
стандартной поставки Python.

Наружу ничего не торчит: слушаем только 127.0.0.1, и каждый запрос должен
предъявить одноразовый ключ из адресной строки. Без ключа любой открытый
в том же браузере сайт мог бы слать запросы на наш порт, а каждый разбор
стоит денег.

Переписка живёт в оперативной памяти и только до следующего разбора —
как и в боте, на диск не попадает ничего.
"""

import argparse
import base64
import json
import os
import posixpath
import secrets
import shutil
import sys
import tempfile
import threading
import time
import traceback
import urllib.parse
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

import console          # noqa: F401  — правит вывод на Windows при импорте
import frame
import metrics
import parser as export_parser
import report
import texts

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ПАПКА_СТРАНИЦЫ = os.path.join(ЗДЕСЬ, "ui")
ФАЙЛ_НАСТРОЕК = os.path.join(ЗДЕСЬ, "настройки.json")
ФАЙЛ_ЛОГА = os.path.join(ЗДЕСЬ, "_лог.txt")

# Окно запускается без консоли, поэтому закрыть программу нечем. Страница
# стучится раз в десять секунд; замолчала дольше — значит, вкладку закрыли,
# и висеть в памяти дальше незачем.
ТИШИНА_ДО_ВЫХОДА = 60
ПРЕДЕЛ_ЗАПРОСА = 25 * 1024 * 1024
МИНИМУМ = 10       # меньше — считать почти нечего, но показать можно

ТИПЫ = {".html": "text/html; charset=utf-8",
        ".css": "text/css; charset=utf-8",
        ".js": "text/javascript; charset=utf-8"}

ключ_доступа = secrets.token_urlsafe(24)
последний_стук = time.time()
_замок = threading.Lock()

# Разобранная переписка. Одно место, потому что программа — на одного
# человека за одним компьютером. Заменяется на следующем разборе.
разобранное = {}


def записать_в_лог(что):
    """Окна нет, значит ошибку больше негде увидеть."""
    try:
        with open(ФАЙЛ_ЛОГА, "a", encoding="utf-8") as fh:
            fh.write("%s  %s\n" % (time.strftime("%Y-%m-%d %H:%M:%S"), что))
    except OSError:
        pass


# --------------------------------------------------------------------------
# Настройки
# --------------------------------------------------------------------------

def прочитать_настройки():
    try:
        with open(ФАЙЛ_НАСТРОЕК, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return {}


def сохранить_настройки(настройки):
    временный = ФАЙЛ_НАСТРОЕК + ".tmp"
    with open(временный, "w", encoding="utf-8") as fh:
        json.dump(настройки, fh, ensure_ascii=False, indent=1)
    os.replace(временный, ФАЙЛ_НАСТРОЕК)


def применить_ключ(ключ):
    """Кладём ключ в окружение — analysis.py берёт его оттуда."""
    ключ = (ключ or "").strip()
    if ключ:
        os.environ["ANTHROPIC_API_KEY"] = ключ
    return bool(ключ)


def ключ_есть():
    return bool(os.environ.get("ANTHROPIC_API_KEY")
                or os.environ.get("ANTHROPIC_AUTH_TOKEN"))


# --------------------------------------------------------------------------
# Разбор
# --------------------------------------------------------------------------

def разобрать_присланное(данные):
    """Из тела запроса делает список сообщений. -> (сообщения, явная)."""
    если_файл = данные.get("файл")
    if если_файл:
        имя = export_parser.безопасное_имя(данные.get("имя"))
        папка = tempfile.mkdtemp(prefix="chat_coach_окно_")
        try:
            путь = os.path.join(папка, имя)
            with open(путь, "wb") as fh:
                fh.write(base64.b64decode(если_файл))
            return export_parser.read_export(путь), False
        finally:
            # Файл был нужен ровно на время разбора — как и в боте.
            shutil.rmtree(папка, ignore_errors=True)
    return export_parser.read_pasted(данные.get("текст") or "")


def цифры_отчёта(итог):
    """Пары «подпись — значение» для правой колонки отчёта."""
    return [{"подпись": подпись, "значение": значение}
            for подпись, значение in report.цифры(итог)]


def отчёт_в_json(итог, разбор_ии=None, ошибка_ии="", рамка=None):
    сейчас = metrics.сейчас(итог)
    ответ = {
        "я": итог["я"], "она": итог["она"],
        "всего": итог["всего"],
        "дней": итог["дней"],
        "период": "",
        "индекс": итог["индекс"],
        "сейчас": сейчас,
        # Вердикт идёт через frame: на дружеской переписке «встречного
        # интереса не видно» — правда про цифры и неправда про людей.
        # Без рамки заголовок отдаёт ровно metrics.словами, как и раньше.
        "вердикт": frame.заголовок(итог, рамка),
        # При отказе «коротко» молчит: цитата уже стоит в стоп-блоке, и
        # повторять её строкой выше — топтаться. Ровно так же поступает
        # консольный отчёт.
        "рамка": {"тип": рамка["тип"],
                  "коротко": "" if frame.стоп(рамка) else frame.коротко(рамка),
                  "стоп": frame.стоп(рамка),
                  "стоп_абзацы": frame.стоп_абзацы(рамка) if frame.стоп(рамка)
                  else []} if рамка else None,
        # Вклад уходит уже целым: если округлять его в браузере, Math.round
        # разойдётся с питоновским round на половинках, и выйдет «13 из 12».
        "разбивка": [{"фактор": пункт["фактор"], "словами": пункт["словами"],
                      "балл": пункт["балл"], "вклад": пункт["вклад_целым"],
                      "потолок": пункт["потолок"]}
                     for пункт in итог["разбивка"]],
        "не_посчитано": [{"фактор": имя, "словами": словами}
                         for имя, словами in metrics.не_посчитано(итог)],
        "тренд": итог["тренд"],
        "цифры": цифры_отчёта(итог),
        "ии": None,
        "ошибка_ии": ошибка_ии,
        "ключ_есть": ключ_есть(),
    }
    # Строку собираем здесь целиком: окончания по-русски умеет считать
    # metrics.склонение, а в браузере они дописывались руками — и выходило
    # «24 сообщений».
    сообщений = "%d %s" % (итог["всего"], metrics.склонение(
        итог["всего"], "сообщение", "сообщения", "сообщений"))
    if итог["первое"] and итог["последнее"]:
        ответ["период"] = "с %s по %s — %d %s, %s" % (
            итог["первое"].strftime("%d.%m.%Y"),
            итог["последнее"].strftime("%d.%m.%Y"), итог["дней"],
            metrics.склонение(итог["дней"], "день", "дня", "дней"),
            сообщений)
    else:
        ответ["период"] = сообщений
    if разбор_ии is not None:
        ответ["ии"] = {
            "стоп": разбор_ии.стоп_сигнал,
            "коротко": разбор_ии.коротко,
            "стоп_причина": разбор_ии.стоп_причина,
            "что_работает": list(разбор_ии.что_работает),
            "что_мешает": [{"что_не_так": совет.что_не_так,
                            "цитата": совет.цитата,
                            "как_лучше": совет.как_лучше}
                           for совет in разбор_ии.что_мешает],
            "следующий_шаг": разбор_ии.следующий_шаг,
        }
    return ответ


# --------------------------------------------------------------------------
# Сервер
# --------------------------------------------------------------------------

class Окно(BaseHTTPRequestHandler):
    server_version = "ChatCoach"

    def log_message(self, формат, *аргументы):
        pass                      # своя тишина: консоли всё равно нет

    # ---------------------------------------------------------- служебное

    def _свой(self):
        """Пускаем только с этого же компьютера и только с верным ключом."""
        хост = (self.headers.get("Host") or "").split(":")[0]
        if хост not in ("127.0.0.1", "localhost"):
            return False
        запрос = self.path.split("?", 1)
        поля = urllib.parse.parse_qs(запрос[1] if len(запрос) > 1 else "")
        предъявлен = (поля.get("k") or [""])[0]
        # Сравниваем байтами, а не строками: compare_digest отказывается
        # работать с не-ASCII и роняет обработчик пятисотой вместо честного
        # отказа. Подобрать ключ нельзя, а вот уронить окно было можно.
        return secrets.compare_digest(предъявлен.encode("utf-8", "replace"),
                                      ключ_доступа.encode("utf-8"))

    def _путь(self):
        return posixpath.normpath(self.path.split("?", 1)[0])

    def _отдать(self, данные, тип="application/json; charset=utf-8", код=200):
        if not isinstance(данные, bytes):
            данные = данные.encode("utf-8")
        self.send_response(код)
        self.send_header("Content-Type", тип)
        self.send_header("Content-Length", str(len(данные)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(данные)

    def _json(self, что, код=200):
        self._отдать(json.dumps(что, ensure_ascii=False), код=код)

    def _беда(self, текст, код=400):
        self._json({"ошибка": текст}, код=код)

    def _тело(self):
        сколько = int(self.headers.get("Content-Length") or 0)
        if сколько > ПРЕДЕЛ_ЗАПРОСА:
            raise ValueError("Файл слишком большой.")
        if not сколько:
            return {}
        return json.loads(self.rfile.read(сколько).decode("utf-8"))

    # ------------------------------------------------------------- страница

    def do_GET(self):
        путь = self._путь()

        # Стили и скрипт отдаём без ключа. Браузер запрашивает их обычными
        # ссылками из разметки, без «?k=», и с проверкой страница грузилась
        # голой: ни оформления, ни логики. Секретов в них нет, а всё, что
        # стоит денег и трогает данные, лежит за /api — вот там ключ и нужен.
        if путь.startswith("/ui/"):
            self._файл_страницы(путь[4:])
            return
        if путь == "/favicon.ico":
            self._отдать(b"", тип="image/x-icon", код=204)
            return

        if not self._свой():
            if путь == "/":
                # Открыли адрес руками, без ключа — объясняем, а не молчим.
                self._отдать("<h1>Нужна ссылка с ключом</h1><p>Закрой вкладку "
                             "и запусти программу заново.</p>",
                             тип="text/html; charset=utf-8", код=403)
            else:
                self._беда("чужой ключ", код=403)
            return

        if путь == "/":
            self._файл_страницы("index.html")
        elif путь == "/api/settings":
            self._json({"ключ_есть": ключ_есть()})
        else:
            self._беда("нет такой страницы", код=404)

    def _файл_страницы(self, имя):
        имя = export_parser.безопасное_имя(имя)
        путь = os.path.join(ПАПКА_СТРАНИЦЫ, имя)
        if not os.path.isfile(путь):
            self._беда("нет файла %s" % имя, код=404)
            return
        with open(путь, "rb") as fh:
            содержимое = fh.read()
        расширение = os.path.splitext(имя)[1].lower()
        self._отдать(содержимое, тип=ТИПЫ.get(расширение, "text/plain"))

    # ---------------------------------------------------------------- api

    def do_POST(self):
        global последний_стук
        if not self._свой():
            self._беда("чужой ключ", код=403)
            return
        путь = self._путь()
        try:
            тело = self._тело()
        except ValueError as сбой:
            self._беда(str(сбой))
            return

        последний_стук = time.time()
        try:
            if путь == "/api/ping":
                self._json({"живой": True})
            elif путь == "/api/quit":
                self._json({"пока": True})
                threading.Thread(target=self.server.shutdown,
                                 daemon=True).start()
            elif путь == "/api/settings":
                self._настройки(тело)
            elif путь == "/api/parse":
                self._разбор_текста(тело)
            elif путь == "/api/analyse":
                self._разбор_целиком(тело)
            else:
                self._беда("нет такого действия", код=404)
        except Exception as сбой:                      # noqa: BLE001
            записать_в_лог(traceback.format_exc())
            self._беда("Что-то пошло не так: %s" % сбой, код=500)

    def _настройки(self, тело):
        ключ = (тело.get("ключ") or "").strip()
        настройки = прочитать_настройки()
        настройки["ключ"] = ключ
        сохранить_настройки(настройки)
        применить_ключ(ключ)
        if not ключ:
            os.environ.pop("ANTHROPIC_API_KEY", None)
        self._json({"ключ_есть": ключ_есть()})

    def _разбор_текста(self, тело):
        """Первый шаг: понять, кто с кем разговаривает."""
        сообщения, явная = разобрать_присланное(тело)
        if not сообщения:
            self._беда("Не нашёл в этом тексте ни одного сообщения. "
                       "Скопируй переписку из Телеграма или размечи строками "
                       "«я:» и «она:».")
            return

        двое, групповой = export_parser.two_sides(сообщения)
        if явная:
            двое = [export_parser.МОЯ_СТОРОНА, export_parser.ЕЁ_СТОРОНА]
        if len(двое) < 2:
            self._беда("Нашёл только одного собеседника — разбирать нечего.")
            return

        with _замок:
            разобранное.clear()
            разобранное["сообщения"] = сообщения
        self._json({"стороны": двое, "явная": явная,
                    "групповой": групповой, "сколько": len(сообщения),
                    "мало": len(сообщения) < МИНИМУМ})

    def _разбор_целиком(self, тело):
        """Второй шаг: цифры, а следом — разбор от Claude."""
        with _замок:
            сообщения = разобранное.get("сообщения")
        if not сообщения:
            self._беда("Переписка потерялась — вставь её заново.")
            return

        я = (тело.get("я") or "").strip()
        # Ту же пару, что показали на экране, и берём: в групповом чате
        # participants вернул бы третьего, и разбор поехал бы не про тех.
        двое, _групповой = export_parser.two_sides(сообщения)
        if {export_parser.МОЯ_СТОРОНА, export_parser.ЕЁ_СТОРОНА} <= set(двое) \
                or я in (export_parser.МОЯ_СТОРОНА, export_parser.ЕЁ_СТОРОНА):
            двое = [export_parser.МОЯ_СТОРОНА, export_parser.ЕЁ_СТОРОНА]
        if я not in двое:
            self._беда("Не понял, кто из них ты.")
            return
        она = двое[1] if двое[0] == я else двое[0]

        итог = metrics.analyse(сообщения, я, она)
        рамка = frame.определить(сообщения, я, она, итог)
        if frame.стоп(рамка):
            # Правило одно на бот, консоль и окно: после отказа советов нет.
            # К модели не идём вовсе — её ответ всё равно не был бы показан.
            self._json(отчёт_в_json(итог, рамка=рамка))
            return
        if not тело.get("с_ии") or not ключ_есть():
            self._json(отчёт_в_json(итог, рамка=рамка))
            return

        try:
            # Импорт здесь: цифры считаются на голой стандартной библиотеке,
            # и без разбора от ИИ ни anthropic, ни pydantic не нужны вовсе.
            import analysis
        except ImportError:
            self._json(отчёт_в_json(
                итог, рамка=рамка,
                ошибка_ии="Нет библиотек для разбора: запусти "
                          "«Установить библиотеки.bat» или "
                          "pip install -r requirements.txt"))
            return
        цель = texts.ЦЕЛИ.get(тело.get("цель"), "разобраться, что я делаю не так")
        try:
            отобранное = analysis.выборка(сообщения, я, она)
            разбор = analysis.разобрать(None, итог, цель,
                                        отобранное=отобранное, рамка=рамка)
        except analysis.ОшибкаРазбора as сбой:
            self._json(отчёт_в_json(итог, рамка=рамка, ошибка_ии=str(сбой)))
            return
        self._json(отчёт_в_json(итог, разбор_ии=разбор, рамка=рамка))


# --------------------------------------------------------------------------
# Запуск
# --------------------------------------------------------------------------

def сторож(сервер):
    """Гасит программу, если страницу закрыли."""
    while True:
        time.sleep(5)
        if time.time() - последний_стук > ТИШИНА_ДО_ВЫХОДА:
            записать_в_лог("страница молчит — выхожу")
            сервер.shutdown()
            return


def main():
    разбор = argparse.ArgumentParser(description="Окно разбора переписки.")
    разбор.add_argument("--порт", type=int, default=0,
                        help="0 — выбрать свободный самому")
    разбор.add_argument("--без-браузера", dest="без_браузера",
                        action="store_true", help="не открывать браузер")
    разбор.add_argument("--ключ", default="", help="ключ доступа (для проверок)")
    аргументы = разбор.parse_args()

    global ключ_доступа
    if аргументы.ключ:
        ключ_доступа = аргументы.ключ

    применить_ключ(прочитать_настройки().get("ключ"))

    сервер = ThreadingHTTPServer(("127.0.0.1", аргументы.порт), Окно)
    порт = сервер.server_address[1]
    адрес = "http://127.0.0.1:%d/?k=%s" % (порт, ключ_доступа)

    print(адрес, flush=True)
    записать_в_лог("запуск на порту %d" % порт)

    threading.Thread(target=сторож, args=(сервер,), daemon=True).start()
    if not аргументы.без_браузера:
        threading.Timer(0.4, webbrowser.open, args=(адрес,)).start()

    try:
        сервер.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        сервер.server_close()
        записать_в_лог("выход")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SystemExit:
        raise
    except Exception:                                  # noqa: BLE001
        записать_в_лог(traceback.format_exc())
        raise
