#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Отчёт по переписке в консоли — без Телеграма и без ИИ.

Это рабочий инструмент отладки: на настоящей выгрузке сразу видно,
верно ли разобрались имена, даты и авторы. Всё, что печатается здесь,
бот показывает теми же словами — текст отчёта собирается одной функцией
на оба случая.

    python report.py --from result.json
    python report.py --from ChatExport_2026-09-13 --me "Иван"
    python report.py --from result.json --me "Иван" --ии

Второй способ — по переписке, скопированной из Телеграма в файл:

    python report.py --вставка кусок.txt --me "Иван"
"""

import argparse
import os
import sys

import console          # noqa: F401  — правит вывод на Windows при импорте
import metrics
import parser as export_parser

ПОЛОСА = 22


def _полоска(доля):
    закрашено = int(round(доля * ПОЛОСА))
    return "█" * закрашено + "·" * (ПОЛОСА - закрашено)


def _строка_метрик(итог):
    м = итог["метрики"]
    вр = metrics.по_русски_время
    строки = [
        "Сообщений:        %d  (твоих %d, её %d)"
        % (итог["всего"], м["моих_сообщений"], м["её_сообщений"]),
        "Разговоров:       %d  (из них начала она — %d из %d засчитанных)"
        % (м["разговоров"], м["начала_она"], м["начал_кто_то"]),
        "Отвечает за:      она %s, ты %s"
        % (вр(м["её_ответ_сек"]), вр(м["мой_ответ_сек"])),
        "Длина сообщения:  её %s, твоя %s"
        % (м["её_длина"] or "?", м["моя_длина"] or "?"),
    ]
    if м["её_вопросы"] is not None:
        строки.append("Её вопросов:      %d%% сообщений"
                      % round(м["её_вопросы"] * 100))
    if м["её_эмоции"] is not None:
        строки.append("Живость:          %d%% её сообщений со смехом или эмодзи"
                      % round(м["её_эмоции"] * 100))
    строки.append("Обрывается на тебе: %d %s из %d"
                  % (м["оборвалось_на_мне"],
                     metrics.склонение(м["оборвалось_на_мне"], "разговор",
                                       "разговора", "разговоров"),
                     м["разговоров"]))
    if м["ночных"]:
        строки.append("Ночных сообщений: %d%%" % round(м["ночных"] * 100))
    return строки


def текст_отчёта(итог, подробно=True):
    """Готовый отчёт обычным текстом. Его же отправляет бот."""
    строки = []
    индекс = итог["индекс"]
    строки.append("Разбор переписки: %s и %s" % (итог["я"], итог["она"]))
    if итог["первое"] and итог["последнее"]:
        строки.append("С %s по %s — %d %s, %d %s."
                      % (итог["первое"].strftime("%d.%m.%Y"),
                         итог["последнее"].strftime("%d.%m.%Y"),
                         итог["дней"],
                         metrics.склонение(итог["дней"], "день", "дня", "дней"),
                         итог["всего"],
                         metrics.склонение(итог["всего"], "сообщение",
                                           "сообщения", "сообщений")))
    строки.append("")

    if индекс is None:
        строки.append("Данных слишком мало, чтобы делать выводы.")
        return "\n".join(строки)

    сейчас = metrics.сейчас(итог)
    if сейчас != индекс:
        строки.append("ИНДЕКС ВОВЛЕЧЁННОСТИ СЕЙЧАС: %d из 100" % сейчас)
        строки.append("(за всё время общения — %d)" % индекс)
    else:
        строки.append("ИНДЕКС ВОВЛЕЧЁННОСТИ: %d из 100" % индекс)
    строки.append(metrics.словами(итог))
    строки.append("")
    строки.append("Из чего сложилось за всё время:")
    for пункт in итог["разбивка"]:
        строки.append("  %-11s %s  %2d из %-2d  %s"
                      % (пункт["фактор"], _полоска(пункт["балл"]),
                         round(пункт["вклад"]), пункт["потолок"],
                         пункт["словами"]))

    тренд = итог["тренд"]
    if тренд:
        строки.append("")
        знак = "+" if тренд["разница"] > 0 else ""
        строки.append("Динамика: начало %d → конец %d (%s%d)"
                      % (тренд["начало"], тренд["конец"], знак, тренд["разница"]))

    пропущено = metrics.не_посчитано(итог)
    if пропущено:
        строки.append("")
        строки.append("Не посчитано — в этом тексте для них нет данных:")
        for имя, словами in пропущено:
            строки.append("  %-11s %s" % (имя, словами))
        строки.append("Их вес разошёлся по остальным факторам. Даты и полная "
                      "история есть в выгрузке — с ней картина будет полнее.")

    if подробно:
        строки.append("")
        строки.append("Цифры:")
        строки.extend("  " + строка for строка in _строка_метрик(итог))

    строки.append("")
    строки.append("Это статистика переписки, а не измерение чувств: она "
                  "описывает, как идёт общение, и ничего не знает о человеке.")
    return "\n".join(строки)


def выбрать_меня(сообщения, имя):
    """Определяет, кто из двоих — пользователь."""
    двое, групповой = export_parser.two_sides(сообщения)
    if len(двое) < 2:
        raise SystemExit("В переписке меньше двух собеседников — разбирать нечего.")
    if групповой:
        print("! Похоже, это групповой чат. Разбор рассчитан на переписку "
              "один на один, цифры будут условными.\n", file=sys.stderr)
    if имя:
        совпало = [кто for кто in двое if кто.lower() == имя.lower().strip()]
        if not совпало:
            raise SystemExit("В переписке нет «%s». Есть: %s."
                             % (имя, " и ".join(двое)))
        я = совпало[0]
    else:
        я = двое[0]
        print("! Кто из вас ты, не сказано — считаю, что «%s». "
              "Если наоборот, добавь --me \"%s\".\n" % (я, двое[1]),
              file=sys.stderr)
    она = двое[1] if двое[0] == я else двое[0]
    return я, она


def main():
    разбор = argparse.ArgumentParser(
        description="Отчёт по переписке из выгрузки Телеграма.")
    разбор.add_argument("--from", dest="откуда", default="",
                        help="result.json, messages.html, лог .txt или папка выгрузки")
    разбор.add_argument("--вставка", dest="вставка", default="",
                        help="файл с перепиской, скопированной из Телеграма")
    разбор.add_argument("--me", dest="я", default="",
                        help="твоё имя в переписке (как в выгрузке)")
    разбор.add_argument("--ии", action="store_true",
                        help="дополнить разбором от Claude (нужен ANTHROPIC_API_KEY)")
    разбор.add_argument("--цель", default="разобраться, что я делаю не так",
                        help="чего ты хочешь добиться — для советов ИИ")
    аргументы = разбор.parse_args()

    источник = аргументы.вставка or аргументы.откуда
    if not источник:
        raise SystemExit("Укажи --from (выгрузка) или --вставка (текст).")
    if not os.path.exists(источник):
        raise SystemExit("Не нашёл: %s" % источник)

    явная = False
    if аргументы.вставка:
        сообщения, явная = export_parser.read_pasted(
            export_parser.прочитать_текст(источник))
    else:
        сообщения = export_parser.read_export(источник)
    if not сообщения:
        raise SystemExit("Не нашёл в этом тексте ни одного сообщения.")

    if явная:
        # Разметили «я:» и «она:» — спрашивать, кто есть кто, незачем.
        я, она = export_parser.МОЯ_СТОРОНА, export_parser.ЕЁ_СТОРОНА
    else:
        я, она = выбрать_меня(сообщения, аргументы.я)
    итог = metrics.analyse(сообщения, я, она)
    print(текст_отчёта(итог))

    if аргументы.ии:
        import analysis          # импорт здесь: без --ии ключ не нужен
        print()
        print(analysis.текст_разбора(
            analysis.разобрать(сообщения, итог, аргументы.цель)))


if __name__ == "__main__":
    raise SystemExit(main())
