def _сколько_разговоров(число):
    return metrics.склонение(число, "разговор", "разговора", "разговоров")


def наблюдения(итог, рамка=None):
    """Факты с числами, из которых вывод очевиден сам.

    Восемь полосок человек не читает: «скорость 15 из 15» рядом
    с «инициатива 3 из 20» выглядит кашей. А «она начала 2 разговора
    из 32» — это уже мысль, и она про то же самое.

    Ни оценок, ни советов: бот показывает, что видно, вывод делает
    человек. Слова «стоит», «советую», «попробуй» здесь не встречаются,
    и это проверяется тестом, чтобы правило не размылось при следующей
    правке формулировок.
    """
    м = итог["метрики"]
    найдено = []                     # (насколько выбивается, строка)

    if м["начал_кто_то"] >= metrics.МИНИМУМ_НАБЛЮДЕНИЙ:
        доля = м["начала_она"] / м["начал_кто_то"]
        найдено.append((1 - доля, "она начала %d %s из %d — остальные начинал ты"
                        % (м["начала_она"], _сколько_разговоров(м["начала_она"]),
                           м["начал_кто_то"])))

    if м["разговоров"] >= metrics.МИНИМУМ_НАБЛЮДЕНИЙ:
        доля = м["оборвалось_на_мне"] / м["разговоров"]
        найдено.append((доля, "%d %s из %d закончились твоим сообщением"
                        % (м["оборвалось_на_мне"],
                           _сколько_разговоров(м["оборвалось_на_мне"]),
                           м["разговоров"])))

    if м["её_ответ_сек"] is not None and м["мой_ответ_сек"] is not None:
        быстрее = м["её_ответ_сек"] <= м["мой_ответ_сек"]
        найдено.append((0.45 if быстрее else 0.75,
                        "отвечает за %s — %s тебя"
                        % (metrics.по_русски_время(м["её_ответ_сек"]),
                           "быстрее" if быстрее else "медленнее")))

    if м["её_вопросы"] is not None:
        найдено.append((1 - min(м["её_вопросы"] / 0.25, 1.0),
                        "вопросы — %d%% её сообщений"
                        % round(м["её_вопросы"] * 100)))

    if м["её_эмоции"] is not None:
        найдено.append((1 - min(м["её_эмоции"] / 0.30, 1.0),
                        "смех или эмодзи — %d%% её сообщений"
                        % round(м["её_эмоции"] * 100)))

    if м["её_длина"] and м["моя_длина"]:
        найдено.append((1 - min(м["её_длина"] / м["моя_длина"], 1.0),
                        "её сообщения — %d символов против твоих %d"
                        % (м["её_длина"], м["моя_длина"])))

    if м["ночных"] and м["ночных"] >= 0.3:
        найдено.append((м["ночных"], "%d%% переписки — после полуночи"
                        % round(м["ночных"] * 100)))

    тренд = итог.get("тренд") or {}
    сдвиги = тренд.get("по_факторам") or {}
    # Баллы, а не вклады: вклад пересчитан под набор факторов своей
    # половины, и сравнивать их между половинами нельзя.
    просело = sorted(((было - стало, имя) for имя, (было, стало) in сдвиги.items()
                      if было - стало >= 0.25), reverse=True)
    if просело:
        _упало, имя = просело[0]
        было, стало = сдвиги[имя]
        найдено.append((0.95, "%s — в начале переписки %d%% от максимума, "
                        "сейчас %d%%"
                        % (metrics.ФАКТОРЫ[имя][3], round(было * 100),
                           round(стало * 100))))

    # Первым идёт то, что сильнее выбивается: шестое наблюдение уже
    # не читают, поэтому важное должно попасть в первые пять.
    найдено.sort(key=lambda пара: -пара[0])
    return [строка for _вес, строка in найдено[:5]]


