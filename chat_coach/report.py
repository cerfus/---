_БЛОКИ = "▁▂▃▄▅▆▇█"


def линия(значения, потолок=None):
    """Спарклайн блоками. None — дыра, а не ноль.

    Дыра честнее выдуманной точки: неделя, где сообщений почти не было,
    ничего про интерес не говорит, и рисовать там уровень нельзя.
    """
    живые = [з for з in значения if з is not None]
    if not живые:
        return ""
    верх = потолок or max(живые) or 1
    куски = []
    for з in значения:
        if з is None:
            куски.append("·")
            continue
        уровень = int(round(min(з / верх, 1.0) * (len(_БЛОКИ) - 1)))
        куски.append(_БЛОКИ[уровень])
    return "".join(куски)


def куда_идёт(итог, недели):
    """Две линии по неделям: индекс и объём. Строки для блока «Куда идёт».

    Линии именно две и порознь. Шкалы у них разные — сотня баллов
    и сообщения в неделю, — а совмещать разные шкалы на одной оси
    нельзя: это самый частый способ соврать графиком.

    Подписаны только концы. Число над каждой точкой не читают.
    """
    if len(недели) < 3:
        return []

    индексы = [индекс for _начало, индекс, _сколько in недели]
    объёмы = [сколько for _начало, _индекс, сколько in недели]

    строки = []
    живые = [(начало, индекс) for начало, индекс, _с in недели
             if индекс is not None]
    if len(живые) >= 2:
        строки.append("Индекс:    %s" % линия(индексы, потолок=100))
        строки.append("           %s %d → %s %d из 100"
                      % (живые[0][0].strftime("%d.%m"), живые[0][1],
                         живые[-1][0].strftime("%d.%m"), живые[-1][1]))
    строки.append("Сообщений: %s" % линия(объёмы))
    строки.append("           %d в первую → %d в последнюю"
                  % (объёмы[0], объёмы[-1]))
    return строки


