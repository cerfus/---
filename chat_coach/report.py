# Как назвать нынешнее значение фактора и целевое — теми же единицами,
# в которых человек про это думает. Норма берётся из metrics.ФАКТОРЫ,
# так что «половина баллов» считается, а не выдумывается.
def _порог_инициативы(значение, цель, м):
    каждый = max(int(round(1 / цель)), 2) if цель else 0
    return ("она начала %d %s из %d. Половина баллов — с каждого %d-го"
            % (м["начала_она"], _сколько_разговоров(м["начала_она"]),
               м["начал_кто_то"], каждый))


def _порог_доли(подпись):
    def готово(значение, цель, _м):
        return "%s — %d%%. Половина баллов — с %d%%" % (
            подпись, round(значение * 100), round(цель * 100))
    return готово


def _порог_обрывов(значение, цель, м):
    return ("на тебе обрывается %d%% разговоров. Половина баллов — "
            "если не больше %d%%" % (round(значение * 100), round(цель * 100)))


ПОРОГИ = {
    "инициатива": _порог_инициативы,
    "вопросы": _порог_доли("вопросы в её сообщениях"),
    "эмоции": _порог_доли("смех и эмодзи у неё"),
    "баланс": _порог_доли("её доля в переписке"),
    "обрывы": _порог_обрывов,
}


def пороги(итог, сколько=3):
    """Арифметика разворота для самых слабых факторов.

    Не пророчество, а порог: что должно случиться, чтобы направление
    сменилось. Считается из metrics.ФАКТОРЫ — норма фактора известна,
    значит известна и половина.

    Фактор, который уже даёт половину баллов, сюда не попадает: нечего
    предлагать там, где и так неплохо.
    """
    найдено = []
    for пункт in итог.get("разбивка", ()):
        имя = пункт["фактор"]
        если_умеем = ПОРОГИ.get(имя)
        if если_умеем is None or пункт["балл"] >= 0.5:
            continue
        _вес, норма, штраф, _словами = metrics.ФАКТОРЫ[имя]
        цель = норма / 2
        значение = пункт["значение"]
        if значение is None:
            continue
        # У штрафных факторов «лучше» — это меньше, а не больше.
        уже_дошло = значение <= цель if штраф else значение >= цель
        if уже_дошло:
            continue
        найдено.append((пункт["балл"],
                        если_умеем(значение, цель, итог["метрики"])))
    найдено.sort(key=lambda пара: пара[0])
    return [строка for _балл, строка in найдено[:сколько]]


