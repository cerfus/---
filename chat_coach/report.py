ПОЛОСА = 22
ПОЛОСА_УЗКАЯ = 12          # для Телеграма: ширина телефона, а не консоли


def _полоска(доля, ширина=ПОЛОСА):
    закрашено = int(round(доля * ширина))
    return "█" * закрашено + "·" * (ширина - закрашено)


def цифры(итог):
    """Пары «подпись — значение». Их печатает консоль и показывает окно.

    Формат намеренно разделён: консоли нужны выровненные строки, окну —
    отдельные поля, а считаются они одинаково, и расходиться им нельзя.
    """
    м = итог["метрики"]
    вр = metrics.по_русски_время
    пары = [
        ("Сообщений", "%d (твоих %d, её %d)"
         % (итог["всего"], м["моих_сообщений"], м["её_сообщений"])),
        ("Разговоров", "%d (из них начала она — %d из %d засчитанных%s)"
         % (м["разговоров"], м["начала_она"], м["начал_кто_то"],
            # Иначе строка спорит с блоком «не посчитано»: там сказано, что
            # инициативу считать не по чему, а тут стоит бодрое «1 из 1».
            "" if м["начал_кто_то"] >= metrics.МИНИМУМ_НАБЛЮДЕНИЙ
            else ", этого мало для вывода")),
        ("Отвечает за", "она %s, ты %s"
         % (вр(м["её_ответ_сек"]), вр(м["мой_ответ_сек"]))),
        ("Длина сообщения", "её %s, твоя %s"
         % (м["её_длина"] or "?", м["моя_длина"] or "?")),
    ]
    if м["её_вопросы"] is not None:
        пары.append(("Её вопросов",
                     "%d%% сообщений" % round(м["её_вопросы"] * 100)))
    if м["её_эмоции"] is not None:
        пары.append(("Живость", "%d%% её сообщений со смехом или эмодзи"
                     % round(м["её_эмоции"] * 100)))
    пары.append(("Обрывается на тебе", "%d %s из %d"
                 % (м["оборвалось_на_мне"],
                    metrics.склонение(м["оборвалось_на_мне"], "разговор",
                                      "разговора", "разговоров"),
                    м["разговоров"])))
    if м["ночных"]:
        пары.append(("Ночных сообщений", "%d%%" % round(м["ночных"] * 100)))
    return пары


def _строка_метрик(итог):
    ширина = max(len(подпись) for подпись, _ in цифры(итог)) + 2
    return ["%-*s %s" % (ширина, подпись + ":", значение)
            for подпись, значение in цифры(итог)]


def текст_отчёта(итог, подробно=True, рамка=None):
    """Готовый отчёт обычным текстом. Его же отправляет бот.

    Рамка (см. frame.py) необязательна: без неё отчёт остаётся прежним,
    и старые вызывающие не ломаются. С ней он сначала говорит, что это
    вообще за переписка, и только потом показывает индекс — иначе цифра
    отвечает на вопрос, которого человек не задавал.
    """
    строки = []
    индекс = итог["индекс"]
    строки.append("Разбор переписки: %s и %s" % (итог["я"], итог["она"]))
    if итог["первое"] and итог["последнее"]:
        строки.append("С %s по %s — %d %s, %d %s."
                      % (итог["первое"].strftime("%d.%m.%Y"),
                         итог["последнее"].strftime("%d.%m.%Y"),
                         итог["дней"],
                         metrics.склонение(итог["дней"], "день", "дня", "дней"),
                         итог["всего"],
                         metrics.склонение(итог["всего"], "сообщение",
                                           "сообщения", "сообщений")))
    строки.append("")

    # Отказ идёт первым и до всяких цифр: если человек уже ответил, индекс
    # вовлечённости отвечает не на тот вопрос, каким бы он ни вышел.
    if frame.стоп(рамка):
        строки.append(frame.стоп_текст(рамка))
        строки.append("")
        строки.append("Цифры ниже оставляю — за ними ты и приходил.")
        строки.append("")

    if индекс is None:
        строки.append("Данных слишком мало, чтобы делать выводы.")
        return "\n".join(строки)

    сейчас = metrics.сейчас(итог)
    if сейчас != индекс:
        строки.append("ИНДЕКС ВОВЛЕЧЁННОСТИ СЕЙЧАС: %d из 100" % сейчас)
        строки.append("(за всё время общения — %d)" % индекс)
    else:
        строки.append("ИНДЕКС ВОВЛЕЧЁННОСТИ: %d из 100" % индекс)
    # Сначала — что это за переписка, потом что значит число: рамка
    # объясняет, ту ли линейку мы вообще приложили.
    если_рамка = "" if frame.стоп(рамка) else frame.коротко(рамка)
    if если_рамка:
        строки.append(если_рамка)
    вывод = frame.заголовок(итог, рамка)
    if вывод:
        строки.append(вывод)
    строки.append("")
    строки.append("Из чего сложилось за всё время:")
    for пункт in итог["разбивка"]:
        строки.append("  %-11s %s  %2d из %-2d  %s"
                      % (пункт["фактор"], _полоска(пункт["балл"]),
                         пункт["вклад_целым"], пункт["потолок"],
                         пункт["словами"]))

    тренд = итог["тренд"]
    if тренд:
        строки.append("")
        знак = "+" if тренд["разница"] > 0 else ""
        строки.append("Динамика: начало %d → конец %d (%s%d)"
                      % (тренд["начало"], тренд["конец"], знак, тренд["разница"]))

    пропущено = metrics.не_посчитано(итог)
    if пропущено:
        строки.append("")
        строки.append("Не посчитано — в этом тексте для них нет данных:")
        for имя, словами in пропущено:
            строки.append("  %-11s %s" % (имя, словами))
        строки.append("Их вес разошёлся по остальным факторам. Даты и полная "
                      "история есть в выгрузке — с ней картина будет полнее.")

    if подробно:
        строки.append("")
        строки.append("Цифры:")
        строки.extend("  " + строка for строка in _строка_метрик(итог))

    строки.append("")
    строки.append("Это статистика переписки, а не измерение чувств: она "
                  "описывает, как идёт общение, и ничего не знает о человеке.")
    return "\n".join(строки)


