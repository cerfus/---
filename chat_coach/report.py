"""
Отчёт по переписке в консоли — без Телеграма и без ИИ.

Это рабочий инструмент отладки: на настоящей выгрузке сразу видно,
верно ли разобрались имена, даты и авторы. Всё, что печатается здесь,
бот показывает теми же словами — текст отчёта собирается одной функцией
на оба случая.

    python report.py --from result.json
    python report.py --from ChatExport_2026-09-13 --me "Иван"
    python report.py --from result.json --me "Иван" --ии

Второй способ — по переписке, скопированной из Телеграма в файл:

    python report.py --вставка кусок.txt --me "Иван"
"""

