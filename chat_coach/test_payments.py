# -*- coding: utf-8 -*-
"""Проверка оплаты. Запуск: python test_payments.py

Ни Телеграма, ни сети: SuccessfulPayment подменяется простым объектом
с теми же полями. Главное, что здесь проверяется, — идемпотентность.
Телеграм повторяет апдейт, пока бот не ответит, и без защиты один платёж
лёг бы на счёт дважды; заметить такое по логам почти невозможно, а
чинить придётся руками в базе.
"""

import os
import shutil
import tempfile
from datetime import datetime

import console          # noqa: F401
import limits
import payments
import storage


def _база():
    папка = tempfile.mkdtemp()
    return storage.База(os.path.join(папка, "бот.sqlite3")), папка


class ОплатаЗвёздами:
    """То же, что SuccessfulPayment, но без Телеграма."""

    def __init__(self, чек, пакет="5", сумма=None, валюта="XTR"):
        self.telegram_payment_charge_id = чек
        self.invoice_payload = payments.в_payload(payments.ПАКЕТЫ[пакет])
        self.total_amount = сумма or payments.ПАКЕТЫ[пакет].звёзд
        self.currency = валюта


# --------------------------------------------------------------------------

def случай_витрина():
    """Пакеты согласованы сами с собой и растут по цене."""
    коды_совпадают = all(код == пакет.код
                         for код, пакет in payments.ПАКЕТЫ.items())
    все_положительные = all(пакет.разборов > 0 and пакет.звёзд > 0
                            for пакет in payments.ПАКЕТЫ.values())
    по_порядку = [payments.ПАКЕТЫ[к].звёзд for к in payments.ПОРЯДОК]
    ок = (коды_совпадают and все_положительные
          and set(payments.ПОРЯДОК) == set(payments.ПАКЕТЫ)
          and по_порядку == sorted(по_порядку)
          # Больше берёшь — дешевле штука, иначе большой пакет не нужен.
          and (по_порядку[-1] / payments.ПАКЕТЫ["40"].разборов
               < по_порядку[0] / payments.ПАКЕТЫ["5"].разборов))
    return ок, "витрина: цены %s" % по_порядку


def случай_payload():
    """Payload туда-обратно, а чужой — не падение, а None."""
    пакет = payments.ПАКЕТЫ["15"]
    строка = payments.в_payload(пакет)
    чужие = ["", None, "пакет:", "пакет:999", "мусор", "пакет:15лишнее",
             "разбор:15"]
    плохие = [ч for ч in чужие if payments.из_payload(ч) is not None]
    ок = (payments.из_payload(строка) == пакет
          and len(строка.encode("utf-8")) <= 128      # предел Телеграма
          and not плохие)
    return ок, "payload: %r, чужие прошли=%s" % (строка, плохие or "ничего")


def случай_зачисление():
    """Покупка кладёт разборы на счёт и видна в остатке."""
    база, папка = _база()
    try:
        пакет, зачли = payments.зачислить_звёзды(база, 7, ОплатаЗвёздами("ch1"))
        остаток = limits.остаток(база, 7, limits.РАЗБОР,
                                 сейчас=datetime(2026, 9, 15, 10, 0))
        ок = (зачли is True and пакет.код == "5"
              and остаток == {"бесплатно": 1, "куплено": 5})
        return ок, "зачисление: %s" % (остаток,)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_повтор_не_зачисляется():
    """Тот же чек дважды — деньги зачтены один раз.

    Это не выдуманный случай: Телеграм шлёт апдейт снова, если бот не
    ответил вовремя. Строка в payments должна остаться одна.
    """
    база, папка = _база()
    try:
        payments.зачислить_звёзды(база, 7, ОплатаЗвёздами("ch1"))
        _пакет, второй = payments.зачислить_звёзды(база, 7,
                                                   ОплатаЗвёздами("ch1"))
        payments.зачислить_звёзды(база, 7, ОплатаЗвёздами("ch2", пакет="15"))
        остаток = база.остаток_купленного(7, limits.РАЗБОР)
        with база._соединение() as соединение:
            строк = соединение.execute(
                "SELECT COUNT(*) AS с FROM payments").fetchone()["с"]
        ок = второй is False and остаток == 20 and строк == 2
        return ок, "повтор: зачли второй раз=%s, остаток=%d, строк=%d" % (
            второй, остаток, строк)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_чужой_payload():
    """Оплата с непонятным payload ничего не зачисляет и не падает."""
    база, папка = _база()
    try:
        оплата = ОплатаЗвёздами("ch9")
        оплата.invoice_payload = "пакет:999"
        пакет, зачли = payments.зачислить_звёзды(база, 7, оплата)
        ок = (пакет is None and зачли is False
              and база.остаток_купленного(7, limits.РАЗБОР) == 0)
        return ок, "чужой payload: пакет=%s зачли=%s" % (пакет, зачли)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_сначала_бесплатное():
    """Порядок трат: сначала бесплатное, потом купленное, потом нечего."""
    база, папка = _база()
    try:
        когда = datetime(2026, 9, 15, 10, 0)
        payments.зачислить_звёзды(база, 7, ОплатаЗвёздами("ch1"))  # 5 разборов
        взяли = [limits.потратить(база, 7, limits.РАЗБОР, сейчас=когда)
                 for _ in range(7)]
        ок = взяли == ([limits.БЕСПЛАТНО] + [limits.ИЗ_ПАКЕТА] * 5 + [None])
        return ок, "порядок: %s" % (взяли,)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_возврат_туда_же():
    """Сорвавшийся разбор возвращается в тот карман, откуда его взяли.

    Вернуть бесплатную попытку вместо купленной — значит подарить разбор,
    и по логам этого не увидеть.
    """
    база, папка = _база()
    try:
        когда = datetime(2026, 9, 15, 10, 0)
        payments.зачислить_звёзды(база, 7, ОплатаЗвёздами("ch1"))
        limits.потратить(база, 7, limits.РАЗБОР, сейчас=когда)   # бесплатный
        откуда = limits.потратить(база, 7, limits.РАЗБОР, сейчас=когда)
        limits.вернуть(база, 7, limits.РАЗБОР, откуда, сейчас=когда)
        после = limits.остаток(база, 7, limits.РАЗБОР, сейчас=когда)
        ок = (откуда == limits.ИЗ_ПАКЕТА
              and после == {"бесплатно": 0, "куплено": 5})
        return ок, "возврат: взяли=%s, стало %s" % (откуда, после)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_возврат_денег():
    """Возврат снимает начисленное, но не уводит остаток в минус.

    Поиск платежа и снятие разделены нарочно: между ними бот зовёт
    Телеграм. Сначала деньги, потом уже наш счёт.
    """
    база, папка = _база()
    try:
        когда = datetime(2026, 9, 15, 10, 0)
        payments.зачислить_звёзды(база, 7, ОплатаЗвёздами("ch1"))  # 5
        for _ in range(4):
            limits.потратить(база, 7, limits.РАЗБОР, сейчас=когда)
        # Потрачен один бесплатный и три купленных, купленных осталось два.
        кому, пакет = payments.платёж_для_возврата(база, "ch1")
        сняли = payments.отметить_возврат(база, "ch1", пакет)
        остаток = база.остаток_купленного(7, limits.РАЗБОР)
        повторно = payments.платёж_для_возврата(база, "ch1")
        нет_такого = payments.платёж_для_возврата(база, "чего-то-нет")
        ок = (кому == 7 and пакет.код == "5" and сняли is True
              and остаток == 0
              and повторно == (None, None) and нет_такого == (None, None))
        return ок, "возврат денег: кому=%s остаток=%d повторно=%s" % (
            кому, остаток, повторно)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_забыть_платежи():
    """/удалить стирает купленное, а платежи обезличивает, а не удаляет.

    Без строки платежа невозможен возврат денег, поэтому обещание «сотру
    всё» здесь имеет ровно одно исключение — и оно названо в тексте
    команды, а не спрятано.
    """
    база, папка = _база()
    try:
        payments.зачислить_звёзды(база, 7, ОплатаЗвёздами("ch1"))
        база.забыть(7)
        платёж = база.найти_платёж(payments.ПРОВАЙДЕР_STARS, "ch1")
        ок = (база.остаток_купленного(7, limits.РАЗБОР) == 0
              and платёж is not None and платёж["user_id"] == 0)
        return ок, "забыть: остаток=0, платёж чей=%s" % (
            платёж and платёж["user_id"])
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def main():
    случаи = (случай_витрина, случай_payload, случай_зачисление,
              случай_повтор_не_зачисляется, случай_чужой_payload,
              случай_сначала_бесплатное, случай_возврат_туда_же,
              случай_возврат_денег, случай_забыть_платежи)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
