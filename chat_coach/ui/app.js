function вБазу64(файл) {
  return new Promise((готово, мимо) => {
    const чтец = new FileReader();
    чтец.onload = () => готово(чтец.result.split(",")[1] || "");
    чтец.onerror = () => мимо(new Error("Не смог прочитать файл."));
    чтец.readAsDataURL(файл);
  });
}

