// ------------------------------------------------------------------ отчёт

function показатьОтчёт(о) {
  const сейчас = о.сейчас === null ? о.индекс : о.сейчас;
  э("индекс").textContent = сейчас === null ? "—" : сейчас;
  э("индекс-подпись").textContent =
    (о.сейчас !== null && о.сейчас !== о.индекс)
      ? "из 100 сейчас · " + о.индекс + " за всё время"
      : "из 100";
  // Что это за переписка — раньше вердикта: он про число, а рамка про то,
  // считает ли это число вообще то, за чем человек пришёл.
  const рамка = э("рамка");
  рамка.textContent = о.рамка ? о.рамка.коротко : "";
  рамка.hidden = !рамка.textContent;

  const стоп = э("рамка-стоп");
  стоп.hidden = !(о.рамка && о.рамка.стоп);
  стоп.innerHTML = стоп.hidden ? "" : "<h3>Стоп</h3>"
    + о.рамка.стоп_абзацы.map((абзац) => "<p>" + экран(абзац) + "</p>").join("");

  э("вердикт").textContent = о.вердикт;
  э("вердикт").hidden = !о.вердикт;
  // Строка приходит готовой: окончания по-русски считает сервер.
  э("период").textContent = о.период;

  const тренд = э("тренд");
  if (о.тренд) {
    const вверх = о.тренд.разница > 0;
    тренд.textContent = (вверх ? "▲ " : "▼ ") + "было " + о.тренд.начало
      + ", стало " + о.тренд.конец
      + " (" + (вверх ? "+" : "") + о.тренд.разница + ")";
    тренд.className = "дельта " + (вверх ? "вверх" : "вниз");
    тренд.hidden = false;
  } else {
    тренд.hidden = true;
  }

  // Полоски: одна гамма на все факторы, различает длина. Число стоит рядом
  // с каждой — значение читается, даже если цвет не различить вовсе.
  const где = э("факторы");
  где.innerHTML = "";
  о.разбивка.forEach((пункт) => {
    const строка = document.createElement("div");
    строка.className = "фактор";
    строка.title = пункт.словами;
    строка.innerHTML =
      '<div class="фактор-имя">' + экран(пункт.фактор)
        + "<span>" + экран(пункт.словами) + "</span></div>"
      + '<div class="дорожка"><div class="заливка"></div></div>'
      + '<div class="фактор-число">' + пункт.вклад
        + " из " + пункт.потолок + "</div>";
    строка.querySelector(".заливка").style.width =
      Math.round(пункт.балл * 100) + "%";
    где.append(строка);
  });

  const пробелы = э("пробелы");
  пробелы.hidden = о.не_посчитано.length === 0;
  э("пробелы-список").innerHTML = о.не_посчитано
    .map((п) => "<li><b>" + экран(п.фактор) + "</b> — " + экран(п.словами) + "</li>")
    .join("");

  э("цифры").innerHTML = о.цифры
    .map((п) => "<tr><td>" + экран(п.подпись) + "</td><td>"
                + экран(п.значение) + "</td></tr>")
    .join("");

  показатьИИ(о);
  э("отчёт").hidden = false;
  э("отчёт").scrollIntoView({ behavior: "smooth", block: "start" });
}

function экран(что) {
  const узел = document.createElement("span");
  узел.textContent = что === null || что === undefined ? "" : String(что);
  return узел.innerHTML;
}

function показатьИИ(о) {
  const где = э("ии");
  где.innerHTML = "";
  где.hidden = false;

  if (о.рамка && о.рамка.стоп) {
    // Стоп-блок уже стоит наверху отчёта, а к модели мы не ходили вовсе.
    где.innerHTML = "<h3>Разбор сообщений</h3><p class=\"пояснение\">"
      + "Не делался — причина в блоке «Стоп» выше.</p>";
    return;
  }
  if (о.ошибка_ии) {
    где.innerHTML = "<h3>Разбор сообщений</h3><p class=\"пояснение\">"
      + экран(о.ошибка_ии) + "</p>";
    return;
  }
  if (!о.ии) {
    где.innerHTML = "<h3>Разбор сообщений</h3><p class=\"пояснение\">"
      + (о.ключ_есть
          ? "Не запрашивался — сними или поставь галочку и нажми ещё раз."
          : "Нужен ключ Claude — поле внизу. Цифры выше посчитаны без него.")
      + "</p>";
    return;
  }

  const р = о.ии;
  if (р.стоп) {
    // Виден отказ — никаких тактик, только это.
    где.innerHTML = '<div class="стоп"><h3>Стоп</h3><p>'
      + экран(р.стоп_причина || р.коротко) + "</p><p class=\"пояснение\">"
      + "Здесь нет смысла искать подход: человек уже ответил. "
      + "Лучшее, что можно сделать, — оставить в покое.</p></div>";
    return;
  }

  let куски = "<h3>Разбор сообщений</h3><p>" + экран(р.коротко) + "</p>";
  if (р.что_работает.length) {
    куски += "<h3>Что у тебя работает</h3><ul class=\"список\">"
      + р.что_работает.map((п) => "<li>" + экран(п) + "</li>").join("")
      + "</ul>";
  }
  if (р.что_мешает.length) {
    куски += "<h3>Что мешает</h3>";
    р.что_мешает.forEach((совет) => {
      куски += '<div class="совет"><b>' + экран(совет.что_не_так) + "</b>"
        + (совет.цитата
            ? '<p class="цитата"><i>было:</i> «' + экран(совет.цитата) + "»</p>"
            : "")
        + (совет.как_лучше
            ? '<p class="цитата"><i>лучше:</i> «' + экран(совет.как_лучше) + "»</p>"
            : "")
        + "</div>";
    });
  }
  if (р.следующий_шаг) {
    куски += '<div class="шаг"><b>Следующий шаг.</b> '
      + экран(р.следующий_шаг) + "</div>";
  }
  где.innerHTML = куски;
}

// ------------------------------------------------------------------- ключ

э("сохранить-ключ").onclick = async () => {
  try {
    const данные = await запрос("/api/settings", { ключ: э("ключ").value });
    э("ключ").value = "";
    обновитьКлюч(данные.ключ_есть);
    беда(данные.ключ_есть ? "Ключ сохранён." : "Ключ убран.");
  } catch (сбой) {
    беда(сбой.message);
  }
};

function обновитьКлюч(есть) {
  э("ключ-статус").textContent = есть ? "Ключ на месте." : "Ключа нет.";
}

fetch("/api/settings?k=" + encodeURIComponent(КЛЮЧ))
  .then((о) => о.json())
  .then((д) => обновитьКлюч(д.ключ_есть))
  .catch(() => обновитьКлюч(false));

