// --------------------------------------------------------------------------
// Линии по неделям
// --------------------------------------------------------------------------
//
// Линии две и порознь: у индекса шкала 0–100, у объёма своя, а совмещать
// разные шкалы на одной оси — самый частый способ соврать графиком.
// Подписаны только концы: число над каждой точкой не читают.

const ШИРИНА = 600;          // система координат; по ширине SVG тянется сам
const ВЫСОТА = 88;
const ПОЛЯ = { верх: 16, низ: 20, бок: 10 };
const НЕДЕЛЬ_ДЛЯ_ЛИНИИ = 3;  // на двух точках линия ничего не показывает

function svg(имя, свойства) {
  const узел = document.createElementNS("http://www.w3.org/2000/svg", имя);
  Object.entries(свойства || {}).forEach(([ключ, значение]) =>
    узел.setAttribute(ключ, значение));
  return узел;
}

function точкиЛинии(значения, потолок) {
  const шагов = Math.max(значения.length - 1, 1);
  const поле = { ш: ШИРИНА - ПОЛЯ.бок * 2, в: ВЫСОТА - ПОЛЯ.верх - ПОЛЯ.низ };
  return значения.map((з, номер) => ({
    x: ПОЛЯ.бок + (поле.ш * номер) / шагов,
    y: з === null ? null
      : ПОЛЯ.верх + поле.в * (1 - Math.min(з / потолок, 1)),
  }));
}

function путьЛинии(точки) {
  // Разрыв остаётся разрывом: линия рвётся, а не проходит через дыру.
  let d = "";
  let вести = false;
  точки.forEach((т) => {
    if (т.y === null) { вести = false; return; }
    d += (вести ? " L " : " M ") + т.x.toFixed(1) + " " + т.y.toFixed(1);
    вести = true;
  });
  return d;
}

function нарисоватьЛинию(куда, значения, потолок, подписи, какПодписать) {
  куда.innerHTML = "";
  // Масштаб равномерный (preserveAspectRatio по умолчанию): растяни SVG
  // по одной ширине — и кружки концов станут эллипсами. Толщину линии
  // держит vector-effect в стилях, ей масштаб не страшен.
  const холст = svg("svg", {
    viewBox: "0 0 " + ШИРИНА + " " + ВЫСОТА, role: "img",
  });
  const точки = точкиЛинии(значения, потолок);
  const живые = точки
    .map((т, номер) => ({ т: т, номер: номер }))
    .filter((пара) => пара.т.y !== null);

  холст.append(svg("line", {
    class: "ось", x1: 0, y1: ВЫСОТА - ПОЛЯ.низ,
    x2: ШИРИНА, y2: ВЫСОТА - ПОЛЯ.низ,
  }));
  холст.append(svg("path", { class: "линия", d: путьЛинии(точки) }));

  // Подписаны только концы — и значением, и датой. Дата стоит под своей
  // точкой, а не в углу холста: у индекса данные могут кончиться раньше
  // последней недели, и дата в углу подписывала бы не ту точку.
  const концы = живые.length > 1 ? [живые[0], живые[живые.length - 1]]
    : живые.slice(0, 1);
  концы.forEach((пара, который) => {
    const слева = который === 0 && концы.length > 1;
    холст.append(svg("circle", {
      class: "конец", cx: пара.т.x, cy: пара.т.y, r: 4,
    }));
    const число = svg("text", {
      class: "подпись-конца", x: пара.т.x + (слева ? 8 : -8),
      y: пара.т.y - 7, "text-anchor": слева ? "start" : "end",
    });
    число.textContent = какПодписать(значения[пара.номер]);
    холст.append(число);
    const дата = svg("text", {
      class: "подпись-даты", x: пара.т.x, y: ВЫСОТА - 6,
      "text-anchor": слева ? "start" : "end",
    });
    дата.textContent = подписи[пара.номер];
    холст.append(дата);
  });

  холст.append(svg("line", { class: "прицел", x1: 0, y1: ПОЛЯ.верх - 6,
                             x2: 0, y2: ВЫСОТА - ПОЛЯ.низ, hidden: "hidden" }));
  куда.append(холст);
  return { холст: холст, коробка: куда, точки: точки };
}

function показатьНедели(недели) {
  const блок = э("куда");
  блок.hidden = недели.length < НЕДЕЛЬ_ДЛЯ_ЛИНИИ;
  if (блок.hidden) { return; }

  const подписи = недели.map((н) => н.подпись);
  const объёмы = недели.map((н) => н.сколько);
  const индекс = нарисоватьЛинию(
    э("линия-индекса"), недели.map((н) => н.индекс), 100, подписи,
    (з) => з + " из 100");
  const объём = нарисоватьЛинию(
    э("линия-объёма"), объёмы, Math.max(...объёмы, 1), подписи,
    (з) => String(з));

  // Прицел общий: неделя под курсором подсвечивается на обеих линиях —
  // ось времени у них одна, и смотреть их надо вместе.
  const всплывашка = э("всплывашка");
  const подсветить = (номер) => {
    [индекс, объём].forEach((линия) => {
      const прицел = линия.холст.querySelector(".прицел");
      if (номер === null) { прицел.setAttribute("hidden", "hidden"); return; }
      прицел.removeAttribute("hidden");
      прицел.setAttribute("x1", линия.точки[номер].x);
      прицел.setAttribute("x2", линия.точки[номер].x);
    });
    if (номер === null) { всплывашка.hidden = true; return; }
    const н = недели[номер];
    всплывашка.hidden = false;
    всплывашка.textContent = н.подпись + " — "
      + (н.индекс === null ? "мало данных" : "индекс " + н.индекс)
      + ", " + н.сколько + " сообщ.";
  };

  [индекс, объём].forEach((линия) => {
    линия.холст.addEventListener("mousemove", (событие) => {
      const рамка = линия.холст.getBoundingClientRect();
      const доля = (событие.clientX - рамка.left) / рамка.width;
      const номер = Math.min(недели.length - 1, Math.max(0,
        Math.round(доля * (недели.length - 1))));
      подсветить(номер);
      // Считаем от коробки: offsetTop есть у HTML-элемента, у SVG его нет.
      всплывашка.style.left = (событие.clientX - рамка.left) + "px";
      всплывашка.style.top = линия.коробка.offsetTop + "px";
    });
    линия.холст.addEventListener("mouseleave", () => подсветить(null));
  });
}


function показатьОтчёт(о) {
  const сейчас = о.сейчас === null ? о.индекс : о.сейчас;
  э("индекс").textContent = сейчас === null ? "—" : сейчас;
  э("индекс-подпись").textContent =
    (о.сейчас !== null && о.сейчас !== о.индекс)
      ? "из 100 сейчас · " + о.индекс + " за всё время"
      : "из 100";
  // Что это за переписка — раньше вердикта: он про число, а рамка про то,
  // считает ли это число вообще то, за чем человек пришёл.
  const рамка = э("рамка");
  рамка.textContent = о.рамка ? о.рамка.коротко : "";
  рамка.hidden = !рамка.textContent;

  const стоп = э("рамка-стоп");
  стоп.hidden = !(о.рамка && о.рамка.стоп);
  стоп.innerHTML = стоп.hidden ? "" : "<h3>Стоп</h3>"
    + о.рамка.стоп_абзацы.map((абзац) => "<p>" + экран(абзац) + "</p>").join("");

  э("вердикт").textContent = о.вердикт;
  э("вердикт").hidden = !о.вердикт;
  // Строка приходит готовой: окончания по-русски считает сервер.
  э("период").textContent = о.период;

  const тренд = э("тренд");
  if (о.тренд) {
    const вверх = о.тренд.разница > 0;
    тренд.textContent = (вверх ? "▲ " : "▼ ") + "было " + о.тренд.начало
      + ", стало " + о.тренд.конец
      + " (" + (вверх ? "+" : "") + о.тренд.разница + ")";
    тренд.className = "дельта " + (вверх ? "вверх" : "вниз");
    тренд.hidden = false;
  } else {
    тренд.hidden = true;
  }

  // Полоски: одна гамма на все факторы, различает длина. Число стоит рядом
  // с каждой — значение читается, даже если цвет не различить вовсе.
  const где = э("факторы");
  где.innerHTML = "";
  о.разбивка.forEach((пункт) => {
    const строка = document.createElement("div");
    строка.className = "фактор";
    строка.title = пункт.словами;
    строка.innerHTML =
      '<div class="фактор-имя">' + экран(пункт.фактор)
        + "<span>" + экран(пункт.словами) + "</span></div>"
      + '<div class="дорожка"><div class="заливка"></div></div>'
      + '<div class="фактор-число">' + пункт.вклад
        + " из " + пункт.потолок + "</div>";
    строка.querySelector(".заливка").style.width =
      Math.round(пункт.балл * 100) + "%";
    где.append(строка);
  });

  // «Что видно» — выше полосок: восемь полосок первым экраном читаются
  // кашей, а «она начала 2 разговора из 32» — это уже мысль.
  э("видно").hidden = о.наблюдения.length === 0;
  э("видно-список").innerHTML = о.наблюдения
    .map((строка) => "<li>" + экран(строка) + "</li>").join("");

  показатьНедели(о.недели || []);

  э("пороги").hidden = о.пороги.length === 0;
  э("пороги-список").innerHTML = о.пороги
    .map((строка) => "<li>" + экран(строка) + "</li>").join("");

  const пробелы = э("пробелы");
  пробелы.hidden = о.не_посчитано.length === 0;
  э("пробелы-список").innerHTML = о.не_посчитано
    .map((п) => "<li><b>" + экран(п.фактор) + "</b> — " + экран(п.словами) + "</li>")
    .join("");

  э("цифры").innerHTML = о.цифры
    .map((п) => "<tr><td>" + экран(п.подпись) + "</td><td>"
                + экран(п.значение) + "</td></tr>")
    .join("");

  показатьИИ(о);
  // Блок виден всегда — иначе про подсказку и черновик просто не узнают.
  // Без ключа кнопки не работают, и сказано, чего не хватает.
  const естьКлюч = Boolean(о.ключ_есть);
  э("кнопка-подсказка").disabled = !естьКлюч;
  э("кнопка-черновик").disabled = !естьКлюч;
  э("дальше-без-ключа").hidden = естьКлюч;
  э("дальше").hidden = false;
  э("дальше-ответ").hidden = true;
  э("черновик-ввод").hidden = true;
  э("отчёт").hidden = false;
  э("отчёт").scrollIntoView({ behavior: "smooth", block: "start" });
}

