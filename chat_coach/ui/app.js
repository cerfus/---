// Ключ доступа лежит в адресной строке: без него сервер не отвечает, и это
// не формальность. Страница висит на локальном порту, и любой открытый в том
// же браузере сайт мог бы стучаться к ней — а каждый разбор стоит денег.
const КЛЮЧ = new URLSearchParams(location.search).get("k") || "";

const э = (id) => document.getElementById(id);
const состояние = { я: "", цель: "ошибки", файл: null };

async function запрос(куда, тело) {
  const ответ = await fetch(куда + "?k=" + encodeURIComponent(КЛЮЧ), {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(тело || {}),
  });
  const данные = await ответ.json().catch(() => ({ ошибка: "Непонятный ответ." }));
  if (!ответ.ok || данные.ошибка) throw new Error(данные.ошибка || "Сбой запроса.");
  return данные;
}

let таймерБеды = 0;
function беда(текст) {
  const окошко = э("беда");
  окошко.textContent = текст;
  окошко.hidden = false;
  clearTimeout(таймерБеды);
  таймерБеды = setTimeout(() => { окошко.hidden = true; }, 9000);
}

function занят(кнопка, да) {
  кнопка.disabled = да;
  кнопка.classList.toggle("думает", да);
}

