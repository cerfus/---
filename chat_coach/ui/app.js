function показатьСтороны(данные) {
  const где = э("стороны");
  где.innerHTML = "";
  состояние.я = "";

  данные.стороны.forEach((имя) => {
    где.append(кнопкаВыбора(имя, false, (кнопка) => {
      [...где.children].forEach((к) => к.setAttribute("aria-pressed", "false"));
      кнопка.setAttribute("aria-pressed", "true");
      состояние.я = имя;
      э("показать").disabled = false;
    }));
  });

  // Разметили «я:» и «она:» — спрашивать не о чем, выбираем сами.
  if (данные.явная) {
    где.children[0].click();
  }

  const цели = э("цели");
  цели.innerHTML = "";
  ЦЕЛИ.forEach(([код, подпись]) => {
    цели.append(кнопкаВыбора(подпись, код === состояние.цель, (кнопка) => {
      [...цели.children].forEach((к) => к.setAttribute("aria-pressed", "false"));
      кнопка.setAttribute("aria-pressed", "true");
      состояние.цель = код;
    }));
  });

  э("шаг-стороны").hidden = false;
  э("отчёт").hidden = true;
  if (данные.групповой) {
    беда("Похоже, это групповой чат: активных собеседников больше двух. "
       + "Разбор рассчитан на переписку один на один, цифры будут условными.");
  } else if (данные.мало) {
    беда("Сообщений маловато (" + данные.сколько + ") — выводы будут шаткими.");
  }
  э("шаг-стороны").scrollIntoView({ behavior: "smooth", block: "nearest" });
}

