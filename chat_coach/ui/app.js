// --------------------------------------------------------------------------
//
// Правила те же, что в боте, и приходят они с сервера готовым текстом:
// после отказа советов нет, а пока она не ответила — подсказки нет тоже.

function показатьДальше(ответ) {
  const где = э("дальше-ответ");
  где.hidden = false;
  где.textContent = ответ.стоп || ответ.придержано || ответ.текст || "";
  где.classList.toggle("придержано", Boolean(ответ.стоп || ответ.придержано));
  где.scrollIntoView({ behavior: "smooth", block: "nearest" });
}

async function спроситьДальше(кнопка, куда, тело) {
  занят(кнопка, true);
  try {
    показатьДальше(await запрос(куда, тело));
  } catch (сбой) {
    беда(сбой.message);
  } finally {
    занят(кнопка, false);
  }
}

э("кнопка-подсказка").addEventListener("click", (событие) =>
  спроситьДальше(событие.currentTarget, "/api/hint", {}));

