def случай_страница():
    """Страница и её файлы отдаются — окну есть что показать."""
    код_страницы, страница = сходить("/")
    коды = {}
    for файл in ("style.css", "app.js"):
        коды[файл] = сходить("/ui/" + файл)[0]
    ок = (код_страницы == 200 and "Разбор переписки" in страница
          and set(коды.values()) == {200})
    return ок, "страница: код=%s файлы=%s" % (код_страницы, коды)


def случай_чужой_ключ():
    """Без ключа и с чужим — отказ. Кириллица в ключе не роняет сервер.

    compare_digest не работает со строками не-ASCII: сравнение напрямую
    отвечало пятисотой вместо отказа, то есть окно можно было уронить
    одним запросом.
    """
    без_ключа = сходить("/", ключ="")[0]
    чужой = сходить("/", ключ="совсем-другой")[0]
    кириллица = сходить("/", ключ="ключ-по-русски")[0]
    ок = без_ключа == 403 and чужой == 403 and кириллица == 403
    return ок, "ключи: пустой=%s чужой=%s кириллица=%s" % (
        без_ключа, чужой, кириллица)


def случай_разбор_текста():
    """Вставленный текст разбирается, стороны находятся."""
    код, ответ = сходить("/api/parse", {"текст": переписка()})
    ок = (код == 200 and sorted(ответ["стороны"]) == ["Аня", "Иван"]
          and ответ["сколько"] == 24 and ответ["групповой"] is False
          and ответ["мало"] is False)
    return ок, "разбор: код=%s ответ=%s" % (код, ответ)


def случай_отчёт():
    """Отчёт считается, и его арифметика сходится."""
    сходить("/api/parse", {"текст": переписка()})
    код, о = сходить("/api/analyse", {"я": "Иван", "цель": "свидание",
                                      "с_ии": False})
    вклады = round(sum(п["вклад"] for п in о["разбивка"]))
    потолки = sum(п["потолок"] for п in о["разбивка"])
    ок = (код == 200 and о["я"] == "Иван" and о["она"] == "Аня"
          and о["индекс"] is not None
          # Сумма вкладов обязана сойтись с индексом, а потолков — с сотней:
          # иначе в окне получится «19 из 15», как было в консоли.
          and abs(вклады - о["индекс"]) <= 1
          and abs(потолки - 100) <= 2
          and о["цифры"] and о["вердикт"])
    return ок, "отчёт: индекс=%s вклады=%s потолки=%s" % (
        о.get("индекс"), вклады, потолки)


def случай_рамка():
    """Окно получает рамку, а при отказе — стоп вместо вердикта.

    Без этого окно показывало бы «встречного интереса не видно» там,
    где бот уже сказал «здесь прозвучал отказ»: два интерфейса на одной
    переписке говорили бы разное.
    """
    сходить("/api/parse", {"текст": переписка()})
    код, обычный = сходить("/api/analyse", {"я": "Иван", "с_ии": False})

    отказная = переписка() + "\n".join(
        ["", "Иван, [20.09.2026 19:00]", "может сходим куда-нибудь вдвоём?", "",
         "Аня, [20.09.2026 19:40]", "нет спасибо", ""])
    сходить("/api/parse", {"текст": отказная})
    _код, отказ = сходить("/api/analyse", {"я": "Иван", "с_ии": False})

    ок = (код == 200 and обычный["рамка"] and обычный["рамка"]["стоп"] is False
          and обычный["вердикт"]
          and отказ["рамка"]["стоп"] is True
          and отказ["вердикт"] == ""          # всё сказано стоп-блоком
          and any("нет спасибо" in абзац
                  for абзац in отказ["рамка"]["стоп_абзацы"]))
    return ок, "рамка: обычная=%s, отказ=%s" % (
        обычный.get("рамка", {}).get("тип"), отказ.get("рамка", {}).get("тип"))


def длинная_переписка():
    """Десять недель, и одна из них почти пустая — ради разрыва в линии."""
    начало = datetime.now() - timedelta(weeks=10)
    строки = []
    for неделя in range(10):
        густо = 1 if неделя == 6 else 5      # шестая неделя — дыра
        день = начало + timedelta(weeks=неделя)
        for н in range(густо):
            час = 10 + н
            строки += [
                "Аня, [%s]" % (день + timedelta(hours=час)).strftime(
                    "%d.%m.%Y %H:%M"),
                "привет! как день прошёл? 😊", "",
                "Иван, [%s]" % (день + timedelta(hours=час, minutes=20))
                .strftime("%d.%m.%Y %H:%M"),
                "нормально, работал", "",
            ]
    return "\n".join(строки)


def свежая_переписка():
    """Последнее слово за ним, и сказано только что: ход не его."""
    сейчас = datetime.now()
    строки = []
    for н in range(6):
        когда = сейчас - timedelta(hours=40 - н * 6)
        строки += [
            "Аня, [%s]" % когда.strftime("%d.%m.%Y %H:%M"),
            "привет! как день прошёл? 😊", "",
            "Иван, [%s]" % (когда + timedelta(minutes=10)).strftime(
                "%d.%m.%Y %H:%M"),
            "нормально, работал", "",
        ]
    # И последнее слово за ним, десять минут назад.
    строки += ["Иван, [%s]" % (сейчас - timedelta(minutes=10)).strftime(
        "%d.%m.%Y %H:%M"), "а ты чем занята?", ""]
    return "\n".join(строки)


def случай_окно_догоняет_бота():
    """Наблюдения, недели и пороги приходят в окно, как и в бота.

    Неделя без данных отдаётся null, а не нулём: нарисовать там ноль
    значило бы показать обвал, которого не было.
    """
    сходить("/api/parse", {"текст": длинная_переписка()})
    код, отчёт = сходить("/api/analyse", {"я": "Иван", "с_ии": False})
    недели = отчёт.get("недели") or []
    дыры = [н for н in недели if н["индекс"] is None]
    ок = (код == 200 and отчёт["наблюдения"] and len(отчёт["наблюдения"]) <= 5
          and len(недели) >= 3 and дыры
          and all(н["сколько"] > 0 for н in недели)
          and all("подпись" in н for н in недели)
          and isinstance(отчёт["пороги"], list))
    return ок, "окно: наблюдений %d, недель %d (дыр %d), порогов %d" % (
        len(отчёт.get("наблюдения") or []), len(недели), len(дыры),
        len(отчёт.get("пороги") or []))


def случай_подсказка_придержана():
    """Пока она не ответила, подсказки нет — и в окне тоже.

    Ни ключа, ни модели для этого не нужно: следующего сообщения просто
    не бывает, пока предыдущее не получило ответа.
    """
    было = os.environ.pop("ANTHROPIC_API_KEY", None)
    try:
        сходить("/api/parse", {"текст": свежая_переписка()})
        сходить("/api/analyse", {"я": "Иван", "с_ии": False})
        код, ответ = сходить("/api/hint", {})
        ок = (код == 200 and ответ.get("придержано")
              and "ещё не ответила" in ответ["придержано"]
              # Ключ не спрашивался: ответ готов и без модели.
              and not ответ.get("ошибка"))
        return ок, "придержка: код=%s ответ=%s" % (
            код, str(ответ)[:70])
    finally:
        if было:
            os.environ["ANTHROPIC_API_KEY"] = было


