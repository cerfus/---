ПОРТ = сервер.server_address[1]


def адрес(путь, ключ=КЛЮЧ):
    # Экранируем и путь, и ключ: в них бывает кириллица, а по проводу
    # уходит только ASCII.
    return "http://127.0.0.1:%d%s?k=%s" % (ПОРТ, urllib.parse.quote(путь),
                                           urllib.parse.quote(ключ))


def сходить(путь, тело=None, ключ=КЛЮЧ):
    """Возвращает (код, разобранный ответ или сырой текст)."""
    данные = None if тело is None else json.dumps(тело).encode("utf-8")
    запрос = urllib.request.Request(
        адрес(путь, ключ), data=данные,
        headers={"Content-Type": "application/json"},
        method="POST" if данные is not None else "GET")
    try:
        with urllib.request.urlopen(запрос, timeout=30) as ответ:
            сырое = ответ.read().decode("utf-8")
            код = ответ.status
    except urllib.error.HTTPError as сбой:
        сырое, код = сбой.read().decode("utf-8"), сбой.code
    try:
        return код, json.loads(сырое)
    except ValueError:
        return код, сырое


