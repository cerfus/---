def случай_страница():
    """Страница и её файлы отдаются — окну есть что показать."""
    код_страницы, страница = сходить("/")
    коды = {}
    for файл in ("style.css", "app.js"):
        коды[файл] = сходить("/ui/" + файл)[0]
    ок = (код_страницы == 200 and "Разбор переписки" in страница
          and set(коды.values()) == {200})
    return ок, "страница: код=%s файлы=%s" % (код_страницы, коды)


def случай_чужой_ключ():
    """Без ключа и с чужим — отказ. Кириллица в ключе не роняет сервер.

    compare_digest не работает со строками не-ASCII: сравнение напрямую
    отвечало пятисотой вместо отказа, то есть окно можно было уронить
    одним запросом.
    """
    без_ключа = сходить("/", ключ="")[0]
    чужой = сходить("/", ключ="совсем-другой")[0]
    кириллица = сходить("/", ключ="ключ-по-русски")[0]
    ок = без_ключа == 403 and чужой == 403 and кириллица == 403
    return ок, "ключи: пустой=%s чужой=%s кириллица=%s" % (
        без_ключа, чужой, кириллица)


def случай_разбор_текста():
    """Вставленный текст разбирается, стороны находятся."""
    код, ответ = сходить("/api/parse", {"текст": переписка()})
    ок = (код == 200 and sorted(ответ["стороны"]) == ["Аня", "Иван"]
          and ответ["сколько"] == 24 and ответ["групповой"] is False
          and ответ["мало"] is False)
    return ок, "разбор: код=%s ответ=%s" % (код, ответ)


def случай_отчёт():
    """Отчёт считается, и его арифметика сходится."""
    сходить("/api/parse", {"текст": переписка()})
    код, о = сходить("/api/analyse", {"я": "Иван", "цель": "свидание",
                                      "с_ии": False})
    вклады = round(sum(п["вклад"] for п in о["разбивка"]))
    потолки = sum(п["потолок"] for п in о["разбивка"])
    ок = (код == 200 and о["я"] == "Иван" and о["она"] == "Аня"
          and о["индекс"] is not None
          # Сумма вкладов обязана сойтись с индексом, а потолков — с сотней:
          # иначе в окне получится «19 из 15», как было в консоли.
          and abs(вклады - о["индекс"]) <= 1
          and abs(потолки - 100) <= 2
          and о["цифры"] and о["вердикт"])
    return ок, "отчёт: индекс=%s вклады=%s потолки=%s" % (
        о.get("индекс"), вклады, потолки)


def случай_архив():
    """Файл приходит base64, имя-ловушка обеззараживается, разбор идёт."""
    код, ответ = сходить("/api/parse", {"файл": архив(),
                                        "имя": "../../ChatExport.zip"})
    сбежал = os.path.exists(os.path.join(os.path.dirname(app.ЗДЕСЬ),
                                         "ChatExport.zip"))
    ок = код == 200 and ответ["сколько"] == 24 and not сбежал
    return ок, "архив: код=%s сообщений=%s файл сбежал=%s" % (
        код, ответ.get("сколько"), сбежал)


def случай_мусор():
    """Не переписка — понятная ошибка, а не пятисотая."""
    код, ответ = сходить("/api/parse", {"текст": "привет как дела"})
    без_переписки = сходить("/api/analyse", {"я": "Никто", "с_ии": False})
    неизвестное = сходить("/api/чепуха", {})[0]
    ок = (код == 400 and "ошибка" in ответ
          and без_переписки[0] == 400 and неизвестное == 404)
    return ок, "мусор: разбор=%s, чужое имя=%s, нет действия=%s" % (
        код, без_переписки[0], неизвестное)


def случай_ключ_модели():
    """Ключ сохраняется и убирается, и это видно в ответе."""
    было = os.environ.pop("ANTHROPIC_API_KEY", None)
    try:
        поставили = сходить("/api/settings", {"ключ": "sk-ant-проверка"})[1]
        убрали = сходить("/api/settings", {"ключ": ""})[1]
        лежит = json.load(open(app.ФАЙЛ_НАСТРОЕК, encoding="utf-8"))
        ок = (поставили["ключ_есть"] is True and убрали["ключ_есть"] is False
              and лежит["ключ"] == "")
        return ок, "ключ: поставили=%s убрали=%s" % (поставили, убрали)
    finally:
        if было:
            os.environ["ANTHROPIC_API_KEY"] = было


def случай_сердцебиение():
    """Пинг отвечает и продлевает жизнь, выход закрывает сервер."""
    было = app.последний_стук
    код, ответ = сходить("/api/ping", {})
    продлилось = app.последний_стук >= было
    выход = сходить("/api/quit", {})

    # Ждём, а не смотрим сразу: сервер сперва отвечает браузеру и только
    # потом гасится отдельным потоком. Проверка, читавшая флаг мгновенно,
    # мигала примерно в половине прогонов — и это была её вина, не его.
    закрылся = False
    for _ in range(50):
        if сервер._BaseServer__shutdown_request:
            закрылся = True
            break
        time.sleep(0.02)

    ок = (код == 200 and ответ == {"живой": True}
          and продлилось and выход[0] == 200 and закрылся)
    return ок, "сердцебиение: пинг=%s продлилось=%s выход=%s закрылся=%s" % (
        код, продлилось, выход[0], закрылся)


def main():
    threading.Thread(target=сервер.serve_forever, daemon=True).start()
    случаи = (случай_страница, случай_чужой_ключ, случай_разбор_текста,
              случай_отчёт, случай_архив, случай_мусор, случай_ключ_модели,
              случай_сердцебиение)
    провалов = 0
    try:
        for случай in случаи:
            ок, описание = случай()
            if not ок:
                провалов += 1
                print("ПЛОХО  %s" % описание)
        print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
        return 1 if провалов else 0
    finally:
        сервер.server_close()
        shutil.rmtree(_ВРЕМЕННАЯ, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
