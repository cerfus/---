def переписка(сколько=6):
    строки = []
    for н in range(сколько):
        день = н + 1
        строки += [
            "Аня, [%02d.09.2026 19:04]" % день, "привет! как день прошёл? 😊", "",
            "Иван, [%02d.09.2026 19:06]" % день, "нормально", "",
            "Аня, [%02d.09.2026 19:20]" % день, "ахаха) а что делал?", "",
            "Иван, [%02d.09.2026 19:40]" % день, "работал", "",
        ]
    return "\n".join(строки)


def архив():
    выгрузка = {"messages": [
        {"id": н, "type": "message",
         "date": "2026-09-%02dT19:%02d:00" % (н // 4 + 1, (н % 4) * 10),
         "from": "Аня" if н % 2 else "Иван",
         "text": "привет, как дела? что нового?" if н % 2 else "норм"}
        for н in range(1, 25)]}
    буфер = io.BytesIO()
    with zipfile.ZipFile(буфер, "w") as зип:
        зип.writestr("ChatExport/result.json",
                     json.dumps(выгрузка, ensure_ascii=False))
    return base64.b64encode(буфер.getvalue()).decode()


