"""Проверка окна. Запуск: python test_app.py

Поднимает тот же сервер, что и программа, на свободном порту и стучится
к нему настоящими запросами. Ни браузера, ни сети наружу, ни ключа Claude:
проверяется всё, что от модели не зависит.
"""

import base64
import io
import json
import os
import shutil
import tempfile
import time
