# -*- coding: utf-8 -*-
"""
Сводка по боту словами. Числа считает storage.сводка.

Разделение то же, что у metrics и report: одно место считает, другое
раскладывает словами. Здесь только раскладка — ни одного запроса в базу.

Зачем вообще. Бот с первого дня пишет в базу числа каждого разбора,
нажатия «хочу премиум» и платежи, и до сих пор это никто ни разу не
читал. Пока их не видно, «что делать дальше» решается на ощупь.
"""

import metrics

ЗАГОЛОВОК = "СВОДКА"

# «Нажали /start» — это именно нажавшие: отметка ставится в обработчике
# /start и больше нигде. Подписи должны называть измеренное, а не
# «пользователей»: иначе первая же цифра будет означать не то, что кажется.
ОГОВОРКА = ("«Нажали /start» — те, кто нажал именно /start: отметка "
            "ставится там и больше нигде.")


def _доля(часть, целое):
    """«(43%)» или пусто, если не от чего считать."""
    if not целое:
        return ""
    return " (%d%%)" % round(часть * 100 / целое)


def _строки(пары):
    """Выравнивает подписи по самой длинной — колонкой, а не лесенкой."""
    ширина = max((len(подпись) for подпись, _ in пары), default=0)
    return ["  %-*s %s" % (ширина, подпись, значение) for подпись, значение
            in пары]


def текстом(с):
    """Готовый текст сводки. На пустой базе — нули, а не деление на ноль."""
    куски = [ЗАГОЛОВОК, ""]

    куски.append("ЛЮДИ")
    куски += _строки([
        ("нажали /start", "%d" % с["людей"]),
        ("из них за %d %s" % (с["дней"], metrics.склонение(
            с["дней"], "день", "дня", "дней")), "%d" % с["новых"]),
        ("возвращались", "%d%s" % (с["возвращались"],
                                   _доля(с["возвращались"], с["людей"]))),
    ])

    # Воронка — главное здесь: она отвечает на «где отваливаются».
    куски += ["", "ВОРОНКА"]
    куски += _строки([
        ("нажали /start", "%d" % с["людей"]),
        ("дошли до разбора", "%d%s" % (с["дошли_до_разбора"],
                                       _доля(с["дошли_до_разбора"],
                                             с["людей"]))),
        ("вернулись за вторым", "%d%s" % (
            с["вернулись_за_вторым"],
            _доля(с["вернулись_за_вторым"], с["дошли_до_разбора"]))),
    ])

    куски += ["", "РАЗБОРЫ"]
    пары = [("всего", "%d" % с["разборов"]),
            ("за %d %s" % (с["дней"], metrics.склонение(
                с["дней"], "день", "дня", "дней")),
             "%d" % с["разборов_за_срок"])]
    if с["медиана_индекса"] is not None:
        пары.append(("медиана индекса «сейчас»",
                     "%d из 100" % с["медиана_индекса"]))
    if с["медиана_объёма"] is not None:
        пары.append(("медиана объёма", "%d %s" % (
            с["медиана_объёма"], metrics.склонение(
                с["медиана_объёма"], "сообщение", "сообщения", "сообщений"))))
    куски += _строки(пары)

    куски += ["", "СПРОС НА ПРЕМИУМ"]
    куски += _строки([
        ("жали «хочу премиум»", "%d %s, %d %s" % (
            с["премиум_нажатий"],
            metrics.склонение(с["премиум_нажатий"], "раз", "раза", "раз"),
            с["премиум_людей"],
            metrics.склонение(с["премиум_людей"], "человек", "человека",
                              "человек"))),
    ])
    if с["премиум_откуда"]:
        куски.append("  с экранов: " + ", ".join(
            "%s — %d" % (откуда, сколько)
            for откуда, сколько in с["премиум_откуда"]))

    куски += ["", "ДЕНЬГИ"]
    пары = [("платежей", "%d, платили %d %s" % (
                 с["платежей"], с["платили_людей"],
                 metrics.склонение(с["платили_людей"], "человек", "человека",
                                   "человек"))),
            # Оставшееся, а не собранное: возвращённое деньгами не было.
            ("осталось", "%d ⭐" % с["звёзд"])]
    if с["возвратов"]:
        пары.append(("возвращено", "%d ⭐ за %d %s" % (
            с["вернули_звёзд"], с["возвратов"],
            metrics.склонение(с["возвратов"], "платёж", "платежа",
                              "платежей"))))
    пары.append(("не потрачено", "%d %s на счетах" % (
        с["непотрачено"], metrics.склонение(
            с["непотрачено"], "разбор", "разбора", "разборов"))))
    куски += _строки(пары)

    куски += ["", ОГОВОРКА]
    return "\n".join(куски)
