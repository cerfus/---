# -*- coding: utf-8 -*-
"""Проверка слоя Claude без единого обращения к сети.

Запуск: python test_analysis.py

Сам вызов модели подменяется заглушкой. Проверяем то, что от модели
не зависит и что при этом важнее всего: в запрос не утекают имена,
выборка собирается из нужных мест, отказ модели не роняет бота,
а стоп-сигнал отменяет любые советы.
"""

from datetime import timedelta

import console          # noqa: F401
import analysis
import frame
import metrics
import test_metrics as образцы


def _чат():
    чат, курсор = образцы.тёплый(образцы.СТАРТ, 4)
    хвост, _ = образцы.холодный(курсор + timedelta(hours=10), 4)
    return чат + хвост


def _итог(чат):
    return metrics.analyse(чат, "Иван", "Аня")


class ЗаглушкаОтвета:
    def __init__(self, parsed_output=None, stop_reason="end_turn", текст=""):
        self.parsed_output = parsed_output
        self.stop_reason = stop_reason
        self.content = [type("Блок", (), {"type": "text", "text": текст})()]


class ЗаглушкаКлиента:
    """Ведёт себя как anthropic.Anthropic, но никуда не ходит."""

    def __init__(self, ответ):
        self.ответ = ответ
        self.запросы = []
        self.messages = self

    def parse(self, **параметры):
        self.запросы.append(параметры)
        return self.ответ

    def create(self, **параметры):
        self.запросы.append(параметры)
        return self.ответ


def случай_обезличивание():
    """Имена и их падежи исчезают, похожие слова остаются целыми."""
    имена = {"Аня": "Она", "Иван": "Ты"}
    проверки = [
        ("Аня, привет", "Она, привет"),
        ("сказал Ане вчера", "сказал Она вчера"),
        ("жду Аню", "жду Она"),
        ("гулял с Аней", "гулял с Она"),
        ("Иван обещал", "Ты обещал"),
        ("учу английский", "учу английский"),      # не трогаем
        ("Андрей звонил", "Андрей звонил"),        # чужое имя не трогаем
    ]
    плохие = [(было, analysis.обезличить(было, имена))
              for было, ждём in проверки
              if analysis.обезличить(было, имена) != ждём]
    return not плохие, "обезличивание: сломалось %s" % (плохие or "ничего")


def случай_выборка():
    """Выборка берёт обрывы и последние сообщения, имён в ней нет."""
    чат = _чат()
    отобранное = analysis.выборка(чат, "Иван", "Аня")
    всё = "\n".join(отобранное["последние"]
                    + [с for _п, строки in отобранное["обрывы"] for с in строки]
                    + [с for кусок in отобранное["удачные"] for с in кусок])
    ок = (отобранное["обрывы"]
          and len(отобранное["последние"]) <= analysis.ПОСЛЕДНИХ
          and "Аня" not in всё and "Иван" not in всё
          and "Ты:" in всё and "Она:" in всё)
    return ок, ("выборка: обрывов=%d удачных=%d последних=%d имён в тексте=%s"
                % (len(отобранное["обрывы"]), len(отобранное["удачные"]),
                   len(отобранное["последние"]),
                   "Аня" in всё or "Иван" in всё))


def случай_запрос():
    """В запросе есть цифры и цель — и нет настоящих имён."""
    чат = _чат()
    итог = _итог(чат)
    запрос = analysis.собрать_запрос(
        итог, analysis.выборка(чат, "Иван", "Аня"), "позвать на свидание")
    ок = ("позвать на свидание" in запрос
          and "индекс вовлечённости" in запрос
          and "ОБРЫВАЛСЯ" in запрос
          and "Аня" not in запрос and "Иван" not in запрос)
    return ок, "запрос: длина=%d символов, имена внутри=%s" % (
        len(запрос), "Аня" in запрос or "Иван" in запрос)


def случай_разбор():
    """Обычный ответ модели доезжает до вызывающего целиком."""
    чат = _чат()
    ожидаемый = analysis.Разбор(
        коротко="Общение держится на тебе.",
        что_работает=["пишешь по делу"],
        что_мешает=[analysis.Совет(что_не_так="пишешь подряд",
                                   цитата="может увидимся",
                                   как_лучше="Свободна в субботу?")],
        следующий_шаг="Напиши одно сообщение и дождись ответа.",
        стоп_сигнал=False, стоп_причина="")
    клиент = ЗаглушкаКлиента(ЗаглушкаОтвета(parsed_output=ожидаемый))
    разбор = analysis.разобрать(чат, _итог(чат), "понять, есть ли шанс",
                                клиент=клиент)
    запрос = клиент.запросы[0]
    ок = (разбор.коротко == ожидаемый.коротко
          and запрос["model"] == analysis.МОДЕЛЬ
          and запрос["output_format"] is analysis.Разбор
          # системную часть кэшируем, иначе короткие вопросы дорожают
          and запрос["system"][0]["cache_control"] == {"type": "ephemeral"})
    return ок, "разбор: модель=%s усилие=%s" % (запрос["model"],
                                                запрос.get("output_config"))


def случай_отказ():
    """Отказ модели — это понятная ошибка, а не падение бота."""
    чат = _чат()
    клиент = ЗаглушкаКлиента(ЗаглушкаОтвета(stop_reason="refusal"))
    try:
        analysis.разобрать(чат, _итог(чат), "цель", клиент=клиент)
        return False, "отказ: исключения не было"
    except analysis.ОшибкаРазбора as сбой:
        return "не стала" in str(сбой), "отказ: %s" % сбой


def случай_стоп_сигнал():
    """При явном отказе девушки никаких тактик не показываем."""
    разбор = analysis.Разбор(
        коротко="Она попросила не писать.",
        что_работает=["был вежлив"],
        что_мешает=[analysis.Совет(что_не_так="пишешь после отказа",
                                   цитата="ну ответь хоть что-нибудь",
                                   как_лучше="ничего не писать")],
        следующий_шаг="написать ещё раз через неделю",
        стоп_сигнал=True,
        стоп_причина="Прямо сказано: «не пиши мне больше».")
    текст = analysis.текст_разбора(разбор)
    ок = ("СТОП" in текст
          and "не пиши мне больше" in текст
          and "Следующий шаг" not in текст      # советов быть не должно
          and "написать ещё раз через неделю" not in текст)
    return ок, "стоп-сигнал: %r" % текст[:80]


def случай_рамка_в_запросе():
    """Рамка доезжает до модели, но без имён — в ней бывает цитата."""
    чат = _чат()
    итог = _итог(чат)
    # Рамку собираем руками: нужна именно та, в пояснении которой есть имя.
    рамка = {"тип": frame.ОТКАЗ, "уверенность": "высокая",
             "почему": ["Её слова: «Аня больше не пишет»"],
             "отказ": {"правило": "не пиши мне", "цитата": "Аня больше не пишет",
                       "когда": None}}
    запрос = analysis.собрать_запрос(
        итог, analysis.выборка(чат, "Иван", "Аня"), "цель", рамка)
    ок = ("ЧТО ЭТО ЗА ПЕРЕПИСКА" in запрос
          and frame.НАЗВАНИЯ[frame.ОТКАЗ] in запрос
          and "Аня" not in запрос)
    return ок, "рамка в запросе: имя внутри=%s" % ("Аня" in запрос)


def случай_черновик():
    """Черновик проверяется, а имя возвращается в готовые варианты."""
    чат = _чат()
    ожидаемый = analysis.Черновик(
        как_сядет="Прочитается как претензия.",
        риск="три вопроса подряд",
        варианты=["Привет, {имя}! Свободна в субботу?",
                  "{имя}, сходим в кино в субботу?"],
        не_отправлять=False, почему_не="")
    клиент = ЗаглушкаКлиента(ЗаглушкаОтвета(parsed_output=ожидаемый))
    разбор = analysis.черновик(_итог(чат),
                               analysis.выборка(чат, "Иван", "Аня"),
                               "Аня ну ответь уже, ты меня игноришь?",
                               клиент=клиент)
    запрос = клиент.запросы[0]["messages"][0]["content"]
    текст = analysis.текст_черновика(разбор)
    ок = (разбор.варианты[0] == "Привет, Аня! Свободна в субботу?"
          # В запрос имя не ушло: вместо него метка.
          and "Аня" not in запрос and analysis.МЕТКА_ИМЕНИ in запрос
          and "ЧЕРНОВИК" in запрос
          and "Привет, Аня!" in текст and "оттолкнуть" in текст)
    return ок, "черновик: варианты=%s, имя в запросе=%s" % (
        разбор.варианты, "Аня" in запрос)


def случай_черновик_падежи():
    """Имя возвращается в той форме, в какой стояло, и по очереди."""
    спрятанный, формы = analysis.спрятать_имя("Аня, жду Аню у Ани", "Аня")
    вернулось = analysis.вернуть_имя(спрятанный, формы, "Аня")
    лишняя = analysis.вернуть_имя("привет {имя}", [], "Аня")
    ок = (спрятанный == "{имя}, жду {имя} у {имя}"
          and формы == ["Аня", "Аню", "Ани"]
          and вернулось == "Аня, жду Аню у Ани"
          and лишняя == "привет Аня")
    return ок, "падежи: %r -> %r" % (спрятанный, вернулось)


def случай_черновик_после_отказа():
    """После отказа черновик не полируется и модель не зовётся."""
    чат = _чат()
    рамка = {"тип": frame.ОТКАЗ, "уверенность": "высокая", "почему": [],
             "отказ": {"правило": "нет, спасибо", "цитата": "нет спасибо",
                       "когда": None}}
    клиент = ЗаглушкаКлиента(ЗаглушкаОтвета(parsed_output=None))
    разбор = analysis.черновик(_итог(чат), None, "ну ответь пожалуйста",
                               рамка=рамка, клиент=клиент)
    текст = analysis.текст_черновика(разбор)
    ок = (разбор.не_отправлять and not разбор.варианты
          and not клиент.запросы                 # к модели не ходили вовсе
          and "не отправлять" in текст)
    return ок, "после отказа: запросов к модели=%d" % len(клиент.запросы)


def main():
    случаи = (случай_обезличивание, случай_выборка, случай_запрос,
              случай_разбор, случай_отказ, случай_стоп_сигнал,
              случай_рамка_в_запросе, случай_черновик, случай_черновик_падежи,
              случай_черновик_после_отказа)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
