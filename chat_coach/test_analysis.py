def случай_возражение_без_улик():
    """Возразить рамке можно, но с цитатами — иначе это мнение поверх цифр."""
    основа = dict(коротко="Общение держится на тебе.", что_работает=[],
                  что_мешает=[], следующий_шаг="Напиши одно и подожди.",
                  стоп_сигнал=False, стоп_причина="")
    с_уликами = analysis.Разбор(рамка_верна=False, рамка_иначе="дружба",
                                рамка_улики=["ты мне как брат", "покаж её фотку"],
                                **основа)
    одна_улика = analysis.Разбор(рамка_верна=False, рамка_иначе="дружба",
                                 рамка_улики=["ты мне как брат"], **основа)
    без_названия = analysis.Разбор(рамка_верна=False, рамка_иначе="",
                                   рамка_улики=["раз", "два"], **основа)
    согласна = analysis.Разбор(рамка_верна=True, рамка_иначе="",
                               рамка_улики=[], **основа)

    ок = (analysis.возражение(с_уликами)
          and analysis.возражение(одна_улика) is None
          and analysis.возражение(без_названия) is None
          and analysis.возражение(согласна) is None
          # И в тексте разбора оно стоит выше вывода про дела в переписке.
          and analysis.текст_разбора(с_уликами).index("дружба")
          < analysis.текст_разбора(с_уликами).index("держится на тебе"))
    return ок, "возражение: с уликами=%s, с одной=%s" % (
        bool(analysis.возражение(с_уликами)),
        bool(analysis.возражение(одна_улика)))


