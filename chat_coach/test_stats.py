# -*- coding: utf-8 -*-
"""Проверка сводки по боту. Запуск: python test_stats.py

Сводка — это инструмент, по которому будут решать, что делать дальше.
Соврать она может тихо: посчитать строки вместо людей, съехать средним
от одной большой переписки, прибавить возврат к выручке вместо вычета.
Каждый из этих случаев здесь и стоит.
"""

import os
import shutil
import sqlite3
import tempfile
from datetime import datetime, timedelta

import console          # noqa: F401
import stats
import storage


def _база():
    папка = tempfile.mkdtemp()
    return storage.База(os.path.join(папка, "бот.sqlite3")), папка


def _итог(индекс, всего):
    """То, что кладёт в базу разбор. Метрики пустые — сводке они не нужны."""
    return {"индекс": индекс, "всего": всего, "дней": 30,
            "тренд": {"конец": индекс}, "метрики": {}}


def случай_пустая_база():
    """Первый запуск: нули, а не деление на ноль.

    Ровно так сводка и будет выглядеть в первый раз, так что падать ей
    тут нельзя ни при каких условиях.
    """
    база, папка = _база()
    try:
        сводка = база.сводка()
        текст = stats.текстом(сводка)
        ок = (сводка["людей"] == 0 and сводка["медиана_индекса"] is None
              and "ВОРОНКА" in текст and "0" in текст)
        return ок, "пустая: людей=%s медиана=%s" % (сводка["людей"],
                                                    сводка["медиана_индекса"])
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_воронка_по_людям():
    """Три разбора одного человека — один дошедший, а не три.

    Если считать строки, воронка покажет рост там, где один и тот же
    человек просто разбирает переписку четвёртый раз.
    """
    база, папка = _база()
    try:
        for кто in (1, 2, 3, 4, 5):
            база.увидеть(кто)
        for _ in range(3):
            база.записать_отчёт(1, _итог(40, 100))
        база.записать_отчёт(2, _итог(50, 200))

        сводка = база.сводка()
        ок = (сводка["людей"] == 5 and сводка["разборов"] == 4
              and сводка["дошли_до_разбора"] == 2
              and сводка["вернулись_за_вторым"] == 1)
        return ок, ("воронка: людей=%d разборов=%d дошли=%d вернулись=%d"
                    % (сводка["людей"], сводка["разборов"],
                       сводка["дошли_до_разбора"],
                       сводка["вернулись_за_вторым"]))
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_медиана_не_съезжает():
    """Одна переписка на шесть тысяч сообщений не двигает медиану.

    Ради этого она и медиана: среднее на таком выбросе перестаёт
    описывать хоть кого-нибудь.
    """
    база, папка = _база()
    try:
        объёмы = (120, 300, 310, 400, 6000)
        for номер, всего in enumerate(объёмы, 1):
            база.записать_отчёт(номер, _итог(40, всего))
        сводка = база.сводка()
        среднее = sum(объёмы) // len(объёмы)
        ок = сводка["медиана_объёма"] == 310 and среднее > 1000
        return ок, "медиана объёма=%s, среднее было бы %d" % (
            сводка["медиана_объёма"], среднее)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_возврат_вычитается():
    """Возвращённые звёзды — не выручка.

    Прибавить их вместо вычета значит смотреть на цифру, которой нет
    ни на одном счету.
    """
    база, папка = _база()
    try:
        база.зачислить(1, "stars", "чек-1", "пакет-5", 150, "XTR",
                       {"разбор": 5})
        база.зачислить(2, "stars", "чек-2", "пакет-15", 350, "XTR",
                       {"разбор": 15})
        база.пометить_возврат("stars", "чек-2", {"разбор": 15})

        сводка = база.сводка()
        ок = (сводка["платежей"] == 2 and сводка["платили_людей"] == 2
              and сводка["звёзд"] == 150 and сводка["вернули_звёзд"] == 350
              and сводка["возвратов"] == 1
              # Купленное у второго сняли вместе с возвратом.
              and сводка["непотрачено"] == 5)
        return ок, "деньги: осталось=%s вернули=%s непотрачено=%s" % (
            сводка["звёзд"], сводка["вернули_звёзд"], сводка["непотрачено"])
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def _состарить(база, кто, дней):
    """Двигает записи человека в прошлое — иначе срок не проверить."""
    когда = (datetime.now() - timedelta(days=дней)).isoformat(
        timespec="seconds")
    соединение = sqlite3.connect(база.путь)
    with соединение:
        соединение.execute("UPDATE users SET created_at=?, seen_at=? "
                           "WHERE user_id=?", (когда, когда, кто))
        соединение.execute("UPDATE reports SET created_at=? WHERE user_id=?",
                           (когда, кто))
    соединение.close()


def случай_срок_работает():
    """«За N дней» считает по сроку, а не всё подряд.

    Без этого «новых за неделю» тихо равнялось бы «всего», и рост был бы
    виден там, где никого нового не появилось.
    """
    база, папка = _база()
    try:
        for кто in (1, 2, 3):
            база.увидеть(кто)
            база.записать_отчёт(кто, _итог(40, 100))
        _состарить(база, 1, дней=30)       # этот пришёл давно

        сводка = база.сводка()
        ок = (сводка["людей"] == 3 and сводка["новых"] == 2
              and сводка["разборов"] == 3 and сводка["разборов_за_срок"] == 2)
        return ок, "срок: всего %d, новых %d, разборов за срок %d" % (
            сводка["людей"], сводка["новых"], сводка["разборов_за_срок"])
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_спрос_по_экранам():
    """Видно не только сколько жали «хочу премиум», но и откуда."""
    база, папка = _база()
    try:
        база.хочет_премиум(1, "разборы")
        база.хочет_премиум(1, "разборы")
        база.хочет_премиум(2, "вопросы")
        сводка = база.сводка()
        ок = (сводка["премиум_нажатий"] == 3 and сводка["премиум_людей"] == 2
              and сводка["премиум_откуда"][0] == ("разборы", 2)
              and "разборы — 2" in stats.текстом(сводка))
        return ок, "спрос: %s" % (сводка["премиум_откуда"],)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_в_сводке_только_числа():
    """Ни текста переписки, ни имён — сводке неоткуда их взять.

    В базе их и нет, но проверка стоит здесь же: сводка — единственное
    место, где всё сложенное вместе уходит наружу одним куском.
    """
    база, папка = _база()
    try:
        база.увидеть(1)
        база.записать_отчёт(1, {"индекс": 40, "всего": 100, "дней": 5,
                                "тренд": {"конец": 40},
                                "метрики": {"её_длина": 42}})
        база.хочет_премиум(1, "разборы")
        сводка = база.сводка()

        # Всё, кроме разбивки по экранам, — числа или None.
        экраны = сводка.pop("премиум_откуда")
        не_числа = {имя: значение for имя, значение in сводка.items()
                    if значение is not None and not isinstance(значение, int)}
        # А экраны — из закрытого списка кнопок, не из чужого текста.
        свои = all(откуда in ("разборы", "вопросы", "черновики", "подсказки",
                              "?") and isinstance(сколько, int)
                   for откуда, сколько in экраны)
        ок = not не_числа and свои
        return ок, "сводка: не числа %s, экраны %s" % (не_числа or "нет",
                                                       экраны)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_текст_собирается():
    """Сводка словами: все разделы на месте и оговорка про /start тоже."""
    база, папка = _база()
    try:
        база.увидеть(1)
        база.записать_отчёт(1, _итог(40, 100))
        текст = stats.текстом(база.сводка())
        разделы = ("ЛЮДИ", "ВОРОНКА", "РАЗБОРЫ", "СПРОС НА ПРЕМИУМ", "ДЕНЬГИ")
        ок = (all(раздел in текст for раздел in разделы)
              and stats.ОГОВОРКА in текст
              and "медиана индекса" in текст)
        return ок, "текст: %d строк" % len(текст.split("\n"))
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def main():
    случаи = (случай_пустая_база, случай_воронка_по_людям,
              случай_медиана_не_съезжает, случай_возврат_вычитается,
              случай_срок_работает, случай_спрос_по_экранам,
              случай_в_сводке_только_числа, случай_текст_собирается)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
