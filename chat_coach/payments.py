# -*- coding: utf-8 -*-
"""
Оплата: пакеты разборов за Telegram Stars.

Почему именно звёзды, а не обычная платёжка. В документации Bot API
написано прямо: бот обязан продавать цифровые товары и услуги внутри
Telegram только за Telegram Stars — «regardless of any other web portals,
apps, services or payment providers you may have set up outside the
Telegram ecosystem». Причина не в жадности Телеграма, а в правилах App
Store и Play Store, и следствие названо там же: бота перестают показывать
мобильным пользователям. Для нас это вся аудитория, так что обходить
правило нечем — включая схему «продать код на сайте, активировать в боте»:
она описана этой же фразой.

Продаём штуки, а не подписку: разбор целой переписки делают редко, и
платить за месяц ради двух разборов — плохая сделка, которую человек
заметит. Ежедневные бесплатные лимиты на вопросы, черновики и подсказки
пакет не трогает: стена, в которую упираются, — это один разбор в неделю.

Провайдер пока один, поэтому никаких классов-провайдеров здесь нет.
Место для второго — колонка provider в таблице payments: когда появится
веб-версия, которой можно торговать вне Телеграма, она встанет туда
без переделки слоя.
"""

from collections import namedtuple

import limits

ПРОВАЙДЕР_STARS = "stars"
ВАЛЮТА_STARS = "XTR"          # так Telegram называет звёзды в API

Пакет = namedtuple("Пакет", "код разборов звёзд подпись")

# Один разбор обходится примерно в девять центов на Opus, пакет из пяти —
# около сорока пяти. Сколько из ста пятидесяти звёзд дойдёт до кошелька,
# смотри в таблице Телеграма перед тем, как включать оплату: если меньше
# доллара, цены надо поднимать, а не надеяться.
ПАКЕТЫ = {
    "5": Пакет("5", 5, 150, "5 разборов переписки"),
    "15": Пакет("15", 15, 350, "15 разборов переписки"),
    "40": Пакет("40", 40, 800, "40 разборов переписки"),
}

# Порядок показа в витрине: от дешёвого к дорогому.
ПОРЯДОК = ("5", "15", "40")

_МЕТКА = "пакет:"


def пакет_по_коду(код):
    """Пакет или None. None — обычный случай, а не сбой: payload приходит
    снаружи, и в нём может оказаться что угодно."""
    return ПАКЕТЫ.get((код or "").strip())


def содержимое(пакет):
    """{вид: штук} — что именно ложится на счёт при покупке."""
    return {limits.РАЗБОР: пакет.разборов}


def в_payload(пакет):
    """Telegram разрешает 1-128 байт; «пакет:40» укладывается с запасом."""
    return _МЕТКА + пакет.код


def из_payload(строка):
    """Пакет из payload инвойса или None, если payload чужой или битый."""
    строка = (строка or "").strip()
    if not строка.startswith(_МЕТКА):
        return None
    return пакет_по_коду(строка[len(_МЕТКА):])


def цена_словами(пакет):
    return "%s — %d ⭐" % (пакет.подпись, пакет.звёзд)


def зачислить_звёзды(база, user_id, оплата):
    """Заводит оплату звёздами на счёт. Возвращает (пакет, зачли_ли_сейчас).

    «оплата» — SuccessfulPayment от aiogram; берём из него payload, сумму
    и telegram_payment_charge_id. Последний и есть ключ идемпотентности:
    Телеграм повторяет апдейт, пока бот не ответит, и без этой защиты один
    платёж лёг бы на счёт дважды. Второй раз функция вернёт (пакет, False) —
    это нормальный исход, а не ошибка.

    Возврат денег тоже держится на этом идентификаторе, поэтому он и
    хранится: без него refundStarPayment позвать не по чему.
    """
    пакет = из_payload(getattr(оплата, "invoice_payload", ""))
    if пакет is None:
        return None, False
    зачли = база.зачислить(
        user_id, ПРОВАЙДЕР_STARS,
        оплата.telegram_payment_charge_id, пакет.код,
        getattr(оплата, "total_amount", пакет.звёзд),
        getattr(оплата, "currency", ВАЛЮТА_STARS),
        содержимое(пакет))
    return пакет, зачли


def платёж_для_возврата(база, внешний_id):
    """(user_id, пакет) или (None, None), если платежа нет или он возвращён.

    Отдельно от снятия начисленного нарочно. Порядок при возврате
    обязан быть таким: сначала деньги уходят обратно человеку, и только
    потом мы снимаем разборы. Наоборот — значит в случае сбоя у Телеграма
    забрать купленное, денег не вернув.
    """
    платёж = база.найти_платёж(ПРОВАЙДЕР_STARS, внешний_id)
    if платёж is None or платёж["refunded_at"]:
        return None, None
    return платёж["user_id"], пакет_по_коду(платёж["package"])


def отметить_возврат(база, внешний_id, пакет):
    """Снимает начисленное — уже после того, как деньги вернулись."""
    return база.пометить_возврат(ПРОВАЙДЕР_STARS, внешний_id,
                                 содержимое(пакет) if пакет else {})
