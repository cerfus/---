def _сообщение(когда, автор, текст):
    return {"автор": автор, "дата": когда, "текст": текст, "вложение": False}


def _подряд(курсор, пары, шаг=timedelta(minutes=3)):
    """Список (автор, текст) превращает в сообщения со сдвигом по времени."""
    чат = []
    for автор, текст in пары:
        чат.append(_сообщение(курсор, автор, текст))
        курсор += шаг
    return чат, курсор


# Без разговоров про третьих: стояло «а он тебе что ответил» — каждая
# восьмая реплика, 12% её сообщений, и рамка честно называла это
# советчицей. Дружеская перепалка и разговор про третьего — разные вещи,
# и мерить ими одну переписку нельзя; здесь нужна чистая перепалка.
ЕЁ_ДРУЖБА = ["да ты пипидастр", "ахахах ну ты дал", "покаж что купил",
             "слушай ну ты чего", "ну ты и лошара",
             "я щас умру со смеху", "да ладно тебе", "ну такое"]
ЕГО_ДРУЖБА = ["ну че там", "прикинь", "смотри какая тема", "да ниче",
              "я в шоке", "вот это поворот", "хех", "ну ты понял"]

ЕЁ_ТЕПЛО = ["приве-е-ет! как прошёл день? 😊",
            "ахаха ты как всегда) а давай в выходные куда-нибудь выберемся?",
            "соскучилась) когда увидимся?",
            "мне с тобой правда хорошо, ты знаешь?",
            "обними меня, я устала 🥺"]
ЕГО_ТЕПЛО = ["привет, нормально", "давай", "я тоже соскучился",
             "в субботу могу", "обнимаю"]

ЕЁ_ХОЛОД = ["норм", "угу", "ок", "посмотрим", "не знаю"]
ЕГО_ХОЛОД = ["привет, как дела? чем занимаешься?",
             "может увидимся на этой неделе",
             "а когда ты свободна?", "ну ок, напиши как решишь"]


def дружба(недель=10, в_день=40):
    """Полсотни сообщений в день месяцами и ноль романтики."""
    чат, курсор = [], СТАРТ
    for день in range(недель * 7):
        for н in range(в_день // 2):
            чат.append(_сообщение(курсор, "Иван", ЕГО_ДРУЖБА[н % 8]))
            курсор += timedelta(seconds=5)
            чат.append(_сообщение(курсор, "Аня", ЕЁ_ДРУЖБА[н % 8]))
            курсор += timedelta(seconds=6)
        курсор += timedelta(hours=20)
    return чат


def ухаживание(недель=10):
    """Она идёт навстречу: сама начинает, зовёт, говорит про чувства."""
    чат, курсор = [], СТАРТ
    for _неделя in range(недель):
        for _день in range(5):
            кусок, курсор = _подряд(курсор, [
                ("Аня", ЕЁ_ТЕПЛО[0]), ("Иван", ЕГО_ТЕПЛО[0]),
                ("Аня", ЕЁ_ТЕПЛО[1]), ("Иван", ЕГО_ТЕПЛО[1]),
                ("Аня", ЕЁ_ТЕПЛО[2]), ("Иван", ЕГО_ТЕПЛО[2]),
                ("Аня", ЕЁ_ТЕПЛО[3]), ("Иван", ЕГО_ТЕПЛО[3]),
                ("Аня", ЕЁ_ТЕПЛО[4]), ("Иван", ЕГО_ТЕПЛО[4]),
            ])
            чат += кусок
            курсор += timedelta(hours=14)
    return чат


def остыло(недель=10):
    """Было тепло, стало пусто: пишет только он, ответы односложные."""
    чат, курсор = [], СТАРТ
    for неделя in range(недель):
        тепло = неделя < недель // 3
        for _день in range(4):
            if тепло:
                кусок, курсор = _подряд(курсор, [
                    ("Аня", ЕЁ_ТЕПЛО[0]), ("Иван", ЕГО_ТЕПЛО[0]),
                    ("Аня", ЕЁ_ТЕПЛО[1]), ("Иван", ЕГО_ТЕПЛО[1]),
                ])
            else:
                кусок, курсор = _подряд(курсор, [
                    ("Иван", ЕГО_ХОЛОД[0]), ("Иван", ЕГО_ХОЛОД[1]),
                    ("Аня", ЕЁ_ХОЛОД[0]), ("Иван", ЕГО_ХОЛОД[2]),
                ], шаг=timedelta(hours=5))
            чат += кусок
            курсор += timedelta(hours=12)
    return чат


def отказ(недель=6):
    """Обычная переписка, а в конце — прямой отказ её словами."""
    чат = остыло(недель)
    курсор = чат[-1]["дата"] + timedelta(hours=3)
    хвост, _ = _подряд(курсор, [
        ("Иван", "может сходим куда-нибудь вдвоём?"),
        ("Аня", "нет, спасибо. давай останемся друзьями"),
    ])
    return чат + хвост


def советчица(недель=8):
    """Она обсуждает с ним третьего человека, и так всю переписку."""
    чат, курсор = [], СТАРТ
    for _неделя in range(недель):
        for _день in range(5):
            кусок, курсор = _подряд(курсор, [
                ("Аня", "слушай, он мне вчера написал, а я не знаю что ответить"),
                ("Иван", "а ты что хочешь?"),
                ("Аня", "ну он зовёт гулять, а ты как думаешь, стоит?"),
                ("Иван", "сходи, чего теряешь"),
                ("Аня", "вот и я думаю) ты меня всегда понимаешь"),
            ])
            чат += кусок
            курсор += timedelta(hours=15)
    return чат


ПЕРЕПИСКИ = (
    ("дружба", дружба, frame.ДРУЖБА),
    ("ухаживание", ухаживание, frame.УХАЖИВАНИЕ),
    ("остыло", остыло, frame.ЗАГЛОХЛО),
    ("отказ", отказ, frame.ОТКАЗ),
    ("советчица", советчица, frame.СОВЕТЧИЦА),
)


