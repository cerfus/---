def main():
    разбор = argparse.ArgumentParser(description="Стенд разбора.")
    разбор.add_argument("--с-моделью", dest="с_моделью", action="store_true",
                        help="прогнать настоящий разбор (стоит денег)")
    разбор.add_argument("--куда", default="прогон",
                        help="папка для ответов модели")
    разбор.add_argument("--сравнить", nargs=2, metavar=("БЫЛО", "СТАЛО"),
                        help="показать два прогона рядом")
    разбор.add_argument("--выгрузка", help="своя переписка вместо выдуманных")
    разбор.add_argument("--я", default="", help="кто из двоих ты в выгрузке")
    разбор.add_argument("--да", action="store_true",
                        help="не спрашивать подтверждения расхода")
    аргументы = разбор.parse_args()

    if аргументы.сравнить:
        сравнить(*аргументы.сравнить)
        return 0

    переписки = ПЕРЕПИСКИ
    if аргументы.выгрузка:
        сообщения = своя_выгрузка(аргументы.выгрузка, аргументы.я)
        переписки = (("своя", lambda: сообщения, None),)

    провалов = 0
    if not аргументы.выгрузка:
        провалов = проверить_рамки()
        показать_выборку()

    if аргументы.с_моделью:
        цена = оценить_расход(переписки)
        print()
        print("Прогон через модель: примерно $%.2f. Это настоящие деньги."
              % цена)
        if not аргументы.да:
            ответ = input("Продолжать? [y/N] ").strip().lower()
            if ответ not in ("y", "yes", "д", "да"):
                print("Не стал.")
                return 0
        print()
        print("РАЗБОР (модель %s, усилие %s)"
              % (analysis.МОДЕЛЬ, analysis.УСИЛИЕ_РАЗБОРА))
        прогнать(аргументы.куда, переписки)
        print()
        print("Ответы в папке %s. Сравнить с прошлым прогоном:"
              % аргументы.куда)
        print("  python eval.py --сравнить прошлая_папка %s" % аргументы.куда)

    print()
    print("Проверок: %d, провалов: %d" % (len(ПЕРЕПИСКИ), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
