def проверить_рамки():
    """Рамка на длинных перепиской. Возвращает число провалов."""
    провалов = 0
    print("РАМКИ (без модели, без сети)")
    for имя, собрать, ждём in ПЕРЕПИСКИ:
        чат = собрать()
        конец = чат[-1]["дата"]
        итог = metrics.analyse(чат, "Иван", "Аня")
        рамка = frame.определить(чат, "Иван", "Аня", итог, сейчас=конец)
        сошлось = рамка["тип"] == ждём
        провалов += 0 if сошлось else 1
        print("  %-12s %5d сообщ.  ждали %-12s вышло %-12s %s"
              % (имя, len(чат), ждём, рамка["тип"],
                 "ок" if сошлось else "ПЛОХО"))
    return провалов


def _разные_строки(отобранное):
    """Множество строк выборки: одна реплика могла попасть в два места."""
    строки = set(отобранное["целиком"]) | set(отобранное["начало"])
    строки |= set(отобранное["последние"])
    for _пауза, кусок in отобранное["обрывы"]:
        строки |= set(кусок)
    for кусок in отобранное["удачные"]:
        строки |= set(кусок)
    for _подпись, кусок in отобранное["по_неделям"]:
        строки |= set(кусок)
    return строки


def показать_выборку():
    """Сколько переписки видит модель. Главное число всей работы."""
    print()
    print("ЧТО ВИДИТ МОДЕЛЬ")
    for имя, собрать, _ждём in ПЕРЕПИСКИ:
        чат = собрать()
        отобранное = analysis.выборка(чат, "Иван", "Аня")
        # Разные строки, а не сумма кусков: обрывы и удачные места
        # повторяют то, что уже попало в начало и в хвост, и сумма
        # давала «показываем 123%» — больше, чем есть в переписке.
        строк = len(_разные_строки(отобранное))
        итог = metrics.analyse(чат, "Иван", "Аня")
        основа = analysis.переписка_для_модели(итог, отобранное)
        print("  %-12s из %5d сообщений показываем %4d (%2d%%), %6d знаков"
              % (имя, len(чат), строк, round(строк * 100 / len(чат)),
                 len(основа)))


