# Померено один раз через messages.count_tokens на этих же переписках:
# русский текст с метками времени даёт примерно столько знаков на токен.
# Держим числом, а не походом по сети на каждом разборе.
ЗНАКОВ_НА_ТОКЕН = 2.7
ЦЕНА_ВХОДА = 5.0 / 1_000_000       # $/токен, claude-opus-5
ЦЕНА_ВЫХОДА = 25.0 / 1_000_000


def оценить_расход(переписки):
    """Грубая оценка счёта за прогон, в долларах."""
    всего = 0.0
    for _имя, собрать, _ждём in переписки:
        чат = собрать()
        итог = metrics.analyse(чат, "Иван", "Аня")
        основа = analysis.переписка_для_модели(
            итог, analysis.выборка(чат, "Иван", "Аня"))
        вход = len(основа) / ЗНАКОВ_НА_ТОКЕН
        всего += вход * ЦЕНА_ВХОДА + 4000 * ЦЕНА_ВЫХОДА
    return всего


def прогнать(куда, переписки, цель="понять, есть ли шанс"):
    """Настоящий разбор каждой переписки. Складывает ответы в папку."""
    os.makedirs(куда, exist_ok=True)
    for имя, собрать, _ждём in переписки:
        чат = собрать()
        конец = чат[-1]["дата"]
        итог = metrics.analyse(чат, "Иван", "Аня")
        рамка = frame.определить(чат, "Иван", "Аня", итог, сейчас=конец)
        отобранное = analysis.выборка(чат, "Иван", "Аня")
        print("  %-12s считаю…" % имя, end="", flush=True)
        try:
            разбор = analysis.разобрать(None, итог, цель,
                                        отобранное=отобранное, рамка=рамка)
        except analysis.ОшибкаРазбора as сбой:
            print(" сорвалось: %s" % сбой)
            continue
        текст = analysis.текст_разбора(разбор, рамка)
        with open(os.path.join(куда, имя + ".txt"), "w",
                  encoding="utf-8") as fh:
            fh.write(текст)
        спорное = analysis.возражение(разбор)
        print(" готово%s" % (", модель возразила рамке" if спорное else ""))


def сравнить(было, стало):
    """Два прогона рядом. Читают это глазами — иного мерила у советов нет."""
    имена = sorted(set(os.listdir(было)) | set(os.listdir(стало)))
    for имя in имена:
        путь_было = os.path.join(было, имя)
        путь_стало = os.path.join(стало, имя)
        левое = _прочитать(путь_было)
        правое = _прочитать(путь_стало)
        print("=" * 72)
        print(имя)
        print("=" * 72)
        if левое == правое:
            print("  (не изменилось)")
            continue
        for строка in difflib.unified_diff(
                левое.split("\n"), правое.split("\n"),
                fromfile=было, tofile=стало, lineterm="", n=2):
            print(строка)
        print()


def _прочитать(путь):
    try:
        with open(путь, encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        return "(нет файла)"


def своя_выгрузка(путь, кто):
    """Переписка с диска — для прогона на настоящих данных.

    В репозиторий она не попадает и попасть не может: путь приходит
    ключом и живёт только в этом запуске.
    """
    сообщения = export_parser.read_export(путь)
    двое, _групповой = export_parser.two_sides(сообщения)
    if кто not in двое:
        raise SystemExit("В этой переписке есть %s — кто из них ты? "
                         "Передай --я «имя»" % " и ".join(двое))
    return сообщения


