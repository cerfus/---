"""
Стенд: чем меряем, что бот стал умнее.

    python eval.py                       — бесплатная половина, без сети
    python eval.py --с-моделью --куда до — прогнать разбор и сложить ответы
    python eval.py --сравнить до после   — показать два прогона рядом

Половины две, и они про разное.

**Бесплатная и точная.** Набор выдуманных переписок, у каждой заранее
известен ответ: какая рамка, есть ли отказ. Это проверяется автоматом
и стоит ноль. Переписки нарочно длинные — на коротких рамка не ломается,
а ломается она как раз там, где переписка идёт месяцами.

**Платная и на глаз.** Те же переписки прогоняются через настоящий
разбор, ответы складываются в папку. Оценивать связность советов
автоматом нечем — их читают глазами, но читают одно и то же на одних
и тех же входах, а не по памяти неделю спустя.

Настоящие переписки сюда не кладутся никогда. Свою выгрузку можно
подсунуть ключом --выгрузка: она останется на твоей машине.
"""

