# -*- coding: utf-8 -*-
"""Проверка метрик и индекса. Запуск: python test_metrics.py

Смысл проверок не в точных числах — веса ещё будут крутиться, — а в том,
что заведомо тёплая переписка и заведомо холодная не перепутаны местами
и что тренд ловит охлаждение.
"""

from datetime import datetime, timedelta

import console          # noqa: F401
import metrics

СТАРТ = datetime(2026, 8, 1, 12, 0)


def _сообщение(курсор, автор, текст):
    return {"автор": автор, "дата": курсор, "текст": текст, "вложение": False}


def тёплый(курсор, сколько):
    """Она сама начинает, отвечает быстро, пишет длинно и спрашивает."""
    чат = []
    for _ in range(сколько):
        чат.append(_сообщение(курсор, "Аня",
                              "приве-е-ет! как прошёл день, что интересного? 😊"))
        курсор += timedelta(minutes=4)
        чат.append(_сообщение(курсор, "Иван", "нормально, работал"))
        курсор += timedelta(minutes=2)
        чат.append(_сообщение(курсор, "Аня",
                              "ахаха ты как всегда) а давай в выходные куда-нибудь "
                              "выберемся? я нашла классное место, покажу?"))
        курсор += timedelta(minutes=3)
        чат.append(_сообщение(курсор, "Иван", "давай"))
        курсор += timedelta(minutes=2)
        чат.append(_сообщение(курсор, "Аня", "ура!! тогда договорились ❤"))
        курсор += timedelta(hours=10)          # следующий разговор — снова её
    return чат, курсор


def холодный(курсор, сколько):
    """Пишу только я, дублю сообщения, она отвечает через сутки односложно.

    Паузы между заходами нарочно длиннее двух суток: иначе каждое открытие
    разговора формально оказывается запоздалым ответом, инициативу измерить
    не по чему, и проверка теряет смысл. В живой переписке молчание как раз
    такое и бывает.
    """
    чат = []
    for _ in range(сколько):
        чат.append(_сообщение(курсор, "Иван", "привет, как дела? чем занимаешься?"))
        курсор += timedelta(minutes=1)
        чат.append(_сообщение(курсор, "Иван", "может увидимся на этой неделе"))
        курсор += timedelta(hours=20)          # разговор оборвался на мне
        чат.append(_сообщение(курсор, "Аня", "норм"))
        курсор += timedelta(minutes=5)
        чат.append(_сообщение(курсор, "Иван", "а когда ты свободна?"))
        курсор += timedelta(days=3)            # снова тишина, и снова пишу я
    return чат, курсор


def случай_тёплая():
    чат, _ = тёплый(СТАРТ, 8)
    итог = metrics.analyse(чат, "Иван", "Аня")
    баллы = {пункт["фактор"]: пункт["балл"] for пункт in итог["разбивка"]}
    ок = (итог["индекс"] >= 70
          and баллы["инициатива"] == 1.0
          and баллы["обрывы"] == 1.0)          # штрафа нет
    return ок, "тёплая: индекс=%s баллы=%s" % (итог["индекс"], баллы)


def случай_холодная():
    чат, _ = холодный(СТАРТ, 8)
    итог = metrics.analyse(чат, "Иван", "Аня")
    баллы = {пункт["фактор"]: пункт["балл"] for пункт in итог["разбивка"]}
    ок = (итог["индекс"] <= 30
          and баллы["инициатива"] == 0.0      # поздний ответ — не инициатива
          and баллы["дубли"] == 0.0           # писал подряд без ответа
          and баллы["обрывы"] == 0.0)
    return ок, "холодная: индекс=%s баллы=%s" % (итог["индекс"], баллы)


def случай_тренд():
    """Сначала было хорошо, потом стало плохо — тренд обязан это увидеть."""
    чат, курсор = тёплый(СТАРТ, 6)
    хвост, _ = холодный(курсор + timedelta(hours=10), 6)
    итог = metrics.analyse(чат + хвост, "Иван", "Аня")
    тренд = итог["тренд"]
    ок = (тренд is not None and тренд["разница"] < -15
          and "Раньше было теплее" in metrics.словами(итог))
    return ок, "тренд: %s" % (тренд,)


def случай_вердикт_по_нынешнему():
    """Остывшая переписка не должна получать бодрый вердикт.

    Общий индекс усредняет всю историю, поэтому полгода тёплого общения
    перевешивают месяц молчания — и человек, пришедший понять, почему всё
    заглохло, слышал бы «она вовлечена». Ведём разговор от последней трети.
    """
    чат, курсор = тёплый(СТАРТ, 6)
    хвост, _ = холодный(курсор + timedelta(hours=10), 6)
    итог = metrics.analyse(чат + хвост, "Иван", "Аня")
    вывод = metrics.словами(итог)
    ок = (metrics.сейчас(итог) < итог["индекс"] - 15
          and "вовлечена" not in вывод)
    return ок, ("вердикт: сейчас=%s всего=%s %r"
                % (metrics.сейчас(итог), итог["индекс"], вывод))


def случай_без_дат():
    """Текстовый лог без дат: время посчитать нельзя, но индекс всё равно есть.

    Вес недоступных факторов обязан разойтись по остальным, а не утянуть
    оценку в ноль.
    """
    чат = []
    for _ in range(10):
        чат.append({"автор": "Аня", "дата": None, "вложение": False,
                    "текст": "привет! как ты, что нового? 😊"})
        чат.append({"автор": "Иван", "дата": None, "вложение": False,
                    "текст": "нормально"})
    итог = metrics.analyse(чат, "Иван", "Аня")
    факторы = {пункт["фактор"] for пункт in итог["разбивка"]}
    ок = (итог["индекс"] is not None and итог["индекс"] > 50
          and "скорость" not in факторы       # без дат не считается
          and "вопросы" in факторы)
    return ок, "без дат: индекс=%s факторы=%s" % (итог["индекс"], sorted(факторы))


def случай_разговоры():
    """Разрыв больше шести часов начинает новый разговор, меньше — нет."""
    чат = [
        _сообщение(СТАРТ, "Иван", "привет"),
        _сообщение(СТАРТ + timedelta(hours=5), "Аня", "привет"),
        _сообщение(СТАРТ + timedelta(hours=12), "Аня", "как ты?"),
    ]
    разговоры = metrics._разговоры(чат)
    серии = metrics._серии(чат)
    ок = (len(разговоры) == 2 and len(разговоры[0]) == 2
          and len(серии) == 2 and len(серии[1][1]) == 2)
    return ок, "разговоры=%d серий=%d" % (len(разговоры), len(серии))


def случай_устойчивость_куска():
    """Сдвиг выделения на одно сообщение не должен двигать индекс.

    У вставленного куска дат нет, поэтому вся переписка — один разговор,
    и «инициатива» с «обрывами» держались на одном наблюдении: кто случайно
    оказался первым и последним в скопированном. Сдвиг на сообщение уводил
    оценку на одиннадцать баллов. Теперь фактор, за которым стоит меньше
    МИНИМУМ_НАБЛЮДЕНИЙ случаев, не показывается вовсе.
    """
    пары = [("Аня", "привет! как ты?"), ("Иван", "нормально")] * 8

    def индекс(пары):
        чат = [{"автор": автор, "дата": None, "текст": текст, "вложение": False}
               for автор, текст in пары]
        return metrics.analyse(чат, "Иван", "Аня")

    слева = индекс(пары)
    сдвинутый = индекс(пары[1:] + [("Аня", "ну ладно")])
    пропущено = {имя for имя, _ in metrics.не_посчитано(слева)}
    ок = (слева["индекс"] == сдвинутый["индекс"]
          and {"инициатива", "обрывы"} <= пропущено)
    return ок, ("устойчивость: %s против %s, не посчитано %s"
                % (слева["индекс"], сдвинутый["индекс"], sorted(пропущено)))


def случай_что_не_посчитано():
    """Отчёт обязан называть факторы, которых ему не хватило."""
    чат = [{"автор": автор, "дата": None, "текст": текст, "вложение": False}
           for автор, текст in [("Аня", "привет! как ты? 😊"), ("Иван", "норм")] * 8]
    итог = metrics.analyse(чат, "Иван", "Аня")
    пропущено = dict(metrics.не_посчитано(итог))
    посчитано = {п["фактор"] for п in итог["разбивка"]}
    ок = ("скорость" in пропущено
          and "вопросы" in посчитано
          and not (set(пропущено) & посчитано)     # одно и то же дважды нельзя
          and all(словами for словами in пропущено.values()))
    return ок, "не посчитано: %s" % sorted(пропущено)



def main():
    случаи = (случай_тёплая, случай_холодная, случай_тренд,
              случай_вердикт_по_нынешнему, случай_без_дат, случай_разговоры,
              случай_устойчивость_куска, случай_что_не_посчитано)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
