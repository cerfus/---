# -*- coding: utf-8 -*-
"""
Вывод в консоль на Windows.

Пока печатаем прямо в окно консоли, всё хорошо: Python 3.6+ отдаёт туда
юникод напрямую. Но стоит перенаправить вывод в файл —

    python report.py --from result.json > отчёт.txt

— и берётся кодировка системы, на русской Windows это cp1251. Ни стрелки
«→», ни полоски «█», которыми нарисован отчёт, в ней нет, и печать падает
с UnicodeEncodeError на ровном месте.

Приём тот же, что в tg_defects/common.py: разрешаем подменить то, что не
влезло, вместо того чтобы ронять всю программу из-за одного символа.

Достаточно импортировать модуль — настройка применяется сама.
"""

import sys


def настроить():
    for поток in (sys.stdout, sys.stderr):
        if hasattr(поток, "reconfigure"):
            try:
                поток.reconfigure(errors="replace")
            except (ValueError, OSError):
                pass


настроить()
