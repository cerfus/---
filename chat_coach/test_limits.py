# -*- coding: utf-8 -*-
"""Проверка квот и хранилища. Запуск: python test_limits.py

Отдельно проверяется то, ради чего всё затевалось: в базу не должно
попасть ни одного куска переписки.
"""

import os
import shutil
import tempfile
from datetime import datetime

import console          # noqa: F401
import limits
import storage


def _база():
    папка = tempfile.mkdtemp()
    return storage.База(os.path.join(папка, "бот.sqlite3")), папка


def случай_недельный_разбор():
    """Бесплатно — один разбор в неделю, на следующей неделе снова можно."""
    база, папка = _база()
    try:
        эта_неделя = datetime(2026, 9, 9, 12, 0)      # среда
        та_же_неделя = datetime(2026, 9, 11, 23, 0)   # пятница
        новая_неделя = datetime(2026, 9, 14, 9, 0)    # понедельник

        первый = limits.потратить(база, 7, limits.РАЗБОР, сейчас=эта_неделя)
        второй = limits.потратить(база, 7, limits.РАЗБОР, сейчас=та_же_неделя)
        третий = limits.потратить(база, 7, limits.РАЗБОР, сейчас=новая_неделя)
        осталось = limits.осталось(база, 7, limits.РАЗБОР, сейчас=новая_неделя)

        ок = (первый is True and второй is False and третий is True
              and осталось == 0)
        return ок, ("неделя: первый=%s второй=%s после сброса=%s осталось=%s"
                    % (первый, второй, третий, осталось))
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_дневные_вопросы():
    """Три вопроса в день, четвёртый — нет, назавтра снова три."""
    база, папка = _база()
    try:
        сегодня = datetime(2026, 9, 13, 10, 0)
        завтра = datetime(2026, 9, 14, 10, 0)
        сегодняшние = [limits.потратить(база, 7, limits.ВОПРОС, сейчас=сегодня)
                       for _ in range(4)]
        завтрашний = limits.потратить(база, 7, limits.ВОПРОС, сейчас=завтра)
        ок = (сегодняшние == [True, True, True, False] and завтрашний is True)
        return ок, "день: %s, завтра=%s" % (сегодняшние, завтрашний)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_возврат():
    """Сорвавшийся разбор не съедает единственную бесплатную попытку."""
    база, папка = _база()
    try:
        когда = datetime(2026, 9, 13, 10, 0)
        limits.потратить(база, 7, limits.РАЗБОР, сейчас=когда)
        limits.вернуть(база, 7, limits.РАЗБОР, сейчас=когда)
        снова = limits.потратить(база, 7, limits.РАЗБОР, сейчас=когда)
        return снова is True, "возврат: снова можно=%s" % снова
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_тариф():
    """У премиума лимит свой, и он не мешает чужим счётчикам."""
    база, папка = _база()
    try:
        когда = datetime(2026, 9, 13, 10, 0)
        база.поставить_тариф(7, "premium")
        разборы = [limits.потратить(база, 7, limits.РАЗБОР, сейчас=когда)
                   for _ in range(5)]
        чужой = limits.осталось(база, 8, limits.РАЗБОР, сейчас=когда)
        ок = all(разборы) and база.тариф(7) == "premium" and чужой == 1
        return ок, ("тариф: премиум разборы=%s, у соседа осталось=%s"
                    % (разборы, чужой))
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_без_переписки_в_базе():
    """В сохранённом отчёте не должно быть ни одной буквы из переписки."""
    база, папка = _база()
    try:
        секрет = "поехали ко мне на дачу в субботу"
        итог = {
            "индекс": 61, "всего": 120, "дней": 30,
            "тренд": {"начало": 70, "конец": 52, "разница": -18},
            "метрики": {"моих_сообщений": 60, "её_сообщений": 60,
                        "разговоров": 12, "начала_она": 5, "начал_кто_то": 11,
                        "оборвалось_на_мне": 4, "мой_ответ_сек": 120,
                        "её_ответ_сек": 900, "моя_длина": 40, "её_длина": 25,
                        "её_вопросы": 0.2, "её_эмоции": 0.3, "ночных": 0.1,
                        "моих_серий_подряд": 3,
                        # Прилетело лишнее — в базу попасть не должно.
                        "последняя_реплика": секрет},
        }
        база.записать_отчёт(7, итог)
        with open(база.путь, "rb") as fh:
            сырые_байты = fh.read()
        история = база.история(7)

        попало = секрет.encode("utf-8") in сырые_байты
        ок = (not попало and len(история) == 1
              and история[0]["score_now"] == 52)
        return ок, ("приватность: текст в базе=%s, записей=%d"
                    % (попало, len(история)))
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_забыть():
    """Команда удаления стирает человека целиком."""
    база, папка = _база()
    try:
        когда = datetime(2026, 9, 13, 10, 0)
        limits.потратить(база, 7, limits.РАЗБОР, сейчас=когда)
        база.хочет_премиум(7, "лимит разборов")
        база.записать_отчёт(7, {"индекс": 50, "всего": 10, "дней": 2,
                                "метрики": {}})
        база.забыть(7)
        ок = (база.история(7) == []
              and limits.осталось(база, 7, limits.РАЗБОР, сейчас=когда) == 1
              and база.спрос_на_премиум()["всего"] == 0)
        return ок, "забыть: история=%s" % (база.история(7),)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def случай_спрос():
    """Нажатия на «хочу премиум» считаются по людям и по разам."""
    база, папка = _база()
    try:
        база.хочет_премиум(1, "лимит разборов")
        база.хочет_премиум(1, "лимит вопросов")
        база.хочет_премиум(2, "лимит разборов")
        спрос = база.спрос_на_премиум()
        ок = спрос == {"всего": 3, "людей": 2}
        return ок, "спрос: %s" % (спрос,)
    finally:
        shutil.rmtree(папка, ignore_errors=True)


def main():
    случаи = (случай_недельный_разбор, случай_дневные_вопросы, случай_возврат,
              случай_тариф, случай_без_переписки_в_базе, случай_забыть,
              случай_спрос)
    провалов = 0
    for случай in случаи:
        ок, описание = случай()
        if not ок:
            провалов += 1
            print("ПЛОХО  %s" % описание)
    print("Проверок: %d, провалов: %d" % (len(случаи), провалов))
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
