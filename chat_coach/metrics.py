# Нарезка переписки
# --------------------------------------------------------------------------

def _серии(сообщения):
    """Подряд идущие сообщения одного человека — одна серия.

    В переписке думают не сообщениями, а репликами: три сообщения подряд —
    это одна реплика, и отвечать будут на неё целиком.
    """
    серии = []
    for сообщение in сообщения:
        if серии and серии[-1][0] == сообщение["автор"]:
            серии[-1][1].append(сообщение)
        else:
            серии.append((сообщение["автор"], [сообщение]))
    return серии


def _разговоры(сообщения):
    """Режет переписку на разговоры по длинной паузе."""
    разговоры, текущий = [], []
    for сообщение in сообщения:
        if текущий and сообщение["дата"] and текущий[-1]["дата"]:
            if сообщение["дата"] - текущий[-1]["дата"] > ПАУЗА_МЕЖДУ_РАЗГОВОРАМИ:
                разговоры.append(текущий)
                текущий = []
        текущий.append(сообщение)
    if текущий:
        разговоры.append(текущий)
    return разговоры


def _инициативы(разговоры):
    """Кто размораживает общение. Возвращает ({автор: сколько}, всего).

    Считать просто «кто написал первым в разговоре» нельзя: если человек
    отвечает через сутки, формально начинается новый разговор — и молчун
    получал бы очки за инициативу ровно за то, что тянул с ответом.
    Поэтому разговор, который открыт поздним ответом собеседника
    (в пределах 48 часов), в счёт не идёт вообще — ни одному, ни другому.
    """
    счёт, всего = {}, 0
    for номер, разговор in enumerate(разговоры):
        открыл = разговор[0]["автор"]
        if номер:
            прошлое = разговоры[номер - 1][-1]
            есть_даты = прошлое["дата"] and разговор[0]["дата"]
            пауза = (разговор[0]["дата"] - прошлое["дата"]) if есть_даты else None
            if (прошлое["автор"] != открыл and пауза is not None
                    and пауза <= ПРЕДЕЛ_ОТВЕТА):
                continue                # это поздний ответ, а не начало
        всего += 1
        счёт[открыл] = счёт.get(открыл, 0) + 1
    return счёт, всего


def _задержки(серии):
    """Сколько каждый думал перед ответом. {автор: [секунды, ...]}"""
    ответы = {}
    for номер in range(1, len(серии)):
        автор, реплика = серии[номер]
        _, предыдущая = серии[номер - 1]
        было, стало = предыдущая[-1]["дата"], реплика[0]["дата"]
        if not было or not стало:
            continue
        пауза = стало - было
        if timedelta(0) <= пауза <= ПРЕДЕЛ_ОТВЕТА:
            ответы.setdefault(автор, []).append(пауза.total_seconds())
    return ответы


