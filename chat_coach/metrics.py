# -*- coding: utf-8 -*-
"""
Метрики переписки и индекс интереса.

Всё здесь считается обычным питоном, без ИИ: быстро, бесплатно и, главное,
объяснимо — на каждый балл видно, откуда он взялся. Это принципиально:
показывать «интерес 47%» без разбивки — значит просить верить на слово.

Индекс — это статистика поведения в переписке, а не измерение чувств.
Так и говорим пользователю: цифра описывает, как идёт общение, и ничего
не знает про человека.

Главный ответ даёт не сам индекс, а тренд: «было 70, стало 40» полезнее
любого среза, потому что говорит, куда всё движется.
"""

import math
import re
from datetime import datetime, timedelta
from statistics import median

# Переписка распадается на разговоры: если молчали дольше — это уже
# новый заход, а не долгий ответ.
ПАУЗА_МЕЖДУ_РАЗГОВОРАМИ = timedelta(hours=6)

# Дольше этого ответ ответом не считается: это возвращение к общению.
ПРЕДЕЛ_ОТВЕТА = timedelta(hours=48)

НОЧЬ_С, НОЧЬ_ДО = 23, 5

# Сколько наблюдений нужно фактору, чтобы его вообще считать.
#
# Без этого порога вставленный кусок переписки даёт чушь: дат в нём нет,
# значит вся переписка — один разговор, и «инициатива» с «обрывами»
# определяются одним наблюдением — кто случайно оказался первым и последним
# в скопированном. Сдвиг выделения на одно сообщение уводил индекс на
# одиннадцать баллов. Фактор, за которым стоит один случай, лучше не
# показывать вовсе: его вес разойдётся по тем, которые что-то знают.
МИНИМУМ_НАБЛЮДЕНИЙ = 3

# Чей ход — писать ли тебе прямо сейчас.
ХОД_ТВОЙ = "твой"          # последнее слово за ней, отвечать тебе
ХОД_ЕЁ = "её"              # ты написал, она ещё не ответила — ждём
ХОД_МОЖНО = "можно"        # ты написал давно, это уже не добивка
ХОД_НЕЯСЕН = "неясен"      # дат нет, измерить молчание нечем

# Раньше суток добивать не надо никогда, даже если она обычно отвечает
# за минуту: «написал ещё раз через три часа» — это и есть те самые
# сообщения подряд без ответа, которые фактор «дубли» и штрафует.
ПОРОГ_ДОБИВКИ = timedelta(hours=24)
# А если она и так отвечает через сутки, то ждать надо дольше суток.
ДОЛЕЙ_ОТ_ЕЁ_МЕДИАНЫ = 3

# Сколько сообщений нужно неделе, чтобы её индекс что-то значил.
# Меньше — дыра в линии: она честнее выдуманной точки.
МИНИМУМ_ЗА_НЕДЕЛЮ = 10

# Насколько большой следующий шаг уместен по нынешним цифрам. Цель от
# этого не меняется — меняется размер шага к ней: звать на свидание там,
# где она отвечает односложно раз в сутки, значит повторять ту самую
# ошибку, которую весь этот разбор и должен показывать.
СТУПЕНЬ_МАЛАЯ = "малая"
СТУПЕНЬ_СРЕДНЯЯ = "средняя"
СТУПЕНЬ_ПРЯМАЯ = "прямая"

ХОДЫ = {
    ХОД_ТВОЙ: "последнее слово за ней — отвечать тебе",
    ХОД_ЕЁ: "ты написал, а она ещё не ответила",
    ХОД_МОЖНО: "ты писал давно, ответа не было: это возвращение разговора, "
               "а не добивка",
    ХОД_НЕЯСЕН: "дат в переписке нет, давно ли ты писал — неизвестно",
}

СТУПЕНИ = {
    СТУПЕНЬ_МАЛАЯ: "одно лёгкое сообщение без просьб и приглашений; "
                   "задача — чтобы ей захотелось ответить",
    СТУПЕНЬ_СРЕДНЯЯ: "конкретный вопрос или мягкое предложение, "
                     "без назначения времени и места",
    СТУПЕНЬ_ПРЯМАЯ: "можно прямо: конкретное предложение с местом и временем",
}

_ЭМОДЗИ = re.compile(
    "[\U0001F300-\U0001FAFF\U00002600-\U000027BF\U0001F900-\U0001F9FF"
    "\U0001F1E6-\U0001F1FF❤♥☺]")
_СМЕХ = re.compile(r"(?:ах){2,}|(?:ха){2,}|хех|лол|ору|\){2,}", re.IGNORECASE)


