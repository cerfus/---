# Отдельные метрики
# --------------------------------------------------------------------------

def _доля(сколько, всего):
    return (сколько / всего) if всего else None


def _скорость(мой, её):
    """Насколько она заставляет ждать по сравнению с тем, как жду я.

    Быстрее меня — уже потолок: смысл не в гонке, а в том, не держит ли она
    меня в ожидании дольше, чем я её.

    Ноль секунд проверяется явно. Время в переписке бывает с точностью до
    минуты, и в живой перепалке медиана ответа честно равна нулю — а «если
    медиана» в питоне на нуле ложно, и фактор молча выпадал ровно тогда,
    когда общение идёт бойчее всего.
    """
    if мой is None or её is None:
        return None
    if её <= 0:
        return 1.0                  # отвечает мгновенно, быстрее некуда
    return min(мой / её, 1.0)


def _длина(сообщения):
    """Средняя длина написанного. Сообщения-вложения не в счёт:
    стикер не короткий ответ, он просто без букв."""
    буквы = [len(с["текст"]) for с in сообщения if с["текст"]]
    return (sum(буквы) / len(буквы)) if буквы else None


# Половина людей в мессенджерах не ставит знак вопроса вовсе. Считать
# вопросы только по «?» — значит показать «0% вопросов» человеку, который
# спрашивает «че ждать» и «а кто еще пойдет»; фактор весит 15, и такой ноль
# прямо врёт в вердикте «сама ли расспрашивает».
#
# Список нарочно узкий. «Что» сюда не входит: «что она красиво выглядит» —
# не вопрос, а придаточное, и таких больше, чем настоящих вопросов с «что».
# Частицы «нибудь», «то», «либо» отсекаются: «как нибудь выставлю» — тоже
# не вопрос.
_ВОПРОС_СЛОВОМ = re.compile(
    r"^\s*(?:а\s+|ну\s+|и\s+)?"
    r"(?:кто|че|чо|чё|как|каки?[йяоеи]{1,2}|когда|где|куда|откуда|почему|"
    r"зачем|сколько|разве|неужели)"
    r"(?!\s*-?\s*(?:нибудь|то|либо))\b", re.IGNORECASE)


# «...или нет» в конце — вопрос почти всегда, даже без знака.
_ИЛИ_НЕТ = re.compile(r"или\s+нет\s*$", re.IGNORECASE)


def _вопрос_ли(текст):
    return bool("?" in текст or _ВОПРОС_СЛОВОМ.match(текст)
                or _ИЛИ_НЕТ.search(текст))


def _вопросы(сообщения):
    return _доля(sum(1 for с in сообщения if _вопрос_ли(с["текст"])),
                 len(сообщения))


def _эмоции(сообщения):
    живых = sum(1 for с in сообщения
                if _ЭМОДЗИ.search(с["текст"]) or _СМЕХ.search(с["текст"]))
    return _доля(живых, len(сообщения))


def _ночные(сообщения):
    сдатой = [с for с in сообщения if с["дата"]]
    ночью = sum(1 for с in сдатой
                if с["дата"].hour >= НОЧЬ_С or с["дата"].hour < НОЧЬ_ДО)
    return _доля(ночью, len(сдатой))


