def склонение(число, одно, два, много):
    """«1 разговор», «2 разговора», «5 разговоров» — иначе режет глаз."""
    хвост_сто = abs(число) % 100
    хвост = abs(число) % 10
    if 11 <= хвост_сто <= 14:
        return много
    if хвост == 1:
        return одно
    if 2 <= хвост <= 4:
        return два
    return много


def по_русски_время(секунды):
    if секунды is None:
        return "неизвестно"
    if секунды < 90:
        return "%d сек" % секунды
    if секунды < 5400:
        return "%d мин" % round(секунды / 60)
    if секунды < 86400:
        return "%.1f ч" % (секунды / 3600)
    return "%.1f сут" % (секунды / 86400)


def сейчас(результат):
    """Индекс за последнюю треть переписки — то есть как дела на сегодня.

    Отдельная функция, потому что общий индекс за всё время отвечает не на
    тот вопрос. Переписка, которая полгода была тёплой, а последний месяц
    еле дышит, в среднем выглядит прекрасно — и человек, пришедший понять,
    почему всё заглохло, услышал бы «она вовлечена». Ведём разговор от
    последнего куска, а историю показываем рядом.
    """
    тренд = результат.get("тренд")
    return тренд["конец"] if тренд else результат["индекс"]


def чей_ход(результат, сейчас_время=None):
    """Твоя ли очередь писать. Возвращает (чей ход, молчание в секундах).

    Смысл в одном: следующего сообщения не бывает, пока предыдущее не
    получило ответа. Если последнее слово твоё и она молчит не дольше,
    чем молчит обычно, — писать нечего, надо ждать. Это не вежливость,
    а арифметика: в переписке, из-за которой всё и затевалось, было 118
    его сообщений против 64 её.

    Порог — сутки, но не меньше трёх её обычных ответов: если она и так
    отвечает через день, то сутки молчания ещё ничего не значат.
    """
    последний = результат.get("последний") or {}
    if последний.get("кто") != "я":
        return ХОД_ТВОЙ, None

    когда = последний.get("когда")
    if not когда:
        # Вставка с телефона: дат нет, измерить молчание нечем. Держать
        # на этом основании нельзя — вставка и есть главный путь.
        return ХОД_НЕЯСЕН, None

    молчание = ((сейчас_время or datetime.now()) - когда).total_seconds()
    её_обычно = (результат.get("метрики") or {}).get("её_ответ_сек")
    порог = ПОРОГ_ДОБИВКИ.total_seconds()
    if её_обычно:
        порог = max(порог, её_обычно * ДОЛЕЙ_ОТ_ЕЁ_МЕДИАНЫ)
    return (ХОД_МОЖНО if молчание >= порог else ХОД_ЕЁ), max(молчание, 0)


def по_неделям(сообщения, я, она):
    """[(начало недели, индекс или None, сколько сообщений), …].

    Тренд из двух точек говорит «было 57, стало 42», но молчит о том,
    когда именно сломалось. Неделя — та единица, в которой люди и помнят
    свою переписку.

    Неделя без дат, без одной из сторон или короче МИНИМУМ_ЗА_НЕДЕЛЮ
    даёт None: провал в линии честнее точки, взятой из воздуха.
    """
    с_датой = [с for с in сообщения
               if с["дата"] and с["автор"] in (я, она)]
    if not с_датой:
        return []

    недели = {}
    for сообщение in с_датой:
        дата = сообщение["дата"]
        # Понедельник той недели: date.weekday() — 0 в понедельник.
        начало = (дата - timedelta(days=дата.weekday())).replace(
            hour=0, minute=0, second=0, microsecond=0)
        недели.setdefault(начало, []).append(сообщение)

    ряд = []
    for начало in sorted(недели):
        кусок = недели[начало]
        индекс = None
        if len(кусок) >= МИНИМУМ_ЗА_НЕДЕЛЮ and len({с["автор"] for с in кусок}) == 2:
            индекс = analyse(кусок, я, она, с_трендом=False)["индекс"]
        ряд.append((начало, индекс, len(кусок)))
    return ряд


def ступень(результат):
    """Насколько большой следующий шаг выдержит эта переписка."""
    индекс = сейчас(результат)
    if индекс is None or индекс < 30:
        return СТУПЕНЬ_МАЛАЯ
    if индекс < 55:
        return СТУПЕНЬ_СРЕДНЯЯ
    return СТУПЕНЬ_ПРЯМАЯ


def не_посчитано(результат):
    """Какие факторы посчитать не вышло и как они называются по-русски.

    Нужна для вставленного текста: там обычно нет дат, и половина шкалы
    отваливается. Вес отвалившихся расходится по остальным, так что индекс
    всё равно по стобалльной шкале, — но показать «61 из 100», умолчав,
    что считали по четырём факторам из восьми, значит соврать умолчанием.
    """
    посчитанные = {пункт["фактор"] for пункт in результат.get("разбивка", [])}
    return [(имя, ФАКТОРЫ[имя][3]) for имя in ФАКТОРЫ
            if имя not in посчитанные]


def словами(результат):
    """Короткий вывод про индекс — то, что бот скажет первой строкой."""
    индекс = сейчас(результат)
    if индекс is None:
        return "Данных слишком мало, чтобы что-то считать."
    if индекс >= 70:
        основа = "Она вовлечена: отвечает, спрашивает и сама начинает."
    elif индекс >= 50:
        основа = "Общение живое, но держится во многом на тебе."
    elif индекс >= 30:
        основа = "Интерес прохладный: отвечает, но навстречу не идёт."
    else:
        основа = "По переписке встречного интереса почти не видно."

    тренд = результат.get("тренд")
    if not тренд or abs(тренд["разница"]) < 8:
        return основа
    if тренд["разница"] > 0:
        return основа + " И становится теплее: было %d, стало %d." % (
            тренд["начало"], тренд["конец"])
    return основа + " Раньше было теплее — %d против нынешних %d." % (
        тренд["начало"], тренд["конец"])


