def склонение(число, одно, два, много):
    """«1 разговор», «2 разговора», «5 разговоров» — иначе режет глаз."""
    хвост_сто = abs(число) % 100
    хвост = abs(число) % 10
    if 11 <= хвост_сто <= 14:
        return много
    if хвост == 1:
        return одно
    if 2 <= хвост <= 4:
        return два
    return много


def по_русски_время(секунды):
    if секунды is None:
        return "неизвестно"
    if секунды < 90:
        return "%d сек" % секунды
    if секунды < 5400:
        return "%d мин" % round(секунды / 60)
    if секунды < 86400:
        return "%.1f ч" % (секунды / 3600)
    return "%.1f сут" % (секунды / 86400)


def сейчас(результат):
    """Индекс за последнюю треть переписки — то есть как дела на сегодня.

    Отдельная функция, потому что общий индекс за всё время отвечает не на
    тот вопрос. Переписка, которая полгода была тёплой, а последний месяц
    еле дышит, в среднем выглядит прекрасно — и человек, пришедший понять,
    почему всё заглохло, услышал бы «она вовлечена». Ведём разговор от
    последнего куска, а историю показываем рядом.
    """
    тренд = результат.get("тренд")
    return тренд["конец"] if тренд else результат["индекс"]


def не_посчитано(результат):
    """Какие факторы посчитать не вышло и как они называются по-русски.

    Нужна для вставленного текста: там обычно нет дат, и половина шкалы
    отваливается. Вес отвалившихся расходится по остальным, так что индекс
    всё равно по стобалльной шкале, — но показать «61 из 100», умолчав,
    что считали по четырём факторам из восьми, значит соврать умолчанием.
    """
    посчитанные = {пункт["фактор"] for пункт in результат.get("разбивка", [])}
    return [(имя, ФАКТОРЫ[имя][3]) for имя in ФАКТОРЫ
            if имя not in посчитанные]


def словами(результат):
    """Короткий вывод про индекс — то, что бот скажет первой строкой."""
    индекс = сейчас(результат)
    if индекс is None:
        return "Данных слишком мало, чтобы что-то считать."
    if индекс >= 70:
        основа = "Она вовлечена: отвечает, спрашивает и сама начинает."
    elif индекс >= 50:
        основа = "Общение живое, но держится во многом на тебе."
    elif индекс >= 30:
        основа = "Интерес прохладный: отвечает, но навстречу не идёт."
    else:
        основа = "По переписке встречного интереса почти не видно."

    тренд = результат.get("тренд")
    if not тренд or abs(тренд["разница"]) < 8:
        return основа
    if тренд["разница"] > 0:
        return основа + " И становится теплее: было %d, стало %d." % (
            тренд["начало"], тренд["конец"])
    return основа + " Раньше было теплее — %d против нынешних %d." % (
        тренд["начало"], тренд["конец"])


# Публичные имена для соседних модулей: разбору от ИИ нужны те же серии
# и разговоры, что считает индекс, — второй раз их резать незачем.
серии = _серии
разговоры = _разговоры
