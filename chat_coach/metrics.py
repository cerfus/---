# -*- coding: utf-8 -*-
"""
Метрики переписки и индекс интереса.

Всё здесь считается обычным питоном, без ИИ: быстро, бесплатно и, главное,
объяснимо — на каждый балл видно, откуда он взялся. Это принципиально:
показывать «интерес 47%» без разбивки — значит просить верить на слово.

Индекс — это статистика поведения в переписке, а не измерение чувств.
Так и говорим пользователю: цифра описывает, как идёт общение, и ничего
не знает про человека.

Главный ответ даёт не сам индекс, а тренд: «было 70, стало 40» полезнее
любого среза, потому что говорит, куда всё движется.
"""

import re
from datetime import timedelta
from statistics import median

# Переписка распадается на разговоры: если молчали дольше — это уже
# новый заход, а не долгий ответ.
ПАУЗА_МЕЖДУ_РАЗГОВОРАМИ = timedelta(hours=6)

# Дольше этого ответ ответом не считается: это возвращение к общению.
ПРЕДЕЛ_ОТВЕТА = timedelta(hours=48)

НОЧЬ_С, НОЧЬ_ДО = 23, 5

# Сколько наблюдений нужно фактору, чтобы его вообще считать.
#
# Без этого порога вставленный кусок переписки даёт чушь: дат в нём нет,
# значит вся переписка — один разговор, и «инициатива» с «обрывами»
# определяются одним наблюдением — кто случайно оказался первым и последним
# в скопированном. Сдвиг выделения на одно сообщение уводил индекс на
# одиннадцать баллов. Фактор, за которым стоит один случай, лучше не
# показывать вовсе: его вес разойдётся по тем, которые что-то знают.
МИНИМУМ_НАБЛЮДЕНИЙ = 3

_ЭМОДЗИ = re.compile(
    "[\U0001F300-\U0001FAFF\U00002600-\U000027BF\U0001F900-\U0001F9FF"
    "\U0001F1E6-\U0001F1FF❤♥☺]")
_СМЕХ = re.compile(r"(?:ах){2,}|(?:ха){2,}|хех|лол|ору|\){2,}", re.IGNORECASE)


# --------------------------------------------------------------------------
# Нарезка переписки
# --------------------------------------------------------------------------

def _серии(сообщения):
    """Подряд идущие сообщения одного человека — одна серия.

    В переписке думают не сообщениями, а репликами: три сообщения подряд —
    это одна реплика, и отвечать будут на неё целиком.
    """
    серии = []
    for сообщение in сообщения:
        if серии and серии[-1][0] == сообщение["автор"]:
            серии[-1][1].append(сообщение)
        else:
            серии.append((сообщение["автор"], [сообщение]))
    return серии


def _разговоры(сообщения):
    """Режет переписку на разговоры по длинной паузе."""
    разговоры, текущий = [], []
    for сообщение in сообщения:
        if текущий and сообщение["дата"] and текущий[-1]["дата"]:
            if сообщение["дата"] - текущий[-1]["дата"] > ПАУЗА_МЕЖДУ_РАЗГОВОРАМИ:
                разговоры.append(текущий)
                текущий = []
        текущий.append(сообщение)
    if текущий:
        разговоры.append(текущий)
    return разговоры


def _инициативы(разговоры):
    """Кто размораживает общение. Возвращает ({автор: сколько}, всего).

    Считать просто «кто написал первым в разговоре» нельзя: если человек
    отвечает через сутки, формально начинается новый разговор — и молчун
    получал бы очки за инициативу ровно за то, что тянул с ответом.
    Поэтому разговор, который открыт поздним ответом собеседника
    (в пределах 48 часов), в счёт не идёт вообще — ни одному, ни другому.
    """
    счёт, всего = {}, 0
    for номер, разговор in enumerate(разговоры):
        открыл = разговор[0]["автор"]
        if номер:
            прошлое = разговоры[номер - 1][-1]
            есть_даты = прошлое["дата"] and разговор[0]["дата"]
            пауза = (разговор[0]["дата"] - прошлое["дата"]) if есть_даты else None
            if (прошлое["автор"] != открыл and пауза is not None
                    and пауза <= ПРЕДЕЛ_ОТВЕТА):
                continue                # это поздний ответ, а не начало
        всего += 1
        счёт[открыл] = счёт.get(открыл, 0) + 1
    return счёт, всего


def _задержки(серии):
    """Сколько каждый думал перед ответом. {автор: [секунды, ...]}"""
    ответы = {}
    for номер in range(1, len(серии)):
        автор, реплика = серии[номер]
        _, предыдущая = серии[номер - 1]
        было, стало = предыдущая[-1]["дата"], реплика[0]["дата"]
        if not было or not стало:
            continue
        пауза = стало - было
        if timedelta(0) <= пауза <= ПРЕДЕЛ_ОТВЕТА:
            ответы.setdefault(автор, []).append(пауза.total_seconds())
    return ответы


# --------------------------------------------------------------------------
# Отдельные метрики
# --------------------------------------------------------------------------

def _доля(сколько, всего):
    return (сколько / всего) if всего else None


def _длина(сообщения):
    """Средняя длина написанного. Сообщения-вложения не в счёт:
    стикер не короткий ответ, он просто без букв."""
    буквы = [len(с["текст"]) for с in сообщения if с["текст"]]
    return (sum(буквы) / len(буквы)) if буквы else None


def _вопросы(сообщения):
    return _доля(sum(1 for с in сообщения if "?" in с["текст"]), len(сообщения))


def _эмоции(сообщения):
    живых = sum(1 for с in сообщения
                if _ЭМОДЗИ.search(с["текст"]) or _СМЕХ.search(с["текст"]))
    return _доля(живых, len(сообщения))


def _ночные(сообщения):
    сдатой = [с for с in сообщения if с["дата"]]
    ночью = sum(1 for с in сдатой
                if с["дата"].hour >= НОЧЬ_С or с["дата"].hour < НОЧЬ_ДО)
    return _доля(ночью, len(сдатой))


# --------------------------------------------------------------------------
# Индекс: веса и нормировка
# --------------------------------------------------------------------------

# фактор -> (вес, к чему нормируем, штраф ли это, как назвать словами)
ФАКТОРЫ = {
    "инициатива":  (20, 0.50, False, "кто первым начинает разговор"),
    "скорость":    (15, 1.00, False, "как быстро она отвечает"),
    "объём":       (15, 1.00, False, "насколько развёрнуто пишет"),
    "вопросы":     (15, 0.25, False, "сама ли расспрашивает"),
    "баланс":      (10, 0.50, False, "кто больше пишет"),
    "эмоции":      (10, 0.30, False, "живость: смех, эмодзи"),
    "обрывы":      (10, 0.40, True,  "разговоры, обрывающиеся на тебе"),
    "дубли":       (5,  0.40, True,  "твои сообщения подряд без ответа"),
}


def _балл(значение, норма, штраф):
    """Сырое число -> балл от 0 до 1."""
    if значение is None:
        return None
    доля = min(значение / норма, 1.0) if норма else 0.0
    return round(1.0 - доля if штраф else доля, 3)


def _собрать_индекс(сырые):
    """Складывает баллы с весами. Недоступные факторы не топят оценку:
    их вес распределяется между остальными, а не засчитывается нулём."""
    разбивка, вес_в_деле = [], 0
    for имя, (вес, норма, штраф, словами) in ФАКТОРЫ.items():
        балл = _балл(сырые.get(имя), норма, штраф)
        if балл is None:
            continue
        вес_в_деле += вес
        разбивка.append({"фактор": имя, "вес": вес, "балл": балл,
                         "вклад": round(вес * балл, 1), "словами": словами,
                         "значение": сырые.get(имя)})
    if not вес_в_деле:
        return None, разбивка
    набрано = sum(пункт["вклад"] for пункт in разбивка)
    # Пересчёт на сто: если часть факторов не посчиталась (в логе нет дат),
    # индекс всё равно по стобалльной шкале, а не «из скольких получилось».
    for пункт in разбивка:
        пункт["вклад"] = round(пункт["вклад"] * 100 / вес_в_деле, 1)
        # Потолок тоже растёт: если часть факторов выпала, их вес ушёл
        # оставшимся. Без этого в отчёте выходило «19 из 15».
        пункт["потолок"] = round(пункт["вес"] * 100 / вес_в_деле)
    return round(набрано * 100 / вес_в_деле), sorted(
        разбивка, key=lambda пункт: -пункт["вес"])


