# Сборка
# --------------------------------------------------------------------------

def _сырые_метрики(сообщения, я, она):
    мои = [с for с in сообщения if с["автор"] == я]
    её = [с for с in сообщения if с["автор"] == она]
    серии = _серии(сообщения)
    разговоры = _разговоры(сообщения)
    задержки = _задержки(серии)

    ответ_её = median(задержки[она]) if задержки.get(она) else None
    ответ_мой = median(задержки[я]) if задержки.get(я) else None
    длина_её, длина_моя = _длина(её), _длина(мои)

    начала, начал_кто_то = _инициативы(разговоры)
    начатых_ею = начала.get(она, 0)
    оборвалось_на_мне = sum(1 for разговор in разговоры
                            if разговор[-1]["автор"] == я)
    мои_серии = [реплика for автор, реплика in серии if автор == я]
    подряд = sum(1 for реплика in мои_серии if len(реплика) > 1)

    хватает_разговоров = len(разговоры) >= МИНИМУМ_НАБЛЮДЕНИЙ
    хватает_ответов = (len(задержки.get(она, [])) >= МИНИМУМ_НАБЛЮДЕНИЙ
                       and len(задержки.get(я, [])) >= МИНИМУМ_НАБЛЮДЕНИЙ)

    сырые = {
        "инициатива": (_доля(начатых_ею, начал_кто_то)
                       if начал_кто_то >= МИНИМУМ_НАБЛЮДЕНИЙ else None),
        # Быстрее меня — уже потолок: смысл не в гонке, а в том,
        # не держит ли она меня в ожидании дольше, чем я её.
        "скорость": (min(ответ_мой / ответ_её, 1.0)
                     if ответ_её and ответ_мой and хватает_ответов else None),
        "объём": (min(длина_её / длина_моя, 1.0)
                  if длина_её and длина_моя else None),
        "вопросы": _вопросы(её),
        "баланс": _доля(len(её), len(сообщения)),
        "эмоции": _эмоции(её),
        "обрывы": (_доля(оборвалось_на_мне, len(разговоры))
                   if хватает_разговоров else None),
        "дубли": (_доля(подряд, len(мои_серии))
                  if len(мои_серии) >= МИНИМУМ_НАБЛЮДЕНИЙ else None),
    }
    подробности = {
        "моих_сообщений": len(мои),
        "её_сообщений": len(её),
        "разговоров": len(разговоры),
        "начала_она": начатых_ею,
        "начал_кто_то": начал_кто_то,
        "оборвалось_на_мне": оборвалось_на_мне,
        "мой_ответ_сек": round(ответ_мой) if ответ_мой else None,
        "её_ответ_сек": round(ответ_её) if ответ_её else None,
        "моя_длина": round(длина_моя) if длина_моя else None,
        "её_длина": round(длина_её) if длина_её else None,
        "её_вопросы": сырые["вопросы"],
        "её_эмоции": сырые["эмоции"],
        "ночных": _ночные(сообщения),
        "моих_серий_подряд": подряд,
    }
    return сырые, подробности


def analyse(сообщения, я, она, с_трендом=True):
    """Считает метрики и индекс. Возвращает всё, что нужно отчёту и ИИ."""
    сообщения = [с for с in сообщения if с["автор"] in (я, она)]
    if not сообщения:
        raise ValueError("В переписке нет сообщений от указанных людей.")

    сырые, подробности = _сырые_метрики(сообщения, я, она)
    индекс, разбивка = _собрать_индекс(сырые)

    даты = [с["дата"] for с in сообщения if с["дата"]]
    тренд = None
    if с_трендом and len(сообщения) >= 30:
        треть = len(сообщения) // 3
        начало = analyse(сообщения[:треть], я, она, с_трендом=False)["индекс"]
        конец = analyse(сообщения[-треть:], я, она, с_трендом=False)["индекс"]
        if начало is not None and конец is not None:
            тренд = {"начало": начало, "конец": конец,
                     "разница": конец - начало}

    return {
        "я": я, "она": она,
        "всего": len(сообщения),
        "первое": min(даты) if даты else None,
        "последнее": max(даты) if даты else None,
        "дней": (max(даты) - min(даты)).days + 1 if даты else None,
        "метрики": подробности,
        "индекс": индекс,
        "разбивка": разбивка,
        "тренд": тренд,
    }


