# -*- coding: utf-8 -*-
"""
Разбор переписки моделью Claude.

Сюда уходит не весь чат, а выборка: посчитанные метрики, последние
сообщения и несколько показательных мест — там, где разговор обрывался,
и там, где он, наоборот, оживал. Так дешевле и, что важнее, безопаснее:
переписка принадлежит двоим, и второй согласия не давал.

Перед отправкой имена заменяются на «Ты» и «Она» — модели незачем знать,
как зовут людей, чтобы разобрать, какие фразы работают.

Разбираем сообщения пользователя, а не её. Она здесь не объект оценки:
её реплики — материал, по которому видно, как на неё действует написанное.
"""

import os
import re
from typing import List

from pydantic import BaseModel, Field

import metrics

МОДЕЛЬ = os.getenv("CHAT_COACH_MODEL", "claude-opus-5")

# Глубина рассуждений. Задача разговорная, а не олимпиадная: на medium
# качество держится, а расход токенов заметно ниже — при бесплатном тарифе
# это разница между работающим ботом и закончившимися деньгами.
# Поднять до high/xhigh — одна переменная окружения.
УСИЛИЕ = os.getenv("CHAT_COACH_EFFORT", "medium")

ПОСЛЕДНИХ = 40          # сколько свежих сообщений показать модели
ПРИМЕРОВ = 3            # сколько обрывов и сколько удачных мест

Я, ОНА = "Ты", "Она"


class ОшибкаРазбора(Exception):
    """Понятная человеку причина, почему разбор не состоялся."""


# --------------------------------------------------------------------------
# Обезличивание
# --------------------------------------------------------------------------

def _формы(имя):
    """Падежные формы имени — чтобы «Ане» и «Аню» тоже исчезли.

    Берём закрытый список окончаний, а не обрубок основы: по основе «Ан»
    под замену попало бы и «английский», и «Андрей».
    """
    формы = set()
    for кусок in re.split(r"[\s,]+", имя.strip()):
        if len(кусок) < 3:
            continue
        формы.add(кусок)
        if кусок[-1].lower() in "аяей":
            основа = кусок[:-1]
            формы.update(основа + окончание for окончание in
                         ("а", "я", "и", "е", "ю", "ы", "ой", "ей", "ою", "ею"))
        else:
            формы.update(кусок + окончание for окончание in
                         ("а", "у", "е", "ом", "ым", "ы"))
    return формы


def обезличить(текст, имена):
    """Убирает имена собеседников из текста сообщения."""
    if not текст:
        return текст
    формы = set()
    for имя, замена in имена.items():
        for форма in _формы(имя):
            формы.add((форма, замена))
    if not формы:
        return текст
    # Длинные формы первыми, иначе «Ан» съест начало «Аней».
    порядок = sorted(формы, key=lambda пара: -len(пара[0]))
    образец = re.compile(r"\b(%s)\b" % "|".join(re.escape(ф) for ф, _ in порядок),
                         re.IGNORECASE)
    замены = {форма.lower(): замена for форма, замена in порядок}
    return образец.sub(lambda сов: замены.get(сов.group(0).lower(), сов.group(0)),
                       текст)


# --------------------------------------------------------------------------
# Выборка: что именно показать модели
# --------------------------------------------------------------------------

def _строка(сообщение, я, она):
    кто = Я if сообщение["автор"] == я else ОНА
    когда = сообщение["дата"].strftime("%d.%m %H:%M") if сообщение["дата"] else "—"
    текст = обезличить(сообщение["текст"], {я: Я, она: ОНА})
    if not текст and сообщение["вложение"]:
        текст = "[вложение]"
    return "%s | %s: %s" % (когда, кто, текст)


def _обрывы(сообщения, я, она, сколько=ПРИМЕРОВ):
    """Мои реплики, после которых она замолчала дольше всего."""
    серии = metrics.серии(сообщения)
    найдено = []
    for номер, (автор, реплика) in enumerate(серии):
        if автор != я or not реплика[-1]["дата"]:
            continue
        следующая = серии[номер + 1][1][0] if номер + 1 < len(серии) else None
        if следующая is None or not следующая["дата"]:
            continue
        пауза = (следующая["дата"] - реплика[-1]["дата"]).total_seconds()
        if пауза >= metrics.ПАУЗА_МЕЖДУ_РАЗГОВОРАМИ.total_seconds():
            найдено.append((пауза, реплика))
    найдено.sort(key=lambda пара: -пара[0])
    return [(пауза, [_строка(с, я, она) for с in реплика])
            for пауза, реплика in найдено[:сколько]]


def _удачные(сообщения, я, она, сколько=ПРИМЕРОВ):
    """Мои реплики, после которых она ответила быстро и развёрнуто."""
    серии = metrics.серии(сообщения)
    её_длина = metrics._длина([с for с in сообщения if с["автор"] == она]) or 0
    найдено = []
    for номер, (автор, реплика) in enumerate(серии):
        if автор != я or номер + 1 >= len(серии) or not реплика[-1]["дата"]:
            continue
        ответ = серии[номер + 1][1]
        if серии[номер + 1][0] != она or not ответ[0]["дата"]:
            continue
        пауза = (ответ[0]["дата"] - реплика[-1]["дата"]).total_seconds()
        длина = sum(len(с["текст"]) for с in ответ)
        if пауза <= 900 and длина > её_длина:
            найдено.append((длина / (пауза + 60), реплика, ответ))
    найдено.sort(key=lambda тройка: -тройка[0])
    return [[_строка(с, я, она) for с in реплика + ответ]
            for _вес, реплика, ответ in найдено[:сколько]]


def выборка(сообщения, я, она):
    """Всё, что увидит модель, кроме цифр."""
    return {
        "последние": [_строка(с, я, она) for с in сообщения[-ПОСЛЕДНИХ:]],
        "обрывы": _обрывы(сообщения, я, она),
        "удачные": _удачные(сообщения, я, она),
    }


