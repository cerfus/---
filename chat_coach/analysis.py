def текст_разбора(разбор):
    """Разбор в том виде, в каком его увидят в консоли и в боте."""
    if разбор.стоп_сигнал:
        return "\n".join([
            "СТОП.",
            разбор.стоп_причина or разбор.коротко,
            "",
            "Здесь нет смысла искать подход: человек уже ответил. "
            "Лучшее, что можно сделать, — оставить в покое.",
        ])

    строки = [разбор.коротко]
    if разбор.что_работает:
        строки += ["", "Что у тебя работает:"]
        строки += ["  + " + пункт for пункт in разбор.что_работает]
    if разбор.что_мешает:
        строки += ["", "Что мешает:"]
        for совет in разбор.что_мешает:
            строки.append("  — %s" % совет.что_не_так)
            if совет.цитата:
                строки.append("    было:  «%s»" % совет.цитата)
            if совет.как_лучше:
                строки.append("    лучше: «%s»" % совет.как_лучше)
    if разбор.следующий_шаг:
        строки += ["", "Следующий шаг: " + разбор.следующий_шаг]
    return "\n".join(строки)
