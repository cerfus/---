def _клиент():
    try:
        import anthropic
    except ImportError:
        raise ОшибкаРазбора("Библиотека anthropic не установлена: "
                            "pip install -r requirements.txt")
    if not (os.getenv("ANTHROPIC_API_KEY") or os.getenv("ANTHROPIC_AUTH_TOKEN")):
        raise ОшибкаРазбора("Не задан ANTHROPIC_API_KEY.")
    return anthropic.Anthropic()


def _по_русски_ошибку(исключение):
    """Переводит сбой API в то, что не стыдно показать человеку."""
    import anthropic
    if isinstance(исключение, anthropic.RateLimitError):
        return "Сейчас слишком много запросов. Попробуй через минуту."
    if isinstance(исключение, anthropic.APIConnectionError):
        return "Не смог достучаться до модели. Попробуй ещё раз."
    if isinstance(исключение, anthropic.APIStatusError):
        return "Модель ответила ошибкой (%s). Попробуй позже." % исключение.status_code
    return "Разбор не получился. Попробуй ещё раз."


def _системный_блок():
    # Кэшируем системную часть: при коротких вопросах по той же переписке
    # префикс не меняется, и повторные обращения обходятся дешевле.
    return [{"type": "text", "text": СИСТЕМА,
             "cache_control": {"type": "ephemeral"}}]


def разобрать(сообщения, итог, цель, клиент=None, отобранное=None, рамка=None):
    """Главная функция: отдаёт Разбор или бросает ОшибкаРазбора.

    Готовую выборку можно передать снаружи — тогда бот держит в памяти
    только её, уже обезличенную, а сам чат забывает сразу после разбора.
    """
    клиент = клиент or _клиент()
    if отобранное is None:
        отобранное = выборка(сообщения, итог["я"], итог["она"])
    запрос = собрать_запрос(итог, отобранное, цель, рамка)

    настройки = {"effort": УСИЛИЕ} if УСИЛИЕ else {}
    try:
        ответ = клиент.messages.parse(
            model=МОДЕЛЬ,
            max_tokens=16000,
            system=_системный_блок(),
            messages=[{"role": "user", "content": запрос}],
            thinking={"type": "adaptive"},
            output_config=настройки,
            output_format=Разбор,
        )
    except Exception as сбой:                     # noqa: BLE001
        raise ОшибкаРазбора(_по_русски_ошибку(сбой)) from сбой

    # Модель может отказаться отвечать — это штатный ответ, а не поломка.
    if getattr(ответ, "stop_reason", None) == "refusal":
        raise ОшибкаРазбора(
            "Модель не стала разбирать эту переписку. Так бывает, если "
            "в ней есть что-то, чего разбор не касается.")
    разбор = getattr(ответ, "parsed_output", None)
    if разбор is None:
        raise ОшибкаРазбора("Модель ответила не по форме. Попробуй ещё раз.")
    return разбор


def спросить(итог, отобранное, вопрос, клиент=None, рамка=None):
    """Короткий вопрос по уже разобранной переписке. Возвращает текст.

    Работает по сохранённой выборке, а не по переписке: к моменту вопроса
    исходный чат уже забыт, и это не ограничение, а так и задумано.
    """
    клиент = клиент or _клиент()
    основа = собрать_запрос(итог, отобранное, "ответить на вопрос ниже", рамка)
    try:
        ответ = клиент.messages.create(
            model=МОДЕЛЬ,
            max_tokens=2000,
            system=_системный_блок(),
            messages=[{"role": "user",
                       "content": основа + "\n\nВОПРОС: " + вопрос
                       + "\n\nОтветь коротко, в пределах пяти предложений."}],
            thinking={"type": "adaptive"},
            cache_control={"type": "ephemeral"},
        )
    except Exception as сбой:                     # noqa: BLE001
        raise ОшибкаРазбора(_по_русски_ошибку(сбой)) from сбой

    if getattr(ответ, "stop_reason", None) == "refusal":
        raise ОшибкаРазбора("На этот вопрос модель отвечать не стала.")
    куски = [блок.text for блок in ответ.content if блок.type == "text"]
    текст = "\n".join(куски).strip()
    if not текст:
        raise ОшибкаРазбора("Пустой ответ. Попробуй переспросить иначе.")
    return текст


ЗАДАЧА_ПОДСКАЗКИ = """\

ЧТО НУЖНО: готовое следующее сообщение — он сидит с пустым полем ввода.
- Цель: %(цель)s.
- Размер шага, который выдержит эта переписка: %(ступень)s.
  Цель от этого не меняется, меняется размер следующего шага к ней. \
Не перепрыгивай ступень, даже если цель просит большего.
- Ход: %(ход)s.

Дай две-три готовые версии — такие, чтобы можно было отправить как есть, \
не дописывая. Они должны звучать как он сам: длина и манера те же, что \
в его сообщениях выше. Если в сообщении нужно её имя — пиши {имя}, вместо \
него встанет настоящее.

В «почему» объясни выбор одной-двумя фразами и опирайся на переписку, \
а не на общие соображения. В «чего_не_писать» назови то, что сейчас \
испортит дело именно в этой переписке.

Если выбранная цель к этой переписке не подходит — поставь \
цель_не_та=true и скажи, что имеет смысл вместо неё. Никаких приёмов: \
ни давления, ни вины, ни многозначительных исчезновений.
"""

ЗАДАЧА_ЧЕРНОВИКА = """\

ЧЕРНОВИК, КОТОРЫЙ ОН СОБИРАЕТСЯ ОТПРАВИТЬ:
%s

Имя собеседницы в черновике заменено на {имя} — сохрани эту подстановку \
в своих вариантах, вместо неё встанет настоящее имя.

Скажи, как это сообщение прочитается с её стороны, что в нём может \
оттолкнуть, и дай две-три готовые версии получше — такие, чтобы их можно \
было отправить как есть, не дописывая. Версии должны звучать как он сам, \
а не как письмо из книжки: длина и манера те же, что в его сообщениях выше.

Если отправлять это не стоит вовсе — поставь не_отправлять=true и скажи \
почему. Не превращай черновик в приём: ни давления, ни вины, ни \
многозначительных исчезновений.
"""


def черновик(итог, отобранное, текст, рамка=None, клиент=None):
    """Проверка одного сообщения перед отправкой. Отдаёт Черновик.

    Разбор целой переписки делают раз в неделю, а это — каждый день,
    и стоит оно копейки: системная часть промпта та же, что у разбора,
    значит кэш попадает и платить приходится только за хвост.
    """
    if frame.стоп(рамка):
        # Тот же запрет, что и в разборе, только дешевле: к модели не идём
        # вовсе. Полировать сообщение к человеку, который уже ответил, —
        # это и есть «помочь обойти отказ», как его ни назови.
        return Черновик(
            как_сядет="", риск="", варианты=[], не_отправлять=True,
            почему_не="В переписке уже прозвучал отказ. Дело не в словах "
                      "этого сообщения, и переписывать их смысла нет.")

    имя = итог["она"]
    спрятанный, формы = спрятать_имя(текст, имя)
    спрятанный = обезличить(спрятанный, {итог["я"]: Я})

    клиент = клиент or _клиент()
    запрос = (собрать_запрос(итог, отобранное, "проверить черновик", рамка)
              + ЗАДАЧА_ЧЕРНОВИКА % спрятанный)
    настройки = {"effort": УСИЛИЕ} if УСИЛИЕ else {}
    try:
        ответ = клиент.messages.parse(
            model=МОДЕЛЬ,
            max_tokens=4000,
            system=_системный_блок(),
            messages=[{"role": "user", "content": запрос}],
            thinking={"type": "adaptive"},
            output_config=настройки,
            output_format=Черновик,
        )
    except Exception as сбой:                     # noqa: BLE001
        raise ОшибкаРазбора(_по_русски_ошибку(сбой)) from сбой

    if getattr(ответ, "stop_reason", None) == "refusal":
        raise ОшибкаРазбора("Модель не стала разбирать этот черновик.")
    разбор = getattr(ответ, "parsed_output", None)
    if разбор is None:
        raise ОшибкаРазбора("Модель ответила не по форме. Попробуй ещё раз.")

    # Имя возвращается здесь, а не при показе: наружу должен выходить
    # готовый к отправке текст, и звать вернуть_имя в каждом месте показа —
    # верный способ однажды забыть.
    разбор.как_сядет = вернуть_имя(разбор.как_сядет, формы, имя)
    разбор.риск = вернуть_имя(разбор.риск, формы, имя)
    разбор.варианты = [вернуть_имя(вариант, формы, имя)
                       for вариант in разбор.варианты]
    return разбор


def подсказка(итог, отобранное, цель, ступень=None, ход=None, рамка=None,
              клиент=None):
    """Готовое следующее сообщение под выбранную цель. Отдаёт Подсказку.

    Ступень и ход считаются сами, если их не передали: вызывающему легко
    забыть, а забытая ступень — это ровно то, ради чего всё затевалось.
    Правку ступени по рамке делаем здесь же, в одном месте.
    """
    if frame.стоп(рамка):
        # Тот же запрет, что в разборе и черновике. Подсказать следующее
        # сообщение человеку, который уже получил «нет», — это и есть
        # помочь обойти отказ, как его ни назови.
        return Подсказка(
            варианты=[], почему="", чего_не_писать="", цель_не_та=True,
            почему_не_та="В переписке уже прозвучал отказ. Следующего "
                         "сообщения здесь нет — и это ответ, а не отговорка.")

    ступень = frame.поправить_ступень(рамка, ступень or metrics.ступень(итог))
    ход = ход or metrics.чей_ход(итог)[0]

    клиент = клиент or _клиент()
    запрос = (собрать_запрос(итог, отобранное, цель, рамка)
              + ЗАДАЧА_ПОДСКАЗКИ % {"цель": цель,
                                    "ступень": metrics.СТУПЕНИ[ступень],
                                    "ход": metrics.ХОДЫ[ход]})
    настройки = {"effort": УСИЛИЕ} if УСИЛИЕ else {}
    try:
        ответ = клиент.messages.parse(
            model=МОДЕЛЬ,
            max_tokens=4000,
            system=_системный_блок(),
            messages=[{"role": "user", "content": запрос}],
            thinking={"type": "adaptive"},
            output_config=настройки,
            output_format=Подсказка,
        )
    except Exception as сбой:                     # noqa: BLE001
        raise ОшибкаРазбора(_по_русски_ошибку(сбой)) from сбой

    if getattr(ответ, "stop_reason", None) == "refusal":
        raise ОшибкаРазбора("Модель не стала подсказывать по этой переписке.")
    готовое = getattr(ответ, "parsed_output", None)
    if готовое is None:
        raise ОшибкаРазбора("Модель ответила не по форме. Попробуй ещё раз.")

    # Имя возвращается здесь: наружу должен выходить текст, готовый
    # к отправке. Входного черновика нет, форм нет — встаёт именительный,
    # а в обращении он и нужен: «Привет, Аня».
    имя = итог["она"]
    готовое.варианты = [вернуть_имя(вариант, [], имя)
                        for вариант in готовое.варианты]
    готовое.почему = вернуть_имя(готовое.почему, [], имя)
    готовое.чего_не_писать = вернуть_имя(готовое.чего_не_писать, [], имя)
    return готовое


