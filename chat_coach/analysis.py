СИСТЕМА = """\
Ты разбираешь переписку и помогаешь человеку общаться лучше. Пишешь \
по-русски, спокойно, без пафоса и без обращения «дружище».

Тебе дают статистику переписки и выборку сообщений. «Ты» — это человек, \
которому ты отвечаешь. «Она» — его собеседница. Имена убраны намеренно.

Что делать:
- Разбирай ЕГО сообщения: где передавил, где было скучно, где сам закрыл \
тему. Её реплики — материал для выводов, а не предмет оценки.
- Опирайся на цитаты из выборки. Ничего не выдумывай: если в переписке \
чего-то нет, значит, этого нет.
- Говори прямо. Если встречного интереса не видно — так и скажи. Утешать \
неправдой хуже, чем сказать неприятное: человек пришёл за ясностью.
- Советы давай конкретные и выполнимые сегодня. Не «будь увереннее», \
а «вместо трёх сообщений подряд напиши одно и дождись ответа».
- В «как_лучше» пиши готовую фразу, которую можно отправить, а не описание.

Чего не делай никогда:
- Никаких приёмов давления: игры на чувстве вины, нарочитых исчезновений \
«для интереса», навязчивости, обесценивания, притворства.
- Если в переписке виден отказ, просьба не писать или прямо сказанное \
«не хочу общаться» — поставь стоп_сигнал=true, спокойно объясни это \
в стоп_причина и не давай никаких тактик. Отказ уважают, а не обходят.
- Не делай выводов о её чувствах, характере, отношениях или мотивах: \
у тебя есть только текст переписки, и этого мало, чтобы судить о человеке.
- Не оценивай внешность и не обсуждай ничего, кроме самого общения.
"""


class Совет(BaseModel):
    что_не_так: str = Field(description="Коротко: какая привычка в переписке мешает")
    цитата: str = Field(description="Его собственная фраза из выборки, где это видно")
    как_лучше: str = Field(description="Готовая фраза на замену, которую можно отправить")


class Разбор(BaseModel):
    коротко: str = Field(description="Вердикт в два-три предложения, без вступлений")
    что_работает: List[str] = Field(description="Его удачные ходы, 1-3 пункта")
    что_мешает: List[Совет] = Field(description="Что исправить, 1-3 пункта")
    следующий_шаг: str = Field(description="Одно конкретное действие на ближайшие дни")
    стоп_сигнал: bool = Field(description="True, если виден отказ или просьба не писать")
    стоп_причина: str = Field(description="Если стоп_сигнал — что именно на это указывает")


def собрать_запрос(итог, отобранное, цель):
    """Текст пользовательского сообщения к модели."""
    м = итог["метрики"]
    вр = metrics.по_русски_время
    куски = ["ЦЕЛЬ ЧЕЛОВЕКА: %s" % цель, "", "СТАТИСТИКА ПЕРЕПИСКИ:"]
    куски.append("- всего сообщений: %d (его %d, её %d), за %s дней"
                 % (итог["всего"], м["моих_сообщений"], м["её_сообщений"],
                    итог["дней"] or "?"))
    куски.append("- индекс вовлечённости: %s из 100 за всё время, %s сейчас"
                 % (итог["индекс"], metrics.сейчас(итог)))
    if итог["тренд"]:
        куски.append("- динамика: было %d, стало %d"
                     % (итог["тренд"]["начало"], итог["тренд"]["конец"]))
    куски.append("- разговоров: %d, из них начала она %d из %d засчитанных"
                 % (м["разговоров"], м["начала_она"], м["начал_кто_то"]))
    куски.append("- отвечает: она за %s, он за %s"
                 % (вр(м["её_ответ_сек"]), вр(м["мой_ответ_сек"])))
    куски.append("- средняя длина сообщения: у неё %s, у него %s"
                 % (м["её_длина"] or "?", м["моя_длина"] or "?"))
    куски.append("- разговоров, оборвавшихся на его сообщении: %d из %d"
                 % (м["оборвалось_на_мне"], м["разговоров"]))
    куски.append("- он писал по нескольку сообщений подряд без ответа: %d раз"
                 % м["моих_серий_подряд"])

    if отобранное["обрывы"]:
        куски += ["", "ГДЕ РАЗГОВОР ОБРЫВАЛСЯ (после этих его реплик она молчала дольше всего):"]
        for пауза, строки in отобранное["обрывы"]:
            куски.append("  --- дальше тишина %s ---" % вр(пауза))
            куски += ["  " + строка for строка in строки]

    if отобранное["удачные"]:
        куски += ["", "ГДЕ РАЗГОВОР ОЖИВАЛ (он написал — она ответила быстро и подробно):"]
        for строки in отобранное["удачные"]:
            куски.append("  ---")
            куски += ["  " + строка for строка in строки]

    куски += ["", "ПОСЛЕДНИЕ СООБЩЕНИЯ:"]
    куски += ["  " + строка for строка in отобранное["последние"]]
    return "\n".join(куски)


# --------------------------------------------------------------------------
# Вызов модели
