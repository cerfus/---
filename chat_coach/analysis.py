def текст_подсказки(готовое):
    """Подсказку — в том виде, в каком её увидят в боте."""
    строки = []
    if готовое.цель_не_та:
        строки += ["Цель к этой переписке не подходит.", готовое.почему_не_та]
        if not готовое.варианты:
            return "\n".join(строки)
        строки.append("")

    if готовое.варианты:
        строки.append("Можно отправить так:")
        for номер, вариант in enumerate(готовое.варианты, 1):
            строки.append("%d. %s" % (номер, вариант))
    if готовое.почему:
        строки += ["", "Почему так: " + готовое.почему]
    if готовое.чего_не_писать:
        строки += ["", "Чего сейчас не писать: " + готовое.чего_не_писать]
    return "\n".join(строки)


def текст_черновика(разбор):
    """Проверенный черновик в том виде, в каком его увидят."""
    if разбор.не_отправлять:
        return "\n".join(["Это лучше не отправлять.", разбор.почему_не])
    строки = [разбор.как_сядет]
    if разбор.риск:
        строки += ["", "Что может оттолкнуть: " + разбор.риск]
    if разбор.варианты:
        строки += ["", "Можно отправить так:"]
        for номер, вариант in enumerate(разбор.варианты, 1):
            строки.append("%d. %s" % (номер, вариант))
    return "\n".join(строки)


def текст_разбора(разбор):
    """Разбор в том виде, в каком его увидят в консоли и в боте."""
    if разбор.стоп_сигнал:
        return "\n".join([
            "СТОП.",
            разбор.стоп_причина or разбор.коротко,
            "",
            "Здесь нет смысла искать подход: человек уже ответил. "
            "Лучшее, что можно сделать, — оставить в покое.",
        ])

    строки = [разбор.коротко]
    if разбор.что_работает:
        строки += ["", "Что у тебя работает:"]
        строки += ["  + " + пункт for пункт in разбор.что_работает]
    if разбор.что_мешает:
        строки += ["", "Что мешает:"]
        for совет in разбор.что_мешает:
            строки.append("  — %s" % совет.что_не_так)
            if совет.цитата:
                строки.append("    было:  «%s»" % совет.цитата)
            if совет.как_лучше:
                строки.append("    лучше: «%s»" % совет.как_лучше)
    if разбор.следующий_шаг:
        строки += ["", "Следующий шаг: " + разбор.следующий_шаг]
    return "\n".join(строки)
