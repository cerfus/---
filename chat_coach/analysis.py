def _формы(имя):
    """Падежные формы имени — чтобы «Ане» и «Аню» тоже исчезли.

    Берём закрытый список окончаний, а не обрубок основы: по основе «Ан»
    под замену попало бы и «английский», и «Андрей».
    """
    формы = set()
    for кусок in re.split(r"[\s,]+", имя.strip()):
        if len(кусок) < 3:
            continue
        формы.add(кусок)
        if кусок[-1].lower() in "аяей":
            основа = кусок[:-1]
            формы.update(основа + окончание for окончание in
                         ("а", "я", "и", "е", "ю", "ы", "ой", "ей", "ою", "ею"))
        else:
            формы.update(кусок + окончание for окончание in
                         ("а", "у", "е", "ом", "ым", "ы"))
    return формы


МЕТКА_ИМЕНИ = "{имя}"


def спрятать_имя(текст, имя):
    """Имя собеседницы в черновике заменяет на {имя}.

    Обычное обезличивание тут не годится. Оно ставит «Она» — и модель
    возвращает готовое к отправке «Привет, Она». Правило «в модель не
    уходит ни одного имени» остаётся в силе, но метка должна быть такой,
    чтобы имя потом встало обратно.

    Возвращает (текст с метками, список исходных форм по порядку) —
    формы нужны, чтобы вернулось «Аню», а не «Аня».
    """
    if not текст or not имя:
        return текст, []
    формы = sorted(_формы(имя), key=len, reverse=True)
    if not формы:
        return текст, []
    образец = re.compile(r"\b(%s)\b" % "|".join(re.escape(ф) for ф in формы),
                         re.IGNORECASE)
    найденные = []

    def заменить(совпадение):
        найденные.append(совпадение.group(0))
        return МЕТКА_ИМЕНИ

    return образец.sub(заменить, текст), найденные


def вернуть_имя(текст, формы, имя):
    """Ставит имя обратно вместо меток — по очереди, как оно и стояло.

    Каждый вариант ответа — переписанный тот же черновик, поэтому очередь
    форм для каждого начинается заново. Если модель вставила метку там,
    где в черновике имени не было, подставляем имя как есть.
    """
    if not текст or МЕТКА_ИМЕНИ not in текст:
        return текст
    очередь = list(формы)
    куски = текст.split(МЕТКА_ИМЕНИ)
    собранное = куски[0]
    for кусок in куски[1:]:
        собранное += (очередь.pop(0) if очередь else имя) + кусок
    return собранное


def обезличить(текст, имена):
    """Убирает имена собеседников из текста сообщения."""
    if not текст:
        return текст
    формы = set()
    for имя, замена in имена.items():
        for форма in _формы(имя):
            формы.add((форма, замена))
    if not формы:
        return текст
    # Длинные формы первыми, иначе «Ан» съест начало «Аней».
    порядок = sorted(формы, key=lambda пара: -len(пара[0]))
    образец = re.compile(r"\b(%s)\b" % "|".join(re.escape(ф) for ф, _ in порядок),
                         re.IGNORECASE)
    замены = {форма.lower(): замена for форма, замена in порядок}
    return образец.sub(lambda сов: замены.get(сов.group(0).lower(), сов.group(0)),
                       текст)


